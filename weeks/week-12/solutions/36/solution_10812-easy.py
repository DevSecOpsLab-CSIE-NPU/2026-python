# ============================================================
# UVA 10812 - Beat the Spread! (簡單版本)
# 
# 【題目核心】
# 超級盃中有人押注分數之和 S，有人押注分差 D（絕對值）
# 給定 S 和 D，求兩隊的得分
# 
# 【數學推導】
# 設高分隊為 H，低分隊為 L
# 由題知：
#   H + L = S ... (1)  分數之和
#   H - L = D ... (2)  分差（H > L）
# 
# 聯立上述兩式：
#   (1) + (2)：2H = S + D  →  H = (S + D) / 2
#   (1) - (2)：2L = S - D  →  L = (S - D) / 2
# 
# 【驗證條件】
# 1. S + D 必須是偶數（否則 H 不是整數）
# 2. S - D 必須是偶數（否則 L 不是整數）
# 3. L >= 0（低分不能為負數）
# 如果上述任一條件不符，輸出 "impossible"
# ============================================================

# 讀取測試資料組數
n = int(input())

# 逐組處理測試資料
for _ in range(n):
    # 讀取分數之和 s 和分差 d
    s, d = map(int, input().split())
    
    # 【檢查 1】s + d 是否為偶數
    # 【檢查 2】s - d 是否為偶數
    if (s + d) % 2 != 0 or (s - d) % 2 != 0:
        print("impossible")
        continue
    
    # 計算高分隊和低分隊的分數
    h = (s + d) // 2
    l = (s - d) // 2
    
    # 【檢查 3】低分隊分數是否為負
    # 若低分 < 0 則無解，否則輸出高分和低分
    print("impossible" if l < 0 else f"{h} {l}")
