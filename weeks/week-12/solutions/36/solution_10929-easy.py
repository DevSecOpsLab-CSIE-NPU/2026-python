# ============================================================
# UVA 10929 - Multiple of 11 (簡單版本)
# 
# 【題目核心】
# 判斷大整數（最多 1000 位）是否為 11 的倍數
# 
# 【判斷技巧】11 的倍數判別方法
# 從右到左，按位置編號：1, 2, 3, 4, 5, ...
# 計算：(奇數位數字和) - (偶數位數字和)
# 若結果能被 11 整除，則原數能被 11 整除
# 
# 【示例】判別 12345:
#   位置：5  4  3  2  1
#   數字：1  2  3  4  5
#   奇數位（1,3,5）：5 + 3 + 1 = 9
#   偶數位（2,4）：  4 + 2 = 6
#   差值：9 - 6 = 3
#   3 % 11 != 0 → 12345 不是 11 的倍數
# 
# 【優點】
# - 可處理任意位數的整數
# - 算法簡單，時間複雜度 O(n) 其中 n 為位數
# ============================================================

# 無限循環，直到遇到 0
while True:
    # 讀取一行輸入（移除多餘空白）
    n = input().strip()
    
    # 輸入為 0 時結束程式
    if n == "0":
        break
    
    # 初始化總和
    total = 0
    
    # 【核心算法】從右到左遍歷每個數字
    # enumerate(reversed(n)) 給出 (索引, 數字)
    # 索引 0 對應最右邊的數字（位置 1）
    for i, d in enumerate(reversed(n)):
        digit_value = int(d)
        
        # 【位置判斷】
        # i % 2 == 0 → 奇數位（位置 1, 3, 5, ...）加上
        # i % 2 == 1 → 偶數位（位置 2, 4, 6, ...）減去
        if i % 2 == 0:
            total += digit_value
        else:
            total -= digit_value
    
    # 【最終判斷】
    # 檢查 (奇偶位差) % 11 是否為 0
    if total % 11 == 0:
        print(f"{n} is a multiple of 11.")
    else:
        print(f"{n} is not a multiple of 11.")
