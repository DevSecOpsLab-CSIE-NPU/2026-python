# ============================================================
# UVA 10931 - Parity (簡單版本)
# 
# 【題目核心】
# 「奇偶性（Parity）」定義為二進位表示中 1 的個數
# 
# 【演算法步驟】
# 1. 將十進位數轉換為二進位表示（不包含前導零）
# 2. 計算二進位中 1 的個數
# 3. 按指定格式輸出
# 
# 【示例】
# 輸入 21：
#   轉換為二進位：21 = 10101(二進位)
#   計算 1 的個數：3 個
#   輸出：The parity of 10101 is 3 (mod 2).
# 
# 【Python 技巧】
# - bin(n) 返回 '0b...' 格式，需要 [2:] 移除前綴
# - str.count('1') 直接計算 1 的個數
# ============================================================

# 無限循環，直到遇到 0
while True:
    # 讀取一個整數
    i = int(input())
    
    # 輸入為 0 時終止程式
    if i == 0:
        break
    
    # 【轉換為二進位】
    # bin(i) 返回 '0b...' 格式，[2:] 移除 '0b' 前綴
    # 例如：bin(21) = '0b10101'，bin(21)[2:] = '10101'
    binary = bin(i)[2:]
    
    # 【計算奇偶性】
    # 統計二進位字符串中 '1' 的個數
    parity = binary.count('1')
    
    # 【輸出結果】
    # 格式：The parity of {binary} is {parity} (mod 2).
    print(f"The parity of {binary} is {parity} (mod 2).")
