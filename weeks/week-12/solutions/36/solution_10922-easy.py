# UVA 10922 - 2 the 9s (簡單版本)
# 
# 【題目核心】
# 一個數是否為 9 的倍數可通過判斷其各位數字和是否為 9 的倍數
# 「9 的深度」定義為將一個數不斷進行「數字求和」操作，
# 直到結果變成個位數（0-9）時，所需操作的次數
# 
# 【演算法】
# 1. 計算輸入數字的各位數字和
# 2. 若結果 >= 10，繼續計算其數字和，並增加深度計數
# 3. 重複直到結果 < 10
# 4. 若最終結果為 9，則是 9 的倍數
# 
# 【示例】
# 輸入 999：
#   第1次：9+9+9 = 27 (深度1)
#   第2次：2+7 = 9 (深度2)
#   最終：9 → 輸出 "9-degree of 999 is 2."
# ============================================================

# 無限循環，直到遇到 0
while True:
    # 讀取一行輸入
    n = input().strip()
    
    # 輸入為 0 時結束
    if n == "0":
        break
    
    # 初始化深度計數器
    depth = 0
    
    # 初始化當前值為輸入數各位數字和
    current = sum(int(d) for d in n)
    
    # 【主工作迴圈】計算數字和直到變成個位數
    while current >= 10:
        # 當前值仍有多位數，增加深度
        depth += 1
        
        # 計算當前值的數字和
        current = sum(int(d) for d in str(current))
    
    # 【結果判斷】
    # 若最終得到 9，則是 9 的倍數，輸出深度
    # 否則不是 9 的倍數
    if current == 9:
        print(f"9-degree of {n} is {depth + 1}.")
    else:
        print(f"{n} is not a multiple of 9.")
