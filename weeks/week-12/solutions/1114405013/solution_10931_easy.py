'''
UVA 10931 — Parity（好記版）
============================
題目要求：
  給一個整數 I，輸出它的二進位表示 B，以及 B 裡面有幾個 1（記為 P）。

輸出格式：
  The parity of B is P (mod 2).

解題三步驟（一句話記法）：
  「轉二進位 → 去掉 '0b' → 數有幾個 '1'」

用到的 Python 內建函式：
  • bin(n)  — 將整數 n 轉成二進位字串，格式為 "0b1010"
  • str.count('1') — 計算字串中 '1' 出現的次數

完整繁體中文逐行說明
'''

def solve(in_stream, out_stream):
    """
    參數：
      in_stream  — 輸入串流（例：sys.stdin），每行一個整數 I
      out_stream — 輸出串流（例：sys.stdout）

    流程：
      ① 讀取整數（範圍 1 ~ 2³¹−1，Python int 可直接儲存）
      ② 遇到 "0" 結束
      ③ 用 bin() 轉二進位，去掉 "0b" 前綴
      ④ 用 count('1') 數有幾個 1
      ⑤ 按題目格式輸出
    """

    # ===================== 主迴圈：讀取直到遇到 "0" =====================
    while True:
        # 讀取一行並去除前後空白／換行
        s = in_stream.readline().strip()

        # 題目規定輸入 "0" 時結束
        if s == '0':
            break

        # ===================== 步驟 1：字串轉整數 ======================
        # 題目範圍 1 ≤ I ≤ 2147483647，Python 的 int 無上限，直接轉即可
        n = int(s)

        # ===================== 步驟 2：轉成二進位 ======================
        # bin(n) 回傳 "0b1010" 這樣的字串
        # 我們只要 "1010" 的部分，所以從索引 2 開始切片
        #
        # 範例：
        #   bin(1)   → "0b1"     → [2:] → "1"
        #   bin(2)   → "0b10"    → [2:] → "10"
        #   bin(10)  → "0b1010"  → [2:] → "1010"
        #   bin(21)  → "0b10101" → [2:] → "10101"
        b = bin(n)[2:]

        # ===================== 步驟 3：數 1 的個數 ======================
        # Python 字串有 .count() 方法，可直接算出某字元出現次數
        # 這比手寫迴圈逐一檢查快又不容易錯
        p = b.count('1')

        # ===================== 步驟 4：輸出結果 ========================
        # 格式完全按照題目要求
        out_stream.write(f"The parity of {b} is {p} (mod 2).\n")


# ===================== 程式進入點 ====================================
if __name__ == '__main__':
    import sys
    solve(sys.stdin, sys.stdout)
