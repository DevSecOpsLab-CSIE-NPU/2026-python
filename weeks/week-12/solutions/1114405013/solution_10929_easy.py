'''
UVA 10929 — You can say 11
===========================
最直覺好記的做法：「逐位連除法」

核心概念：
  要判斷一個超大整數（最多 1000 位）是否為 11 的倍數，
  不用真的把整個數字存成整數（也存不下），
  只要「從左到右，一次處理一位，過程中只保留除以 11 的餘數」就行了。

數學原理：
  12345 = ((((0×10 + 1)×10 + 2)×10 + 3)×10 + 4)×10 + 5
  若每一步都對 11 取餘數，最後的結果和直接 12345 % 11 一模一樣。

完整繁體中文逐行說明
'''

def solve(in_stream, out_stream):
    """
    參數：
      in_stream  — 輸入串流（例：sys.stdin），每行一個正整數
      out_stream — 輸出串流（例：sys.stdout）

    流程摘要：
      ① 逐行讀取數字（字串形式，因為可能 1000 位）
      ② 若遇到 "0" 就結束程式
      ③ 從左到右逐位計算「目前為止的數字」除以 11 的餘數
      ④ 若最後餘數為 0 → 是 11 的倍數
         否則         → 不是 11 的倍數
    """

    # ===================== 主迴圈：讀取直到 "0" =====================
    while True:
        # in_stream.readline() 從串流讀取一行（含換行字元）
        # .strip() 去掉前後空白與換行字元
        s = in_stream.readline().strip()

        # 題目規定：輸入 "0" 代表結束，不處理
        if s == '0':
            break

        # ===================== 連除法核心 ==========================
        # remainder 代表「處理到目前位數為止的數字 ÷ 11 的餘數」
        # 初始為 0，因為還沒處理任何位數
        remainder = 0

        # 用 for 迴圈從字串最左邊的字元開始，逐一處理
        # 範例：若 s = "121"，則 ch 依序為 '1', '2', '1'
        for ch in s:
            # ----------------------------------------------------------
            # 步驟 A：將字元 '0'~'9' 轉成對應的整數 0~9
            # ----------------------------------------------------------
            # 方法 1（直觀）： int(ch)
            # 方法 2（較快）： ord(ch) - ord('0')
            #   因為 ASCII 編碼中 '0' = 48, '1' = 49, …, '9' = 57
            #   所以 ord('3') - 48 = 51 - 48 = 3
            digit = ord(ch) - 48      # 等同於 int(ch)

            # ----------------------------------------------------------
            # 步驟 B：更新餘數
            # ----------------------------------------------------------
            # 公式：新餘數 = (舊餘數 × 10 + 新數字) % 11
            #
            # 為什麼這樣做？
            #   假設目前讀到的數字是 "12"，已經處理完 "1"，
            #   餘數 = 1 % 11 = 1。
            #   現在要加入數字 2：
            #     • 原本的 1 要往左挪一位 → 變成 10（×10）
            #     • 加上新數字 2           → 變成 12
            #     • 對 11 取餘數           → 12 % 11 = 1
            #
            # 逐步範例："121"
            #   第 1 步：remainder = (0×10 + 1) % 11 = 1
            #   第 2 步：remainder = (1×10 + 2) % 11 = 12 % 11 = 1
            #   第 3 步：remainder = (1×10 + 1) % 11 = 11 % 11 = 0
            #   最終餘數 0 → 121 是 11 的倍數 ✓
            remainder = (remainder * 10 + digit) % 11

        # ===================== 輸出結果 ==============================
        # 若最終餘數為 0，代表整個數字可被 11 整除
        if remainder == 0:
            out_stream.write(f"{s} is a multiple of 11.\n")
        else:
            out_stream.write(f"{s} is not a multiple of 11.\n")


# ===================== 程式進入點 ====================================
if __name__ == '__main__':
    import sys
    solve(sys.stdin, sys.stdout)
