# R01. 類別基礎（8.1）
# 本範例示範 Python 類別的幾個基本概念：
# 1. __init__：建構子，用來初始化物件
# 2. 方法：在類別中定義功能
# 3. __repr__：給開發者看的物件字串表示
# 4. __str__：給使用者看的物件字串表示
# 5. 類別變數與實例變數的差異

# -----------------------------------------------------------------------------
# 一、最簡單的 class：Point
# -----------------------------------------------------------------------------
# Point 類別代表平面上的一個點，包含 x 與 y 兩個座標。
class Point:
    # __init__ 是建構子，當你建立物件時會自動執行。
    # self 代表「目前這個物件本身」，後面加上的屬性會變成實例變數。
    def __init__(self, x, y):
        self.x = x
        self.y = y

    # __repr__ 會回傳一個適合開發者閱讀的表示法。
    # 理想上，repr() 的結果最好看起來像可以直接用來重建物件的程式碼。
    def __repr__(self):
        return f"Point({self.x}, {self.y})"

    # __str__ 是 print() 或 str() 主要使用的表示法。
    # 通常會比 __repr__ 更簡潔、更偏向給使用者看。
    def __str__(self):
        return f"({self.x}, {self.y})"

    # distance_to 是我們自訂的方法，用來計算兩點之間的距離。
    # other 也應該是另一個 Point 物件。
    def distance_to(self, other):
        # 這裡使用平面座標距離公式：
        # 距離 = sqrt((x1 - x2)^2 + (y1 - y2)^2)
        return ((self.x - other.x) ** 2 + (self.y - other.y) ** 2) ** 0.5


# 建立兩個 Point 物件。
# 這兩個物件各自擁有自己的 x、y 座標值。
p1 = Point(0, 0)
p2 = Point(3, 4)

# repr(p1) 會呼叫 __repr__，結果適合開發時除錯閱讀。
print(repr(p1))             # Point(0, 0)

# str(p2) 會呼叫 __str__，結果通常比較簡潔。
print(str(p2))              # (3, 4)

# distance_to() 會計算 p1 到 p2 的距離。
# (0, 0) 到 (3, 4) 的距離是 5，符合 3-4-5 直角三角形。
print(p1.distance_to(p2))  # 5.0

# -----------------------------------------------------------------------------
# 二、類別變數 vs 實例變數
# -----------------------------------------------------------------------------
# 類別變數是寫在 class 裡、但不在任何方法裡的變數。
# 它屬於整個類別，所有實例都可以共用這個值。
class Student:
    school = "國立澎湖科技大學"    # 類別變數：所有實例共用

    # __init__ 會幫每個學生物件建立自己的姓名與學號。
    # 這些屬於實例變數，因為每個物件都可以有不同值。
    def __init__(self, name, student_id):
        self.name = name            # 實例變數：每個實例獨立
        self.student_id = student_id

    # 這裡把學號與姓名格式化成較好讀的表示法。
    def __repr__(self):
        return f"Student({self.student_id}, {self.name})"

    # greeting() 使用類別變數 school 與實例變數 name 組合成一句話。
    # 這種寫法很常見，因為類別變數可提供共用資訊，實例變數則保存個別資料。
    def greeting(self):
        return f"我是 {self.school} 的 {self.name}"


# 建立兩位學生物件。
# 雖然兩個物件都屬於 Student 類別，但各自的 name 與 student_id 不同。
s1 = Student("王小明", "11144050001")
s2 = Student("李小華", "11144050002")

# 呼叫 greeting()，會讀取 school 類別變數與 name 實例變數。
print(s1.greeting())

# 透過實例也可以讀取類別變數。
print(s2.school)            # 透過實例存取類別變數

# 也可以直接透過類別名稱讀取類別變數。
print(Student.school)       # 透過類別名稱存取

# -----------------------------------------------------------------------------
# 三、修改類別變數
# -----------------------------------------------------------------------------
# 如果直接修改 Student.school，代表改的是整個類別共用的值。
# 因為實例沒有自己另外定義 school，所以所有實例看到的值都會一起變更。
Student.school = "NPU"
print(s1.school)            # NPU
print(s2.school)            # NPU

# -----------------------------------------------------------------------------
# 補充說明
# -----------------------------------------------------------------------------
# 類別變數：所有物件共享，通常拿來放共用設定或預設值。
# 實例變數：每個物件獨立，通常拿來放每個物件自己的資料。
# __repr__：偏向除錯與開發者閱讀。
# __str__：偏向輸出給使用者閱讀。
#
# 若一個 class 有提供 __repr__ 與 __str__，會讓物件在印出、除錯、互動式環境中更容易理解。
