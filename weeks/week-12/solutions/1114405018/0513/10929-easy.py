"""
UVA 10929 — Counting 11s (Easy Version)

========== 題目說明 ==========
給定一個最多 1000 位的超大正整數，判斷它是否為 11 的倍數。

由於數字可能超過 Python int 的合理範圍，我們不使用除法，
而是利用「11 的整除性質」進行判定。

========== 11 的倍數判定法則 ==========
一個整數的「奇數位數字之和」與「偶數位數字之和」的差，
如果能被 11 整除，則原整數也是 11 的倍數。

位置定義（從右往左，從 1 開始）：
  個位    → 第 1 位（奇數位）
  十位    → 第 2 位（偶數位）
  百位    → 第 3 位（奇數位）
  千位    → 第 4 位（偶數位）
  ...

========== 例子 ==========
例 1：N = 121
  位置：3   2   1
  數字：1   2   1
  奇數位（位置 1, 3）：1 + 1 = 2
  偶數位（位置 2）：2
  差 = 2 - 2 = 0
  0 能被 11 整除 → 121 是 11 的倍數 ✓

例 2：N = 1234
  位置：4   3   2   1
  數字：1   2   3   4
  奇數位（位置 1, 3）：4 + 2 = 6
  偶數位（位置 2, 4）：3 + 1 = 4
  差 = 6 - 4 = 2
  2 不能被 11 整除 → 1234 不是 11 的倍數 ✓
"""


def is_multiple_of_11(number_text):
    """
    判斷字串形式的整數是否為 11 的倍數。
    
    參數：
        number_text: 由數字字元組成的字串（例如 "121"）
    
    回傳值：
        True  表示這個數字是 11 的倍數
        False 表示這個數字不是 11 的倍數
    
    演算法步驟：
    1. 使用 reversed() 從字串的最右邊開始遍歷（個位開始）
    2. 位置從 1 開始計數，每次遞增 1
    3. 奇數位置（1, 3, 5, ...）的數字加到 odd_sum
    4. 偶數位置（2, 4, 6, ...）的數字加到 even_sum
    5. 計算差值 = odd_sum - even_sum
    6. 如果 差值 % 11 == 0，則原數是 11 的倍數
    """
    # 初始化兩個累加變數
    odd_sum = 0      # 奇數位數字之和
    even_sum = 0     # 偶數位數字之和
    position = 1     # 位置計數器，從 1 開始（個位）
    
    # 使用 reversed() 從右往左遍歷字串中的每個數字字元
    # 這樣可以直接得到位置編號（第 1 位、第 2 位、...）
    for digit_char in reversed(number_text):
        # 將字元轉換為整數數字
        digit = int(digit_char)
        
        # 判斷當前位置是奇數位還是偶數位
        if position % 2 == 1:
            # 奇數位：加到 odd_sum
            odd_sum += digit
        else:
            # 偶數位：加到 even_sum
            even_sum += digit
        
        # 位置計數器遞增，準備處理下一個數字
        position += 1
    
    # 計算「奇數位數字和」與「偶數位數字和」的差
    difference = odd_sum - even_sum
    
    # 判斷差是否能被 11 整除
    # 如果能（餘數為 0），則原整數是 11 的倍數
    return difference % 11 == 0


def main():
    """
    主程式：讀取輸入、處理、輸出結果。
    
    流程：
    1. 無限迴圈讀取使用者輸入
    2. 若輸入為 "0"，則結束程式
    3. 否則判斷該數字是否為 11 的倍數，並輸出結果
    """
    while True:
        # 讀入一行輸入，並移除前後的空白
        n = input().strip()
        
        # 題目規定輸入 0 表示結束程式
        if n == "0":
            break
        
        # 呼叫 is_multiple_of_11() 判斷 n 是否為 11 的倍數
        # 根據結果選擇輸出內容
        result = "is a multiple of 11." if is_multiple_of_11(n) else "is not a multiple of 11."
        
        # 輸出格式：數字 + 空格 + 判斷結果
        print(f"{n} {result}")


if __name__ == "__main__":
    # 程式進入點
    # 當此檔案被直接執行時（而不是被 import），執行 main() 函式
    main()
