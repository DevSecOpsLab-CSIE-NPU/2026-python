"""
UVA 10812 — Beat the Spread! 簡易版本

這一版的重點是「好記、好寫、好重現」。

題目給我們兩個數字：
  S = 兩隊分數總和
  D = 兩隊分數差的絕對值

我們要反推出兩隊各自的分數，而且要讓較大的分數先輸出。

推導方式很直觀：
  高分 + 低分 = S
  高分 - 低分 = D

把兩式相加，可以得到高分：
  高分 = (S + D) / 2

把兩式相減，可以得到低分：
  低分 = (S - D) / 2

因此只要檢查兩件事：
  1. (S + D) 能不能被 2 整除
  2. 算出來的低分是不是負數

如果任一條件不成立，就輸出 "impossible"。
"""

# 讀入測試資料組數。
# 題目第一行會先給你有幾筆資料，接下來每一行是一組 S 和 D。
n = int(input())

for _ in range(n):
    # 讀入一組資料：
    # S = 分數總和
    # D = 分數差
    S, D = map(int, input().split())
    
    # 先檢查 (S + D) 是否為偶數。
    # 因為高分 = (S + D) / 2，若 (S + D) 是奇數，就不可能得到整數解。
    if (S + D) % 2 != 0:
        print("impossible")
        continue
    
    # 若通過檢查，就直接套公式算出高分與低分。
    # 使用 // 是整數除法，這樣輸出的結果一定是整數。
    high = (S + D) // 2
    low = (S - D) // 2
    
    # 低分不能是負數。
    # 如果 S < D，則 (S - D) 會是負的，代表這組資料無解。
    if low < 0:
        print("impossible")
    else:
        # 輸出格式要求高分在前、低分在後，中間用空格分隔。
        print(f"{high} {low}")
