"""
================================================================================
UVA 10908 - Largest Square （最大正方形） — 簡易版

問題簡述：
  在 M×N 的字元網格中，對於給定的中心點 (r, c)，
  找出以該點為中心、所有字元相同的最大正方形的邊長。

核心概念：
  正方形必須滿足：
  1. 邊長為奇數（1, 3, 5, ...）
  2. 中心點恰好在正方形中央
  3. 所有字符與中心點相同

簡單的數學關係：
  邊長 = 2k + 1（k 為半径）
  例如：k=0→邊長1，k=1→邊長3，k=2→邊長5

解題思路：
  1. 檢查中心點是否在網格範圍內
  2. 取得中心點的字符
  3. 從最大可能的半径開始，逐漸縮小
  4. 檢查該邊長的正方形內是否所有字符相同
  5. 找到第一個有效正方形即返回（貪心方式）

================================================================================
"""


def find_largest_square(grid, r, c):
    """
    找出以 (r, c) 為中心的最大同色正方形邊長。
    
    參數：
        grid (list): M 行 N 列的字元網格
        r (int): 中心點行座標
        c (int): 中心點列座標
    
    返回：
        int: 最大正方形的邊長（至少為 1）
    """
    
    # ========================================================================
    # 第一步：取得網格的大小
    # ========================================================================
    # M 是行數（高度），N 是列數（寬度）
    M = len(grid)
    N = len(grid[0])
    
    # ========================================================================
    # 第二步：檢查中心點是否在有效範圍內
    # ========================================================================
    # 有效範圍：0 <= r < M 且 0 <= c < N
    if r < 0 or r >= M or c < 0 or c >= N:
        return 0
    
    # ========================================================================
    # 第三步：取得中心點的字符
    # ========================================================================
    # 正方形內的所有字符都必須與中心點相同
    center_char = grid[r][c]
    
    # ========================================================================
    # 第四步：計算最大可能的半径
    # ========================================================================
    # 半径受限於到四個邊界的距離，取最小值
    # 例如：中心 (3, 4)，邊界 (7×10)
    # - 到上：3, 到下：3, 到左：4, 到右：5
    # - max_radius = min(3, 3, 4, 5) = 3
    max_radius = min(r, c, M - 1 - r, N - 1 - c)
    
    # ========================================================================
    # 第五步：貪心搜尋 — 從大到小試探
    # ========================================================================
    # 從最大半径開始逐漸減小
    # 找到的第一個有效正方形就是最大的
    for k in range(max_radius, -1, -1):
        
        # ====================================================================
        # 檢查邊長為 2k+1 的正方形內所有字符是否相同
        # ====================================================================
        valid = True
        
        # 掃描正方形內的每個格子
        # i：從 (r-k) 到 (r+k)，包括兩端
        # j：從 (c-k) 到 (c+k)，包括兩端
        for i in range(r - k, r + k + 1):
            for j in range(c - k, c + k + 1):
                # 發現不同字符就標記為無效
                if grid[i][j] != center_char:
                    valid = False
                    break
            if not valid:
                break
        
        # ====================================================================
        # 若該邊長的正方形有效，立即返回
        # ====================================================================
        if valid:
            return 2 * k + 1
    
    # ========================================================================
    # 最後保障：至少返回 1
    # ========================================================================
    # 邊長 1 的正方形（中心點本身）永遠有效
    return 1


def main():
    """
    主程式：讀取輸入、處理查詢、輸出結果。
    
    流程：
    1. 讀取測試資料組數 T
    2. 對每組測試資料：
       - 讀取網格大小 (M, N) 和查詢數 Q
       - 讀取 M 行的網格內容
       - 輸出 "M N Q"
       - 對每個查詢求解並輸出結果
    """
    
    # ========================================================================
    # 讀取測試資料組數
    # ========================================================================
    T = int(input())
    
    # ========================================================================
    # 處理每組測試資料
    # ========================================================================
    for _ in range(T):
        # ====================================================================
        # 讀取該組的基本資訊
        # ====================================================================
        # M：行數，N：列數，Q：查詢數
        M, N, Q = map(int, input().split())
        
        # ====================================================================
        # 讀取網格內容
        # ====================================================================
        # 讀取 M 行，每行 N 個字符
        grid = []
        for i in range(M):
            row = input().strip()
            grid.append(row)
        
        # ====================================================================
        # 輸出該組的基本資訊
        # ====================================================================
        print(M, N, Q)
        
        # ====================================================================
        # 處理查詢
        # ====================================================================
        # 對每個查詢座標求解
        for j in range(Q):
            # 讀取查詢座標 (r, c)
            r, c = map(int, input().split())
            
            # 調用求解函數
            result = find_largest_square(grid, r, c)
            
            # 輸出結果
            print(result)


# ============================================================================
# 程式進入點
# ============================================================================
# 如果此檔案作為主程式執行，則呼叫 main()
if __name__ == "__main__":
    main()
