"""
================================================================================
UVA 10929 - 判斷 11 的倍數

題目描述：
  給定一個正整數 N（最多 1000 位），判斷它是否為 11 的倍數。
  
  N 的位數可能非常大（最多 1000 位），無法用一般整數型態儲存，
  因此需要以字串形式讀入。

判斷技巧：
  一個整數為 11 的倍數，當且僅當其「奇數位數字之和」與「偶數位數字之和」
  的差是 11 的倍數。
  
  注意：位數從右往左計算，第 1 位為奇數位，第 2 位為偶數位，以此類推。
  
  例子：
    - 121: 從右往左是 1 (奇), 2 (偶), 1 (奇)
      奇數位和：1+1=2，偶數位和：2，差=0（0 是 11 倍數）✓
    
    - 123: 從右往左是 3 (奇), 2 (偶), 1 (奇)
      奇數位和：3+1=4，偶數位和：2，差=2（2 不是 11 倍數）✗

輸入說明：
  每行輸入一個正整數 N（最多 1000 位）。
  輸入 0 時結束，不需處理此筆資料。

輸出說明：
  - 若 N 是 11 的倍數：「N is a multiple of 11.」
  - 若 N 不是 11 的倍數：「N is not a multiple of 11.」

================================================================================
"""


def is_multiple_of_11(n_str):
    """
    判斷一個數（用字串表示）是否為 11 的倍數。
    
    核心演算法：
      1. 從右往左遍歷每一位數字
      2. 按照位數（從 1 開始）判斷是奇數位還是偶數位
      3. 分別累加奇數位和偶數位的數字
      4. 計算兩者的差
      5. 檢查差是否能被 11 整除
    
    為什麼這樣做有效：
      根據數學原理，任何整數可以寫成：
      N = a₀ + 10*a₁ + 100*a₂ + ...（其中 a₀ 是個位，a₁ 是十位，...）
      
      由於 10 ≡ -1 (mod 11)，所以 10² ≡ 1 (mod 11)，10³ ≡ -1 (mod 11)，...
      
      因此 N ≡ a₀ - a₁ + a₂ - a₃ + ... (mod 11)
              ≡ (a₀ + a₂ + ...) - (a₁ + a₃ + ...) (mod 11)
              ≡ (奇數位和) - (偶數位和) (mod 11)
      
      所以 N 是 11 的倍數 ⟺ (奇數位和) - (偶數位和) ≡ 0 (mod 11)
    
    參數：
        n_str (str): 表示正整數的字串（可以有多達 1000 位）
    
    返回：
        bool: 是 11 的倍數返回 True，否則返回 False
    """
    
    # 初始化奇數位和偶數位的累計值
    odd_sum = 0    # 奇數位數字和（第 1, 3, 5, ... 位）
    even_sum = 0   # 偶數位數字和（第 2, 4, 6, ... 位）
    
    # ========================================================================
    # 從右往左遍歷每一位數字（位數從 1 開始計算）
    # ========================================================================
    for idx, digit_char in enumerate(reversed(n_str)):
        # 將字符轉換為整數
        digit = int(digit_char)
        
        # 根據位數判斷是奇數位還是偶數位
        # idx 從 0 開始，所以 idx+1 才是實際位數
        position = idx + 1
        
        if position % 2 == 1:
            # 奇數位（1, 3, 5, ...）
            odd_sum += digit
        else:
            # 偶數位（2, 4, 6, ...）
            even_sum += digit
    
    # 計算奇偶位數字之和的差
    diff = odd_sum - even_sum
    
    # 檢查差是否為 11 的倍數
    # 使用模運算，包括負數的情況
    # 例：-11 % 11 = 0，所以 -11 是 11 的倍數
    return diff % 11 == 0


def main():
    """
    主程式：讀取輸入、判斷是否為 11 的倍數、輸出結果。
    
    流程：
    1. 無限迴圈讀取輸入
    2. 若輸入為 "0" 則終止程式
    3. 呼叫 is_multiple_of_11() 判斷
    4. 輸出相應的結果
    """
    
    # ========================================================================
    # 迴圈讀取輸入直到遇到 "0"
    # ========================================================================
    while True:
        # 讀取一行輸入並去除首尾空白
        line = input().strip()
        
        # ====================================================================
        # 檢查是否為終止條件
        # ====================================================================
        if line == "0":
            # 遇到 0，終止程式
            break
        
        # ====================================================================
        # 判斷是否為 11 的倍數
        # ====================================================================
        if is_multiple_of_11(line):
            # 是 11 的倍數
            print(f"{line} is a multiple of 11.")
        else:
            # 不是 11 的倍數
            print(f"{line} is not a multiple of 11.")


# ============================================================================
# 程式進入點
# ============================================================================
if __name__ == "__main__":
    main()
