"""
================================================================================
UVA 10812 - Beat the Spread! （打敗價差）

程式功能：
  超級盃賭局題目。已知兩隊分數的和與差，求兩隊各自的得分。

題目背景：
  超級盃賭局中：
  - 有人押注兩隊分數之「和」S
  - 有人押注兩隊分數之「差」（絕對值）D
  
  需要根據 S 和 D，推算兩隊各自的得分（較大分數先輸出）。
  若無整數解或出現負數得分，則輸出 impossible。

數學原理：
  設兩隊分數為 a（高分）和 b（低分），則：
  - a + b = S          （分數和）
  - a - b = D          （分數差）
  
  解這個線性方程組：
  - a = (S + D) / 2    （較高分）
  - b = (S - D) / 2    （較低分）

有效性條件（必須同時滿足）：
  1. (S + D) 必須為偶數 → 才能整除2得到整數
  2. (S - D) 必須為偶數 → 才能整除2得到整數  
  3. b >= 0             → 分數不能為負數

輸入格式：
  第一行：測試資料組數 n
  接下來 n 行：每行包含兩個非負整數 S 和 D

輸出格式：
  每行輸出一組結果
  - 若有解：輸出兩個整數（較大的先），以空格分隔
  - 若無解：輸出 impossible

================================================================================
"""


def solve_beat_the_spread(S, D):
    """
    求解兩隊的最終分數。
    
    根據分數和 S 與分數差 D，計算兩隊各自的得分。
    
    參數：
        S (int): 兩隊分數的和（非負整數）
        D (int): 兩隊分數的差，絕對值（非負整數）
    
    返回：
        tuple: 若有解則返回 (較大分數, 較小分數)
        None:  若無解（無整數解或出現負數）
    
    時間複雜度：O(1)
    空間複雜度：O(1)
    """
    
    # ========================================================================
    # 第一步：檢查 (S + D) 的奇偶性
    # ========================================================================
    # 較高分的公式為 a = (S + D) / 2
    # 若 (S + D) 為奇數，則無法整除以2得到整數
    # 例如：S=10, D=3 → (10+3)=13 是奇數 → 13/2=6.5（不是整數）
    if (S + D) % 2 != 0:
        # 無法得到整數解，返回 None
        return None
    
    # ========================================================================
    # 第二步：檢查 (S - D) 的奇偶性
    # ========================================================================
    # 較低分的公式為 b = (S - D) / 2
    # 若 (S - D) 為奇數，則無法整除以2得到整數
    # 例如：S=11, D=2 → (11-2)=9 是奇數 → 9/2=4.5（不是整數）
    if (S - D) % 2 != 0:
        # 無法得到整數解，返回 None
        return None
    
    # ========================================================================
    # 第三步：計算兩隊的分數
    # ========================================================================
    # 使用整數除法 // 確保結果是整數
    # 較高分 = (S + D) / 2
    higher_score = (S + D) // 2
    
    # 較低分 = (S - D) / 2
    lower_score = (S - D) // 2
    
    # ========================================================================
    # 第四步：檢查較低分是否為非負數
    # ========================================================================
    # 題目要求分數不能為負數
    # 例如：S=20, D=40 → lower_score = (20-40)/2 = -10（負數，不合法）
    if lower_score < 0:
        # 出現負數分數，返回 None
        return None
    
    # ========================================================================
    # 第五步：返回結果
    # ========================================================================
    # 題目要求較大分數先輸出
    # 因為 D >= 0，所以 higher_score >= lower_score 必然成立
    return (higher_score, lower_score)


def main():
    """
    主程式入口點。
    
    流程：
    1. 讀取測試資料組數
    2. 對每組測試資料執行求解
    3. 輸出結果
    """
    
    # ========================================================================
    # 讀取輸入
    # ========================================================================
    # 第一行輸入：測試資料的組數 n
    n = int(input())
    
    # ========================================================================
    # 處理每組測試資料
    # ========================================================================
    # 迴圈 n 次，每次處理一組測試資料
    for _ in range(n):
        # 讀取該組測試資料的 S 和 D
        S, D = map(int, input().split())
        
        # 呼叫求解函數
        result = solve_beat_the_spread(S, D)
        
        # ====================================================================
        # 輸出結果
        # ====================================================================
        # 檢查是否有解
        if result is None:
            # 無解的情況：輸出 impossible
            print("impossible")
        else:
            # 有解的情況：輸出兩個分數（較大的先）
            # result[0] 是較高分，result[1] 是較低分
            print(f"{result[0]} {result[1]}")


# ============================================================================
# 程式進入點
# ============================================================================
if __name__ == "__main__":
    # 當此檔案作為主程式執行時，呼叫 main() 函數
    main()
