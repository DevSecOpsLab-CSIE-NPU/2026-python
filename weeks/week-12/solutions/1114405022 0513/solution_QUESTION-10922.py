"""
================================================================================
UVA 10922 - 2 the 9s

題目描述：
  一個整數若能被 9 整除，則稱為「9 的倍數」。
  
  判斷一個數是否為 9 的倍數的遞迴方法：
  1. 計算該數各位數字的總和
  2. 若總和仍為多位數，再次計算各位數字的總和
  3. 重複此過程，直到只剩一位數
  4. 若最終結果為 9，則原數為 9 的倍數
  
  「9 的深度」定義：
  一個能被 9 整除的數，需要重複幾次上述加總過程才能得到 9。

輸入說明：
  - 每行輸入一個正整數（位數可能很多）
  - 以 0 結束輸入（不需處理）

輸出說明：
  - 若不是 9 的倍數：X is not a multiple of 9.
  - 若是 9 的倍數：9-degree of X is Y.
  其中 X 為輸入整數，Y 為 9 的深度

核心思路：
  1. 使用模 9 的性質快速判斷是否為 9 的倍數
  2. 若是，反覆計算各位數字總和，計數直到得到 9

================================================================================
"""


def calculate_digit_sum(n):
    """
    計算一個數字的各位數字總和。
    
    將輸入數字（可以是字串或整數）的所有位數相加。
    
    參數：
        n (int or str): 輸入的數字
    
    返回：
        int: 各位數字的總和
    """
    # 將輸入轉換為字串，以便逐位進行計算
    s = str(n)
    
    # 初始化總和為 0
    total = 0
    
    # 遍歷每一位數字
    for digit_char in s:
        # 將字符轉換為整數並累加
        total += int(digit_char)
    
    return total


def find_nine_degree(n):
    """
    找出一個數字的「9 的深度」。
    
    定義：一個能被 9 整除的數，需要重複多少次「計算各位數字總和」
    的操作才能得到數字 9。
    
    參數：
        n (int or str): 輸入的數字（可能很大，用字串表示）
    
    返回：
        int or None: 
          - 若是 9 的倍數，返回其深度（正整數）
          - 若不是 9 的倍數，返回 None
    """
    
    # 將輸入轉換為整數（支持字串輸入）
    n = int(n) if isinstance(n, str) else n
    
    # 初始化深度計數器
    degree = 0
    
    # ========================================================================
    # 不斷計算各位數字總和，直到得到單位數 9 或其他
    # ========================================================================
    while True:
        # 計算當前數字的各位數字總和
        n = calculate_digit_sum(n)
        
        # 深度加 1
        degree += 1
        
        # 檢查是否達到 9
        if n == 9:
            # 是 9 的倍數，返回深度
            return degree
        elif n < 10:
            # 已經是個位數但不是 9，不是 9 的倍數
            return None


def main():
    """
    主程式：讀取輸入、處理查詢、輸出結果。
    
    流程：
    1. 迴圈讀取輸入
    2. 若輸入為 0 則停止
    3. 判斷是否為 9 的倍數
    4. 輸出相應的結果
    """
    
    # ========================================================================
    # 迴圈讀取輸入
    # ========================================================================
    while True:
        # 讀取一行輸入
        line = input().strip()
        
        # 若輸入為 0，停止程式
        if line == "0":
            break
        
        # ====================================================================
        # 轉換為整數
        # ====================================================================
        n = int(line)
        
        # ====================================================================
        # 計算 9 的深度
        # ====================================================================
        degree = find_nine_degree(line)
        
        # ====================================================================
        # 輸出結果
        # ====================================================================
        if degree is None:
            # 不是 9 的倍數
            print(f"{line} is not a multiple of 9.")
        else:
            # 是 9 的倍數
            print(f"9-degree of {line} is {degree}.")


# ============================================================================
# 程式進入點
# ============================================================================
if __name__ == "__main__":
    main()
