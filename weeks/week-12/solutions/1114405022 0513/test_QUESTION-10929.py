"""
================================================================================
UVA 10929 - 判斷 11 的倍數 - 單元測試

測試策略：
  使用 unittest 框架，測試以下情況：
  1. 標準的 11 的倍數（兩位、三位、四位、大數字）
  2. 標準的非 11 倍數
  3. 邊界情況：0、1、11、111
  4. 大數字（1000 位）

判斷技巧：
  一個數是否為 11 的倍數，看「奇數位數字之和」- 「偶數位數字之和」是否為 11 的倍數
  （位數從右往左計算，第 1 位為奇數位，第 2 位為偶數位）

================================================================================
"""

import unittest


def is_multiple_of_11(n_str):
    """
    判斷一個數（用字串表示）是否為 11 的倍數。
    
    核心邏輯：
      - 從右往左遍歷每一位數字
      - 奇數位（1, 3, 5, ...）的數字相加
      - 偶數位（2, 4, 6, ...）的數字相加
      - 計算兩者的差
      - 若差是 11 的倍數，則原數是 11 的倍數
    
    參數：
        n_str (str): 表示正整數的字串
    
    返回：
        bool: 是 11 的倍數返回 True，否則返回 False
    """
    # 計算各位數字之和
    odd_sum = 0    # 奇數位數字和（第 1, 3, 5, ... 位）
    even_sum = 0   # 偶數位數字和（第 2, 4, 6, ... 位）
    
    # 從右往左遍歷數字（位數從 1 開始計算）
    for idx, digit_char in enumerate(reversed(n_str)):
        digit = int(digit_char)
        
        # 根據位數（從 1 開始）判斷是奇數位還是偶數位
        if (idx + 1) % 2 == 1:
            # 奇數位
            odd_sum += digit
        else:
            # 偶數位
            even_sum += digit
    
    # 計算差
    diff = odd_sum - even_sum
    
    # 檢查差是否為 11 的倍數
    # 包括負數：-11 也是 11 的倍數，通過 % 11 == 0 判斷
    return diff % 11 == 0


class TestMultipleOf11(unittest.TestCase):
    """
    單元測試類：測試 is_multiple_of_11() 函數
    """
    
    # ========================================================================
    # 測試基本情況：11 的倍數
    # ========================================================================
    
    def test_single_digit_11(self):
        """測試：11 本身"""
        self.assertTrue(is_multiple_of_11("11"))
    
    def test_two_digit_22(self):
        """測試：22 是 11 的倍數 (2+2=4, 差=4-0=4... 不對)"""
        # 22: 從右往左是 2 (奇), 2 (偶)
        # 奇數位和：2，偶數位和：2，差=0，0 是 11 倍數
        self.assertTrue(is_multiple_of_11("22"))
    
    def test_three_digit_121(self):
        """測試：121 是 11 的倍數"""
        # 121: 從右往左是 1 (奇), 2 (偶), 1 (奇)
        # 奇數位和：1+1=2，偶數位和：2，差=0
        self.assertTrue(is_multiple_of_11("121"))
    
    def test_three_digit_132(self):
        """測試：132 是 11 的倍數"""
        # 132: 從右往左是 2 (奇), 3 (偶), 1 (奇)
        # 奇數位和：2+1=3，偶數位和：3，差=0
        self.assertTrue(is_multiple_of_11("132"))
    
    def test_four_digit_1111(self):
        """測試：1111 是 11 的倍數"""
        # 1111: 從右往左是 1 (奇), 1 (偶), 1 (奇), 1 (偶)
        # 奇數位和：1+1=2，偶數位和：1+1=2，差=0
        self.assertTrue(is_multiple_of_11("1111"))
    
    def test_four_digit_1210(self):
        """測試：1210 是 11 的倍數"""
        # 1210: 從右往左是 0 (奇), 1 (偶), 2 (奇), 1 (偶)
        # 奇數位和：0+2=2，偶數位和：1+1=2，差=0
        self.assertTrue(is_multiple_of_11("1210"))
    
    def test_five_digit_12321(self):
        """測試：12321 是 11 的倍數"""
        # 12321: 從右往左是 1 (奇), 2 (偶), 3 (奇), 2 (偶), 1 (奇)
        # 奇數位和：1+3+1=5，偶數位和：2+2=4，差=1... 不對
        # 讓我重新驗算 12321 ÷ 11 = 1120.09... 不是倍數
        # 改為測試 1331: 1 (奇), 3 (偶), 3 (奇), 1 (偶)
        # 奇數位和：1+3=4，偶數位和：3+1=4，差=0
        self.assertTrue(is_multiple_of_11("1331"))
    
    def test_two_digit_99(self):
        """測試：99 是 11 的倍數"""
        # 99: 從右往左是 9 (奇), 9 (偶)
        # 奇數位和：9，偶數位和：9，差=0
        self.assertTrue(is_multiple_of_11("99"))
    
    # ========================================================================
    # 測試基本情況：非 11 倍數
    # ========================================================================
    
    def test_single_digit_1(self):
        """測試：1 不是 11 的倍數"""
        self.assertFalse(is_multiple_of_11("1"))
    
    def test_single_digit_5(self):
        """測試：5 不是 11 的倍數"""
        self.assertFalse(is_multiple_of_11("5"))
    
    def test_two_digit_10(self):
        """測試：10 不是 11 的倍數"""
        # 10: 從右往左是 0 (奇), 1 (偶)
        # 奇數位和：0，偶數位和：1，差=-1，-1 % 11 = 10（非 0）
        self.assertFalse(is_multiple_of_11("10"))
    
    def test_two_digit_23(self):
        """測試：23 不是 11 的倍數"""
        # 23: 從右往左是 3 (奇), 2 (偶)
        # 奇數位和：3，偶數位和：2，差=1
        self.assertFalse(is_multiple_of_11("23"))
    
    def test_three_digit_100(self):
        """測試：100 不是 11 的倍數"""
        # 100: 從右往左是 0 (奇), 0 (偶), 1 (奇)
        # 奇數位和：0+1=1，偶數位和：0，差=1
        self.assertFalse(is_multiple_of_11("100"))
    
    def test_three_digit_123(self):
        """測試：123 不是 11 的倍數"""
        # 123: 從右往左是 3 (奇), 2 (偶), 1 (奇)
        # 奇數位和：3+1=4，偶數位和：2，差=2
        self.assertFalse(is_multiple_of_11("123"))
    
    def test_four_digit_1000(self):
        """測試：1000 不是 11 的倍數"""
        # 1000: 從右往左是 0 (奇), 0 (偶), 0 (奇), 1 (偶)
        # 奇數位和：0+0=0，偶數位和：0+1=1，差=-1
        self.assertFalse(is_multiple_of_11("1000"))
    
    # ========================================================================
    # 邊界情況
    # ========================================================================
    
    def test_zero(self):
        """測試：0 是 11 的倍數（0 ÷ 11 = 0）"""
        self.assertTrue(is_multiple_of_11("0"))
    
    def test_double_zero(self):
        """測試：00 等於 0，是 11 的倍數"""
        self.assertTrue(is_multiple_of_11("00"))
    
    def test_large_multiple(self):
        """測試：大數字 121121121 是 11 的倍數"""
        # 121121121 = 121 * 1001001，已知 121 和 1001001 都是 11 的倍數
        self.assertTrue(is_multiple_of_11("121121121"))
    
    def test_very_large_number_1000_digits(self):
        """測試：1000 位的大數字"""
        # 構造一個 1000 位、全由 1 組成的數字
        # 1111...1 (1000 個 1)
        # 奇數位數 500 個 1，偶數位數 500 個 1
        # 奇數位和：500，偶數位和：500，差=0（是 11 的倍數）
        large_num = "1" * 1000
        self.assertTrue(is_multiple_of_11(large_num))
    
    def test_very_large_number_not_multiple(self):
        """測試：1000 位的大數字（非 11 倍數）"""
        # 構造一個 1000 位，前 999 位為 0，最高位為 1 的數字
        large_num = "1" + "0" * 999
        # 1000000...0 (1 後面 999 個 0)
        # 奇數位數 500 個 0，偶數位數 500 個 0，最高位 1 是奇數位
        # 奇數位和：1，偶數位和：0，差=1（不是 11 的倍數）
        self.assertFalse(is_multiple_of_11(large_num))
    
    # ========================================================================
    # 負差的情況（奇數位和 < 偶數位和）
    # ========================================================================
    
    def test_negative_diff_1(self):
        """測試：差為負數的倍數關係"""
        # 12: 從右往左是 2 (奇), 1 (偶)
        # 奇數位和：2，偶數位和：1，差=1（不是 11 的倍數）
        self.assertFalse(is_multiple_of_11("12"))
    
    def test_negative_diff_multiple(self):
        """測試：差為負數但是 11 的倍數"""
        # 209: 從右往左是 9 (奇), 0 (偶), 2 (奇)
        # 奇數位和：9+2=11，偶數位和：0，差=11（是 11 的倍數）
        self.assertTrue(is_multiple_of_11("209"))
    
    def test_diff_negative_not_multiple(self):
        """測試：差為負數不是 11 的倍數"""
        # 2: 從右往左是 2 (奇)
        # 奇數位和：2，偶數位和：0，差=2（不是 11 的倍數）
        self.assertFalse(is_multiple_of_11("2"))


# ============================================================================
# 主程式入口
# ============================================================================
if __name__ == "__main__":
    # 運行測試
    unittest.main(verbosity=2)
