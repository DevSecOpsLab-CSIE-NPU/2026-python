"""
================================================================================
UVA 10812 - Beat the Spread! （打敗價差） — 簡易版

問題簡述：
  已知兩隊分數的「和」S 和「差」D，求兩隊各自的最終分數。
  
解題公式（核心關鍵）：
  ┌─────────────────────────────┐
  │ 高分 = (S + D) / 2          │
  │ 低分 = (S - D) / 2          │
  └─────────────────────────────┘
  
  說明：若 a = 高分, b = 低分，則
        a + b = S  ... (1) 分數和
        a - b = D  ... (2) 分數差
        
  將兩式相加：2a = S + D  →  a = (S + D) / 2
  將兩式相減：2b = S - D  →  b = (S - D) / 2

有效性檢查（同時滿足所有條件才有解）：
  ✓ (S + D) 必須是偶數  → 分數必須是整數
  ✓ (S - D) 必須是偶數  → 分數必須是整數
  ✓ 低分 >= 0           → 分數不能為負數

輸入範例：
  2
  40 20      → 高分30 低分10（30+10=40, 30-10=20）✓
  20 40      → impossible（低分=-10）✗

================================================================================
"""


def solve(S, D):
    """
    根據分數和與差，計算兩隊分數。
    
    參數：
      S (int): 兩隊分數的和
      D (int): 兩隊分數的差（絕對值）
    
    返回：
      tuple: (高分, 低分) - 若有有效解
      None  - 若無解（不是整數或分數為負）
    """
    
    # ========================================================================
    # 第一步：驗證 (S + D) 和 (S - D) 是否都是偶數
    # ========================================================================
    # 若其中一個是奇數，表示無法整除以 2 得到整數
    # 例如：S=10, D=3 → (S+D)=13（奇數）→ 無整數解
    # 例如：S=11, D=2 → (S-D)=9（奇數）  → 無整數解
    if (S + D) % 2 != 0 or (S - D) % 2 != 0:
        return None  # 無解
    
    # ========================================================================
    # 第二步：計算兩隊的分數
    # ========================================================================
    # 使用整數除法 // 確保結果是整數
    high = (S + D) // 2   # 高分 = 和 + 差 的一半
    low = (S - D) // 2    # 低分 = 和 - 差 的一半
    
    # ========================================================================
    # 第三步：檢查低分是否為非負數
    # ========================================================================
    # 題目要求分數不能為負。若差 D 太大就會出現負數
    # 例如：S=20, D=40 → 低分=(20-40)/2=-10 → 無解
    if low < 0:
        return None  # 無解
    
    # ========================================================================
    # 第四步：返回結果
    # ========================================================================
    # 題目要求「較大的先輸出」
    # 由於 D >= 0，所以 high >= low 必然成立
    return (high, low)


# ============================================================================
# 主程式入口
# ============================================================================

# 讀取測試資料組數
n = int(input())

# 對每組測試資料進行處理
for _ in range(n):
    # 讀取該組的 S（和）和 D（差）
    S, D = map(int, input().split())
    
    # 呼叫求解函數
    result = solve(S, D)
    
    # 根據結果判斷是否有解
    if result is None:
        # 無解：輸出 impossible
        print("impossible")
    else:
        # 有解：輸出高分和低分（用空格分隔）
        print(result[0], result[1])
