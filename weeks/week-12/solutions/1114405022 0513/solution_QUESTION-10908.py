"""
================================================================================
UVA 10908 - Largest Square （最大正方形）

程式概要：
  在 M×N 的字元網格中，對於給定的中心點 (r, c)，找出以該點為中心、
  所有字元相同的最大正方形的邊長。

題目重點：
  ✓ 正方形中心必須恰好在中心點 (r, c) 上
  ✓ 正方形的邊長必須為奇數（1, 3, 5, ...）
  ✓ 正方形內所有字符必須與中心點相同
  ✓ 網格座標系：左上角 (0, 0)，右下角 (M-1, N-1)

核心概念 - 正方形邊長與半径的關係：
  ┌─────────────────────────────────────────────────┐
  │ 邊長 = 2k + 1（k 為半径）                       │
  │ 例如：k=0 時邊長=1，k=1 時邊長=3，k=2 時邊長=5  │
  │ 這確保邊長總是奇數，中心點恰好在正方形中央      │
  └─────────────────────────────────────────────────┘

解題策略（貪心方法）：
  1. 計算中心點到四個邊界的距離，取最小值為最大可能的半径
  2. 從最大的半径開始，逐漸減小
  3. 對每個半径，檢查該邊長的正方形內所有字符是否相同
  4. 找到有效的正方形後立即返回（這就是最大的）
  5. 若都不有效，至少返回邊長 1（中心點本身）

複雜度分析：
  時間複雜度：O(M × N × T × Q)
    - T：測試資料組數
    - Q：每組的查詢數
    - M×N：每次查詢最多檢查整個網格
  空間複雜度：O(M × N)
    - 用於儲存網格

================================================================================
"""


def find_largest_square(grid, r, c):
    """
    核心演算法：找出以 (r, c) 為中心的最大同色正方形邊長。
    
    此函數實現貪心算法，從最大可能的正方形開始檢查，逐漸縮小。
    一旦找到有效的正方形，立即返回其邊長（避免不必要的計算）。
    
    參數：
        grid (list): M 行 N 列的字元網格
                    可以是 list[list] 或 list[str]
        r (int): 中心點的行座標（0-indexed）
        c (int): 中心點的列座標（0-indexed）
    
    返回：
        int: 最大正方形的邊長（最小為 1）
    
    時間複雜度：O(M × N) 最壞情況
    空間複雜度：O(1) 除去輸入外的額外空間
    """
    
    # ========================================================================
    # 第一步：取得網格的維度資訊
    # ========================================================================
    # M: 網格的行數（高度）
    # N: 網格的列數（寬度）
    # 例如：7×10 的網格表示有 7 行 10 列
    M = len(grid)           # 行數
    N = len(grid[0])        # 列數（假設非空網格）
    
    # ========================================================================
    # 第二步：邊界檢查 - 驗證中心點的合法性
    # ========================================================================
    # 檢查中心點 (r, c) 是否在網格範圍內
    # 有效範圍：0 <= r < M 且 0 <= c < N
    # 
    # 例如：對於 7×10 的網格
    # ✓ (0, 0) 合法（左上角）
    # ✓ (6, 9) 合法（右下角）
    # ✗ (-1, 5) 不合法（超出左邊界）
    # ✗ (7, 5) 不合法（超出下邊界）
    if r < 0 or r >= M or c < 0 or c >= N:
        return 0  # 返回 0 表示無效位置
    
    # ========================================================================
    # 第三步：取得中心點的字符
    # ========================================================================
    # 正方形內所有字符都必須與中心點相同
    # 將中心點的字符存儲起來，用於後續比較
    center_char = grid[r][c]
    
    # ========================================================================
    # 第四步：計算最大可能的半径
    # ========================================================================
    # 正方形的半径受限於中心點到四個邊界的距離
    # max_radius = min(
    #     到上邊的距離 (r - 0) = r,
    #     到左邊的距離 (c - 0) = c,
    #     到下邊的距離 (M-1 - r) = M-1-r,
    #     到右邊的距離 (N-1 - c) = N-1-c
    # )
    #
    # 例如：7×10 的網格，中心點 (3, 4)
    # - 到上邊：3
    # - 到左邊：4
    # - 到下邊：7-1-3 = 3
    # - 到右邊：10-1-4 = 5
    # max_radius = min(3, 4, 3, 5) = 3
    # 最大邊長 = 2×3+1 = 7
    max_radius = min(r, c, M - 1 - r, N - 1 - c)
    
    # ========================================================================
    # 第五步：貪心搜尋 - 從大到小試探
    # ========================================================================
    # 從 max_radius 開始，逐漸減小 k 的值
    # k 從最大值遞減到 0
    # 這樣可以保證找到的第一個有效正方形就是最大的
    for k in range(max_radius, -1, -1):
        
        # ====================================================================
        # 第 5.1 步：定義該邊長的正方形的邊界
        # ====================================================================
        # 邊長 = 2k + 1 的正方形，以 (r, c) 為中心
        # 其邊界為：
        # - 上邊界：第 (r - k) 行
        # - 下邊界：第 (r + k) 行
        # - 左邊界：第 (c - k) 列
        # - 右邊界：第 (c + k) 列
        # 
        # 例如：中心 (3, 4)，k=2 的正方形
        # - 上邊界：第 (3-2)=1 行
        # - 下邊界：第 (3+2)=5 行
        # - 左邊界：第 (4-2)=2 列
        # - 右邊界：第 (4+2)=6 列
        # 範圍：(1,2) 到 (5,6) 是一個 5×5 的正方形
        
        valid = True  # 假設該邊長的正方形有效
        
        # ====================================================================
        # 第 5.2 步：檢查正方形內的所有字符
        # ====================================================================
        # 掃描正方形內的每個格子，確認所有字符都與中心點相同
        # i：行座標，從 (r - k) 到 (r + k) 包含兩端
        # j：列座標，從 (c - k) 到 (c + k) 包含兩端
        for i in range(r - k, r + k + 1):
            for j in range(c - k, c + k + 1):
                # 若發現任何字符與中心點不同，標記為無效
                if grid[i][j] != center_char:
                    valid = False
                    break  # 提前跳出內層迴圈
            if not valid:
                break  # 提前跳出外層迴圈
        
        # ====================================================================
        # 第 5.3 步：若該邊長的正方形有效，返回結果
        # ====================================================================
        # 由於是從大到小搜尋，找到的第一個有效正方形就是最大的
        if valid:
            return 2 * k + 1  # 邊長 = 2k + 1
    
    # ========================================================================
    # 第六步：保障條件 - 至少返回 1
    # ========================================================================
    # 邊長為 1 的正方形（中心點本身）總是有效的，
    # 因為中心點的字符必然等於它本身
    # 理論上不應該執行到這裡（當 max_radius >= 0 時，k=0 應該已返回）
    return 1


def main():
    """
    主程式：讀取輸入、處理查詢、輸出結果。
    
    程式流程：
    1. 讀取測試資料組數 T
    2. 對每組測試資料：
       a. 讀取網格大小 M、N 和查詢數 Q
       b. 讀取 M 行的網格內容
       c. 輸出 "M N Q"
       d. 對每個查詢求解並輸出結果
    
    輸入格式詳解：
    ┌─────────────────────────────────────────┐
    │ T                    (測試資料組數)      │
    │ M N Q                (網格及查詢資訊)    │
    │ [M 行網格內容]                          │
    │ [Q 行查詢座標]                          │
    │ ... (重複上述 T 次)                     │
    └─────────────────────────────────────────┘
    
    輸出格式詳解：
    ┌─────────────────────────────────────────┐
    │ M N Q                (網格及查詢資訊)    │
    │ [Q 行查詢結果]                          │
    │ ... (重複 T 組)                         │
    └─────────────────────────────────────────┘
    """
    
    # ========================================================================
    # 步驟 1：讀取測試資料組數
    # ========================================================================
    # T 表示有多少組測試資料需要處理
    # 例如：T=3 表示有 3 組測試資料
    T = int(input())
    
    # ========================================================================
    # 步驟 2：迴圈處理每組測試資料
    # ========================================================================
    # 重複 T 次，每次處理一組完整的測試資料
    for _ in range(T):
        
        # ====================================================================
        # 步驟 2.1：讀取該組測試的基本資訊
        # ====================================================================
        # M：網格的行數（高度）
        # N：網格的列數（寬度）
        # Q：該組測試的查詢數
        # 例如：M=7 N=10 Q=4 表示 7×10 的網格，4 個查詢
        M, N, Q = map(int, input().split())
        
        # ====================================================================
        # 步驟 2.2：讀取網格內容
        # ====================================================================
        # 讀取 M 行，每行包含 N 個字符
        # 使用 strip() 移除行末的空白符（如換行符）
        grid = []
        for i in range(M):
            row = input().strip()  # 讀取一行並移除末尾空白
            grid.append(row)       # 添加到網格列表
        
        # 例如：對於 7×10 的網格
        # grid[0] = "abbbaaaaaa"
        # grid[1] = "abbbaaaaaa"
        # ... 依此類推
        
        # ====================================================================
        # 步驟 2.3：輸出該組測試的基本資訊
        # ====================================================================
        # 題目要求：先輸出 "M N Q"
        print(M, N, Q)
        
        # ====================================================================
        # 步驟 2.4：處理該組的查詢
        # ====================================================================
        # 對每個查詢：
        # - 讀取查詢座標 (r, c)
        # - 調用 find_largest_square() 求解
        # - 輸出結果
        for j in range(Q):
            # 讀取查詢座標
            # 例如：(1, 2) 表示中心點在第 1 行第 2 列（0-indexed）
            r, c = map(int, input().split())
            
            # 調用核心函數求解
            result = find_largest_square(grid, r, c)
            
            # 輸出該查詢的答案
            print(result)


# ============================================================================
# 程式進入點
# ============================================================================
# 檢查此檔案是否作為主程式執行（而非被其他程式匯入）
# 若是主程式則執行 main() 函數
if __name__ == "__main__":
    main()
