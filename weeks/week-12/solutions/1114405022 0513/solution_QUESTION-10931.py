"""
================================================================================
UVA 10931 - Parity（奇偶性）

題目描述：
  整數 N 的「奇偶性」定義為其二進位表示中 1 的個數。
  
  給定一個整數 I，需要：
  1. 將其轉換為二進位表示（不含前導零）
  2. 計算二進位中 1 的個數 P
  3. 依照固定格式輸出結果

輸入範圍：
  1 ≤ I ≤ 2,147,483,647（32 位帶符號整數的正數上限）
  輸入 0 時代表結束

輸出格式：
  「The parity of B is P (mod 2).」
  - B：I 的二進位表示（不含前導零）
  - P：二進位中 1 的個數

例子：
  1 → 二進位："1" → 1 的個數:1 → 輸出:「The parity of 1 is 1 (mod 2).」
  2 → 二進位:"10" → 1 的個數:1 → 輸出:「The parity of 10 is 1 (mod 2).」
  10 → 二進位:"1010" → 1 的個數:2 → 輸出:「The parity of 1010 is 2 (mod 2).」
  21 → 二進位:"10101" → 1 的個數:3 → 輸出:「The parity of 10101 is 3 (mod 2).」

================================================================================
"""


def calculate_parity(n):
    """
    計算一個整數的奇偶性（二進位中 1 的個數）。
    
    演算法流程：
      1. 使用 Python 的 bin() 函數轉換為二進位字串
      2. 去掉二進位字串的 "0b" 前綴
      3. 計算字串中 '1' 的個數
      4. 返回二進位字串和 1 的個數
    
    時間複雜度：O(log n)，其中 n 是輸入的整數值
    空間複雜度：O(log n)，用於存儲二進位字串
    
    參數：
        n (int): 正整數（1 ≤ n ≤ 2,147,483,647）
    
    返回：
        tuple: (二進位字串, 1 的個數)
               例：(5) → ("101", 2)
    """
    
    # ========================================================================
    # 轉換為二進位字串
    # ========================================================================
    # bin(n) 返回形如 "0b101" 的字串，需要去掉 "0b" 前綴
    binary_str = bin(n)[2:]
    
    # ========================================================================
    # 計算 1 的個數
    # ========================================================================
    # 直接計算字串中 '1' 字符的個數
    ones_count = binary_str.count('1')
    
    # ========================================================================
    # 返回結果
    # ========================================================================
    return binary_str, ones_count


def main():
    """
    主程式：讀取輸入、計算奇偶性、輸出結果。
    
    流程：
      1. 無限迴圈讀取輸入
      2. 若輸入為 0 則終止程式
      3. 計算奇偶性
      4. 按照格式輸出結果
    """
    
    # ========================================================================
    # 迴圈讀取輸入
    # ========================================================================
    while True:
        # 讀取一行輸入
        line = input().strip()
        
        # 轉換為整數
        n = int(line)
        
        # ====================================================================
        # 檢查終止條件
        # ====================================================================
        if n == 0:
            # 遇到 0，終止程式
            break
        
        # ====================================================================
        # 計算奇偶性
        # ====================================================================
        binary_str, ones_count = calculate_parity(n)
        
        # ====================================================================
        # 輸出結果
        # ====================================================================
        # 按照指定格式輸出：「The parity of B is P (mod 2).」
        print(f"The parity of {binary_str} is {ones_count} (mod 2).")


# ============================================================================
# 程式進入點
# ============================================================================
if __name__ == "__main__":
    main()
