def zip_to_county(zipcode: str) -> str:
    """郵遞區號前 3 碼 → 縣市名稱，找不到回傳 '其他'"""
    digits = "".join(ch for ch in str(zipcode) if ch.isdigit())
    if len(digits) < 3:
        return "其他"
    return ZIPCODE_TO_COUNTY.get(digits[:3], "其他")


def load_county_counts(year: int, data_dir: Path) -> dict[str, int]:
    """讀取單一年份，回傳 {縣市: 人數} 的 dict"""
    csv_path = data_dir / f"{year}年新生資料庫.csv"
    counts: dict[str, int] = defaultdict(int)

    with csv_path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            county = zip_to_county(row.get("郵遞區號", ""))
            counts[county] += 1

    return dict(counts)


def get_top_counties(all_years: dict[int, dict[str, int]], top_n: int = 10) -> list[str]:
    """6 年合計，回傳人數前 top_n 的縣市清單"""
    totals: dict[str, int] = defaultdict(int)
    for county_counts in all_years.values():
        for county, count in county_counts.items():
            totals[county] += count

    ranked = sorted(totals.items(), key=lambda x: (-x[1], x[0]))
    return [county for county, _ in ranked[:top_n]]


def plot_heatmap(all_years: dict[int, dict[str, int]], counties: list[str], output_path: Path) -> None:
    years = sorted(all_years.keys())
    matrix = np.array([[all_years[year].get(county, 0) for year in years] for county in counties])

    plt.rcParams["font.sans-serif"] = ["Microsoft JhengHei", "Arial Unicode MS", "sans-serif"]
    plt.rcParams["axes.unicode_minus"] = False

    fig, ax = plt.subplots(figsize=(10, 7))
    img = ax.imshow(matrix, cmap="YlOrRd", aspect="auto")

    ax.set_title("109-114 學年度招生來源縣市熱力圖（Top 10）", fontsize=14)
    ax.set_xticks(np.arange(len(years)))
    ax.set_xticklabels(years)
    ax.set_yticks(np.arange(len(counties)))
    ax.set_yticklabels(counties)
    ax.set_xlabel("學年度")
    ax.set_ylabel("縣市")

    threshold = matrix.max() * 0.55 if matrix.size else 0
    for i in range(matrix.shape[0]):
        for j in range(matrix.shape[1]):
            text_color = "white" if matrix[i, j] >= threshold else "black"
            ax.text(j, i, str(matrix[i, j]), ha="center", va="center", fontsize=8, color=text_color)

    cbar = fig.colorbar(img, ax=ax)
    cbar.set_label("人數")
    fig.tight_layout()

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=200)
    plt.close(fig)


def main() -> None:
    data_dir = resolve_data_dir()
    years = [109, 110, 111, 112, 113, 114]
    all_years = {year: load_county_counts(year, data_dir) for year in years}
    top_counties = get_top_counties(all_years, top_n=10)

    output = Path(__file__).parent / "output" / "task2.png"
    plot_heatmap(all_years, top_counties, output)
    print(f"Task2 image generated: {output}")


if __name__ == "__main__":
    main()
