# R01. 函數彈性簽章（Flexible Function Signatures）
# =============================================================================
# 什麼是「彈性簽章」？
#   一般函數的參數數量是固定的，但有時候我們希望：
#       1. 接受「不固定數量」的位置參數（*args）
#       2. 接受「不固定數量」的關鍵字參數（**kwargs）
#       3. 強制某些參數「一定要用名稱傳遞」（keyword-only）
#
# Python 的參數系統非常靈活，可以組合出各種簽章模式。
#
# 對應 Bloom's Taxonomy：記憶（Remember）— 背得出語法
# =============================================================================


# ═════════════════════════════════════════════════════════════════════════════
# *args：不固定個數的位置參數
# ═════════════════════════════════════════════════════════════════════════════
# 語法：在參數名稱前加一個星號 *
# 行為：所有「多餘的」位置參數會被包成一個 tuple 傳入
# 命名：通常叫 args（arguments 的縮寫），但其實可以用任何名字
# 應用：加總函數、格式化輸出、任何不確定參數數量的場景

def add_all(*args):
    """加總任意數量的數字

    args 在函數內部是一個 tuple
    即使不傳任何參數，args 也是空 tuple，不會出錯

    範例：
        add_all(1, 2)       → args = (1, 2)
        add_all(1, 2, 3, 4) → args = (1, 2, 3, 4)
        add_all()           → args = ()
    """
    return sum(args)

print("=== *args：不定個數的位置參數 ===")
print(add_all(1, 2))            # 3
print(add_all(1, 2, 3, 4, 5))  # 15
print(add_all())                # 0（空的也沒問題）


# ═════════════════════════════════════════════════════════════════════════════
# **kwargs：不固定個數的關鍵字參數
# ═════════════════════════════════════════════════════════════════════════════
# 語法：在參數名稱前加兩個星號 **
# 行為：所有「多餘的」關鍵字參數會被包成一個 dict 傳入
# 命名：通常叫 kwargs（keyword arguments 的縮寫）
# 應用：建立字典、傳遞設定選項、包裝裝飾器

def make_student(**kwargs):
    """建立學生資料，欄位可以自由指定

    kwargs 在函數內部是一個 dict
    傳入的「名稱=值」會變成 dict 的 key-value

    範例：
        make_student(name="小明", grade=85)
        → kwargs = {"name": "小明", "grade": 85}
    """
    return kwargs

print("\n=== **kwargs：不定個數的關鍵字參數 ===")
s = make_student(name="王小明", grade=85, seat=12)
print(s)   # {'name': '王小明', 'grade': 85, 'seat': 12}


# ═════════════════════════════════════════════════════════════════════════════
# keyword-only：強制用名稱呼叫
# ═════════════════════════════════════════════════════════════════════════════
# 語法：在參數列表中加入一個孤獨的 *
# 行為：* 之後的所有參數「一定要用名稱傳遞」，不能靠位置
# 目的：避免呼叫時搞錯參數順序，提高可讀性
# 應用：參數較多時、參數容易混淆時

def send_score(student_id, *, subject, score):
    """發送學生成績通知

    * 之後的參數（subject, score）必須具名傳遞
    這樣即使以後增加參數，也不會因為順序錯亂而導致 bug

    正確呼叫：
        send_score("411234001", subject="數學", score=90)
    錯誤呼叫（會 TypeError）：
        send_score("411234001", "數學", 90)
    """
    print(f"學號 {student_id}｜{subject}：{score} 分")

print("\n=== keyword-only：強制具名，避免填錯順序 ===")
send_score("411234001", subject="數學", score=90)   # 正確
# send_score("411234001", "數學", 90)  # ← 這樣會 TypeError！


# ═════════════════════════════════════════════════════════════════════════════
# 三種參數混合使用
# ═════════════════════════════════════════════════════════════════════════════
# Python 函數的參數順序有嚴格規定：
#   1. 普通位置參數（positional）
#   2. *args（不固定位置參數）
#   3. keyword-only 參數（* 後面的）
#   4. **kwargs（不固定關鍵字參數）

def report(title, *scores, prefix="成績"):
    """產生成績報告

    參數說明：
        title：報表標題（普通位置參數）
        *scores：任意多個成績（不固定位置參數）
        prefix：前綴文字（有預設值，可以選擇性傳入）

    技巧：
        prefix 在 *scores 之後，所以它是 keyword-only，
        必須用 prefix="最終" 的方式傳遞，不能靠位置。
    """
    avg = sum(scores) / len(scores) if scores else 0
    print(f"{prefix}報告－{title}：平均 {avg:.1f}")

print("\n=== 混合：普通 + *args + 預設值 ===")
report("期中考", 80, 90, 70)          # prefix 用預設值 "成績"
report("期末考", 95, 85, 75, 100, prefix="最終")  # 指定 prefix


# ═════════════════════════════════════════════════════════════════════════════
# 記憶重點
# ═════════════════════════════════════════════════════════════════════════════
# 1. *args   → tuple，接受任意個「值」（位置參數）
# 2. **kwargs → dict，接受任意個「名稱=值」（關鍵字參數）
# 3. *（單獨一顆星）→ 後面的參數一定要具名，不能靠位置
# 4. 參數順序固定：
#    普通參數 → *args → keyword-only 參數 → **kwargs
#    違反這個順序會 SyntaxError
# 5. 面試常見問題：
#    Q: *args 和 **kwargs 的差別？
#    A: *args 收位置參數變成 tuple，**kwargs 收關鍵字參數變成 dict
