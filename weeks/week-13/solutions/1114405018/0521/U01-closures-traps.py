# nonlocal：在閉包裡修改外層的變數
# ═════════════════════════════════════════════════════════════════════════════
# 一般情況下，閉包可以「讀取」外層變數，但不能「修改」。
# 這是因為 count += 1 相當於 count = count + 1，
# 左邊的 count 會被 Python 認為是「在函數內新建一個區域變數」，
# 而不是「修改外層的 count」。
#
# 解決方案：用 nonlocal 宣告，告訴 Python：
#   「count 不是區域變數，它是外層函數的變數，我要修改它」

print("\n=== nonlocal：修改外層變數 ===")

def make_counter(start=0):
    """回傳一個計數器函數，每次呼叫加 1

    這是一個閉包工廠：
        - 外層函數 make_counter 建立變數 count
        - 內層函數 counter 可以讀取和修改 count
        - 每次呼叫 make_counter 會產生一組獨立的 count

    如果沒有 nonlocal：
        count += 1 會試圖建立一個區域變數 count
        但右邊的 count 還沒定義，所以會 UnboundLocalError
    """
    count = start

    def counter():
        nonlocal count   # ← 宣告：count 來自外層，不是新的區域變數
        count += 1       # 修改外層的 count
        return count

    return counter

c1 = make_counter()      # 從 0 開始的計數器
c2 = make_counter(10)    # 從 10 開始的計數器
print(c1(), c1(), c1())   # 1 2 3
print(c2(), c2())         # 11 12
print(c1())               # 4（c1 和 c2 是各自獨立的）


