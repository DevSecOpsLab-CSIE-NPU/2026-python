# ═════════════════════════════════════════════════════════════════════════════
# 陷阱 1：可變的預設值（Mutable Default Arguments）
# ═════════════════════════════════════════════════════════════════════════════
# 關鍵觀念：
#   函數的預設值不是在「每次呼叫時」重新建立的，
#   而是在「def 定義時」就建立好，之後所有呼叫都共用同一個物件。
#
# 對於不可變型別（int, str, tuple, None）來說沒問題，
# 但對可變型別（list, dict, set）來說，共用會造成預期之外的副作用。

def add_to_cart(item, cart=[]):   # ← 這個 [] 只在 def 時建立一次！
    """把商品加入購物車

    問題分析：
        cart=[] 這個空 list 在函數定義時就被建立了
        之後每次呼叫 add_to_cart，如果沒傳 cart，
        用的都是「同一個」list 物件

    驗證方法：
        用 id(cart) 可以發現三次呼叫的 cart 都是同一個記憶體位置
    """
    cart.append(item)
    return cart

print("=== 陷阱 1：可變預設值 ===")
print(add_to_cart("蘋果"))   # ['蘋果']
print(add_to_cart("香蕉"))   # ['蘋果', '香蕉']  ← 驚！不是 ['香蕉']
print(add_to_cart("葡萄"))   # ['蘋果', '香蕉', '葡萄']
# 原因：三次呼叫共用同一個 list，每次 append 都是在同一個 list 上加

print("\n--- 正確寫法：用 None 當預設值 ---")
def add_to_cart_safe(item, cart=None):
    """正確的購物車實作

    原理：
        None 是不可變的，每次呼叫時預設值都是 None
        在函數內部檢查：如果是 None，就建立一個新的 list
        這樣每次呼叫（沒傳 cart）都會有自己獨立的 list

    這個模式在 Python 中非常常見，是標準的慣用寫法
    """
    if cart is None:
        cart = []   # ← 每次沒傳參數時，才建立新的 list
    cart.append(item)
    return cart

print(add_to_cart_safe("蘋果"))  # ['蘋果']
print(add_to_cart_safe("香蕉"))  # ['香蕉'] ← 各自獨立，正確！


# ═════════════════════════════════════════════════════════════════════════════
# 陷阱 2：閉包的延遲綁定（Late Binding Closure）
# ═════════════════════════════════════════════════════════════════════════════
# 什麼是閉包？
#   閉包是一個函數，它「記住」了定義時的外層變數環境。
#   例如在 for 迴圈中定義的 lambda，可以存取迴圈變數 i。
#
# 關鍵問題：
#   閉包記住的是「變數名稱（i）」而不是「建立當下的值」。
#   當閉包真正被「執行」時，才會去查變數 i 目前的值。
#   如果那時 i 已經變了，閉包拿到的就是改變後的值。

print("\n=== 陷阱 2：閉包延遲綁定 ===")
funcs = []
for i in range(5):
    # 這裡定義了 5 個 lambda
    # 每個 lambda 都說「我要回傳 i」
    # 但 lambda 沒有立即執行，它只是記住「我要去查 i 這個變數」
    funcs.append(lambda: i)

print("你以為：", [0, 1, 2, 3, 4])
print("實際上：", [f() for f in funcs])  # [4, 4, 4, 4, 4]

# 為什麼全部都是 4？
#   for 迴圈結束時，i 的最終值是 4
#   所有 5 個 lambda 都是在「被呼叫時」才去查 i 的值
#   那時候 i = 4，所以全部回傳 4

print("\n--- 正確寫法：用預設參數把值「複製」進來 ---")
funcs_ok = []
for i in range(5):
    # 關鍵技巧：lambda i=i: i
    # 第一個 i 是 lambda 的參數名稱
    # 第二個 i 是目前 for 迴圈的 i 的值
    # 預設參數在定義時就會被計算並儲存
    # 所以每個 lambda 的 i 參數的預設值是不同的（0, 1, 2, 3, 4）
    funcs_ok.append(lambda i=i: i)

print("修正後：", [f() for f in funcs_ok])  # [0, 1, 2, 3, 4] ✓


