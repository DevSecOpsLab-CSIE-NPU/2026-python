# 實際應用：用閉包做「一次性」工具函數
# ═════════════════════════════════════════════════════════════════════════════
# 有時候你只需要「記住一點狀態」，又不想為此寫一個完整 class。
# 閉包是很好的輕量級選擇。例如 CPE 中追蹤「已經走過的節點」。

print("\n=== 閉包應用：記住已走過的節點 ===")
def make_visit_tracker():
    """建立一個拜訪追蹤器

    回傳的 visit 函數會記住哪些節點已經被造訪過
    不需要寫 class，閉包就夠了

    應用場景：
        - 圖論中檢查節點是否走過
        - 去重複過濾
        - 狀態追蹤
    """
    visited = set()

    def visit(node):
        nonlocal visited
        if node in visited:
            return False    # 已走過
        visited.add(node)
        return True         # 第一次走到

    return visit

visit = make_visit_tracker()
results = [visit(n) for n in [1, 2, 1, 3, 2, 4]]
print(results)  # [True, True, False, True, False, True]


