# U03. 字串格式化效能與陷阱（2.14–2.20）
# 說明：join vs + / format_map 缺失鍵 / bytes 索引差異

import timeit

# ─────────────────────────────────────────────────────────────────
# join 效能優於 + （2.14）
# 說明：使用 + 串接字串會每次建立新物件，效能較差
# ─────────────────────────────────────────────────────────────────

# 建立測試資料：1000 個小字串
parts = [f"item{i}" for i in range(1000)]


def bad_concat():
    """使用 + 串接（效能差，時間複雜度 O(n²)）"""
    s = ""
    for p in parts:
        s += p  # 每次迴圈都會建立新的字串物件
    return s


def good_join():
    """使用 join（效能好，時間複雜度 O(n)）"""
    return "".join(parts)


# 效能測試：各執行 500 次
t1 = timeit.timeit(bad_concat, number=500)
t2 = timeit.timeit(good_join, number=500)
print(f"+串接: {t1:.3f}s  join: {t2:.3f}s")


# ─────────────────────────────────────────────────────────────────
# format_map 處理缺失鍵（2.15）
# 說明：format_map() 可以用自訂字典處理缺失的鍵，不會抛出 KeyError
# ─────────────────────────────────────────────────────────────────

class SafeSub(dict):
    """
    安全的字串替換類別
    繼承自 dict，當鍵不存在時回傳帶有大括號的原始佔位符
    """
    
    def __missing__(self, key: str) -> str:
        """當鍵不存在時呼叫"""
        return "{" + key + "}"  # 缺失時保留佔位符


name = "Guido"
s = "{name} has {n} messages."

# format_map 使用 SafeSub，雖然 'n' 鍵不存在，但不會報錯
# 反而會保留 {n} 作為輸出
print(s.format_map(SafeSub(vars())))  # 輸出：'Guido has {n} messages.'


# ─────────────────────────────────────────────────────────────────
# bytes 索引回傳整數（2.20）
# 說明：位元組物件的索引操作回傳整數而非字元
# ─────────────────────────────────────────────────────────────────

a = "Hello"
b = b"Hello"

# 字串索引：回傳字元
print(a[0])  # 輸出：'H'

# 位元組索引：回傳整數（ASCII 編碼）
print(b[0])  # 輸出：72（即 ord('H')）


# ─────────────────────────────────────────────────────────────────
# bytes 不能直接 format，需先格式化再 encode
# 說明：位元組物件沒有 format() 方法
# ─────────────────────────────────────────────────────────────────

# 正確流程：先建立格式化字串，再 encode 為位元組
print("{:10s} {:5d}".format("ACME", 100).encode("ascii"))
# 輸出：b'ACME            100'