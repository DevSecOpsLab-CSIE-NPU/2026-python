# U07. 隨機種子與安全亂數（3.11）
# 說明：random 模組為偽隨機，相同種子產生相同序列；密碼學請用 secrets

import random
import secrets

# ─────────────────────────────────────────────────────────────────
# 相同種子 → 相同序列（可重現）
# 說明：random 模組是偽隨機數產生器，設定相同种子會產生相同的隨機序列
# 這對於除錯和測試很有用
# ─────────────────────────────────────────────────────────────────

random.seed(42)
seq1 = [random.randint(1, 100) for _ in range(5)]

random.seed(42)
seq2 = [random.randint(1, 100) for _ in range(5)]

print(seq1 == seq2)  # 輸出：True（兩次序列完全相同）


# ─────────────────────────────────────────────────────────────────
# 不同 Random 實例各自獨立
# 說明：可以建立多個獨立的 Random 物件，彼此不影響
# ─────────────────────────────────────────────────────────────────

rng1 = random.Random(1)
rng2 = random.Random(2)

print(rng1.random(), rng2.random())  # 輸出：兩個不同的隨機值


# ─────────────────────────────────────────────────────────────────
# 密碼學安全亂數（不可預測，不能設种子）
# 說明：secrets 模組提供密碼學安全的隨機數，適用於安全相關場景
# ─────────────────────────────────────────────────────────────────

# 產生 0 到 99 之間的密碼學安全整數
print(secrets.randbelow(100))

# 產生 16 位元組的隨機 hex 字串（32 個十六進位字元）
print(secrets.token_hex(16))

# 產生 16 位元組的隨機位元組
print(secrets.token_bytes(16))


# ─────────────────────────────────────────────────────────────────
# 重要：random 模組不適合密碼、token、session key 等安全場景
# 說明：random 是偽隨機，可以被預測，只適合遊戲、模擬、測試等非安全用途
