# 這份範例整理 Python 中最常見的數值處理觀念：
# 1. round() 的四捨五入規則
# 2. 浮點數誤差與 Decimal 的用途
# 3. format() 的數字格式化寫法
# 4. 二進位、八進位、十六進位的表示與轉換

from decimal import Decimal, localcontext
import math

# ── 3.1 四捨五入 ──────────────────────────────────────
# round(number, ndigits) 中，ndigits 表示要保留到小數第幾位。
print(round(1.27, 1))  # 1.3
print(round(1.25361, 3))  # 1.254

# Python 的 round() 採用「銀行家捨入」(round half to even)。
# 當剛好落在 .5 時，會往最近的偶數靠攏，而不是一律進位。
print(round(0.5))  # 0（銀行家捨入，取最近偶數）
print(round(2.5))  # 2

a = 1627731
# ndigits 為負數時，代表往整數位左邊做四捨五入。
# 這裡 -2 表示四捨五入到百位。
print(round(a, -2))  # 1627700（對百位四捨五入）

# ── 3.2 精確浮點數 ────────────────────────────────────
# 一般 float 採用二進位浮點表示，某些十進位小數無法精確儲存。
# 因此 4.2 + 2.1 可能出現看似奇怪的尾數誤差。
print(4.2 + 2.1)  # 6.300000000000001（有誤差）

# Decimal 以十進位邏輯表示數值，適合金融、金額、精度要求較高的情境。
# 建議用字串建立 Decimal，避免把 float 的誤差一併帶進來。
da, db = Decimal("4.2"), Decimal("2.1")
print(da + db)  # 6.3（精確）

# localcontext() 可以暫時調整 Decimal 的運算設定。
# 這裡把有效位數設為 3，因此結果會依該精度顯示。
with localcontext() as ctx:
    ctx.prec = 3
    print(Decimal("1.3") / Decimal("1.7"))  # 0.765

# math.fsum() 專門用來做較高精度的浮點加總。
# 當大數與小數混合相加時，通常比內建 sum() 更可靠。
print(math.fsum([1.23e18, 1, -1.23e18]))  # 1.0（正確）

# ── 3.3 數字格式化 ────────────────────────────────────
x = 1234.56789

# 0.2f：固定小數點格式，保留 2 位小數。
print(format(x, "0.2f"))  # '1234.57'

# >10.1f：總寬度 10、靠右對齊、保留 1 位小數。
print(format(x, ">10.1f"))  # '    1234.6'

# ,：加入千分位逗號。
print(format(x, ","))  # '1,234.56789'

# 0,.2f：同時加千分位並保留 2 位小數。
print(format(x, "0,.2f"))  # '1,234.57'

# e：使用科學記號表示法。
print(format(x, "e"))  # '1.234568e+03'

# ── 3.4 二八十六進制 ──────────────────────────────────
n = 1234

# bin()/oct()/hex() 會回傳帶前綴的字串：0b、0o、0x。
print(bin(n), oct(n), hex(n))  # 0b10011010010 0o2322 0x4d2

# format() 可取得不含前綴的進位表示。
print(format(n, "b"), format(n, "x"))  # 10011010010 4d2

# int(字串, 基底) 可以把不同進位字串轉回十進位整數。
print(int("4d2", 16), int("2322", 8))  # 1234 1234
