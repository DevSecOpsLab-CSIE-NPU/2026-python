# R05. 數字基礎：四捨五入、進制、格式化（3.1–3.4）
# 說明：round / Decimal / format / bin / oct / hex 的基本用法

from decimal import Decimal, localcontext
import math

# ─────────────────────────────────────────────────────────────────
# 3.1 四捨五入
# Python 的 round() 使用「銀行家捨入法」（Banker's Rounding）
# 當最後一位是 5 時，會向最近的偶數捨入
# ─────────────────────────────────────────────────────────────────

# 基本四捨五入：對小數點後第 1 位進行四捨五入
print(round(1.27, 1))  # 輸出：1.3

# 對小數點後第 3 位進行四捨五入
print(round(1.25361, 3))  # 輸出：1.254

# 銀行家捨入：0.5 捨入為 0（因為 0 是偶數）
print(round(0.5))  # 輸出：0

# 銀行家捨入：2.5 捨入為 2（因為 2 是偶數）
print(round(2.5))  # 輸出：2

# 使用負數指定對十位、百位等進行四捨五入
a = 1627731
print(round(a, -2))  # 輸出：1627700（對百位四捨五入）

# ─────────────────────────────────────────────────────────────────
# 3.2 精確浮點數
# 說明：浮點數運算會有精度問題，使用 Decimal 類別可避免
# ─────────────────────────────────────────────────────────────────

# 一般浮點數運算會產生誤差（因為二進位無法精確表示十進位小數）
print(4.2 + 2.1)  # 輸出：6.300000000000001（有精度誤差）

# 使用 Decimal 進行精確計算：將字串傳入以確保精確度
da, db = Decimal("4.2"), Decimal("2.1")
print(da + db)  # 輸出：6.3（精確結果）

# 使用 localcontext 設定精度範圍
# 這會讓 Decimal 運算只保留 3 位有效數字
with localcontext() as ctx:
    ctx.prec = 3
    print(Decimal("1.3") / Decimal("1.7"))  # 輸出：0.765

# math.fsum 提供比 sum() 更精確的浮點數累加
# 解決大數加小數時的精度流失問題
print(math.fsum([1.23e18, 1, -1.23e18]))  # 輸出：1.0（正確答案）

# ─────────────────────────────────────────────────────────────────
# 3.3 數字格式化
# 說明：使用 format() 函數格式化數字输出
# ─────────────────────────────────────────────────────────────────

x = 1234.56789

# 0.2f：固定小數點 2 位
print(format(x, "0.2f"))  # 輸出：'1234.57'

# >10.1f：右對齊，寬度 10，小數點 1 位
print(format(x, ">10.1f"))  # 輸出：'    1234.6'

# ,：千分位逗號
print(format(x, ","))  # 輸出：'1,234.56789'

# 0,.2f：千分位 + 固定小數點 2 位
print(format(x, "0,.2f"))  # 輸出：'1,234.57'

# e：科學記號表示法
print(format(x, "e"))  # 輸出：'1.234568e+03'

# ─────────────────────────────────────────────────────────────────
# 3.4 二、八、十六進制
# 說明：Python 內建進制轉換函數
# ─────────────────────────────────────────────────────────────────

n = 1234

# bin()：二進制、oct()：八進制、hex()：十六進制
print(bin(n), oct(n), hex(n))  # 輸出：0b10011010010 0o2322 0x4d2

# format() 也可以指定進制格式
# b：二進制、x：十六進制
print(format(n, "b"), format(n, "x"))  # 輸出：10011010010 4d2

# int() 可以將指定進制的字串轉為整數
print(int("4d2", 16), int("2322", 8))  # 輸出：1234 1234