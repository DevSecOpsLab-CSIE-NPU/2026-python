# R04. 位元組字串操作（2.20）
# 說明：bytes / bytearray 支援大部分字串方法，但有幾個重要差異需要注意

import re

# 建立一個位元組物件，內容為 "Hello World"
# 注意：位元組字串必須使用 b"" 前綴
data = b"Hello World"

# 使用切片取得前 5 個位元組（相當於字串的前 5 個字元）
print(data[0:5])  # 輸出：b'Hello'

# startswith() 方法用於檢查位元組物件是否以指定的前綴開頭
print(data.startswith(b"Hello"))  # 輸出：True

# split() 方法可以將位元組字串依空白分割成清單
print(data.split())  # 輸出：[b'Hello', b'World']

# replace() 方法用於替換位元組中的子字串
print(data.replace(b"Hello", b"Hello Cruel"))  # 輸出：b'Hello Cruel World'

# ============================================================
# 正則表達式也必須使用 bytes 模式
# 說明：使用正則表達式處理位元組時，正規表達式字串必須加上 b 前綴
# ============================================================

# 原始位元組資料，包含冒號和逗號作為分隔符
raw = b"FOO:BAR,SPAM"

# 使用正則表達式依冒號或逗號分割字串
# rb"[:,]" 表示使用 bytes 模式的正規表達式
print(re.split(rb"[:,]", raw))  # 輸出：[b'FOO', b'BAR', b'SPAM']

# ============================================================
# 差異 1：索引回傳整數而非字元
# 說明：對字串使用索引取得字元，但對位元組使用索引取得整數（ASCII碼）
# ============================================================

# 字串索引：取得字元 'H'
a = "Hello"
print(a[0])  # 輸出：'H'（字元）

# 位元組索引：取得整數 72（即字元 'H' 的 ASCII 碼）
b = b"Hello"
print(b[0])  # 輸出：72（整數，等同於 ord('H')）

# ============================================================
# 差異 2：不能直接用 format()，需先編碼
# 說明：位元組物件沒有 format() 方法，需要先建立字串再編碼
# ============================================================

# 使用 format() 建立格式化字串，然後使用 encode() 轉換為位元組
# {:10s} 表示左對齊的 10 字元寬度字串
# {:10d} 表示右對齊的 10 位元寬度整數
formatted = "{:10s} {:10d}".format("ACME", 100).encode("ascii")
print(formatted)  # 輸出：b'ACME            100'