"""
UVA 10041 簡單好記版（easy）

記法口訣：
1) 先把每一組地址排序
2) 找中位數位置當作 Vito 新家
3) 把每個地址到中位數的距離加總

為什麼可行：
在一條直線上，若目標是讓「絕對距離總和」最小，最佳點會落在中位數。
因此本題不需要暴力嘗試每個門牌，只要抓中位數就能得到最小總距離。
"""

import sys


def main() -> None:
    # 一次讀完整份輸入，並用 split() 拆成數字字串，再轉成 int。
    # 例如輸入：
    # 2
    # 2 2 4
    # 3 2 4 6
    # 會變成 nums = [2, 2, 2, 4, 3, 2, 4, 6]
    nums = list(map(int, sys.stdin.read().split()))
    if not nums:
        # 若沒有任何輸入，直接結束。
        return

    # 第一個數字是測資組數 t。
    t = nums[0]

    # i 是目前讀到 nums 的哪個位置（索引指標）。
    # 因為 nums[0] 已經是 t，所以從 1 開始。
    i = 1

    # ans 用來收集每一組測資的答案，最後再一次輸出。
    ans = []

    for _ in range(t):
        # 每組第一個數字 r 代表這組有幾位親戚（幾個地址）。
        r = nums[i]
        i += 1

        # 取出這一組的 r 個地址。
        # 切片範圍是 [i, i + r)，取完後要把指標往後移 r 格。
        a = nums[i : i + r]
        i += r

        # 核心步驟 1：排序，讓中位數可以直接用索引取得。
        a.sort()

        # 核心步驟 2：取中位數。
        # - r 為奇數：正中間那個
        # - r 為偶數：中間兩個任選其一都可得到最小總距離
        m = a[r // 2]

        # 核心步驟 3：把每個地址到 m 的絕對距離加總。
        # abs(x - m) 就是題目定義的距離。
        # 轉成字串是為了最後用 join 輸出多行。
        ans.append(str(sum(abs(x - m) for x in a)))

    # 每組答案各佔一行，符合 UVA 輸出格式。
    sys.stdout.write("\n".join(ans))


if __name__ == "__main__":
    main()
