def solve_probability_easy(n: int, p: float, i: int) -> float:
    """
    這是一個更容易記憶且簡潔的版本（Pythonic / One-liner）。
    我們只要知道核心公式是無窮等比級數求和：a / (1-r)
    其中 a 是第一輪就贏的機率，r 是一整輪都沒有人贏的機率。
    我們直接把所有變數合併在一起寫！
    """
    # 如果沒人有機會贏 (p = 0)，那機率就是 0
    if p == 0:
        return 0.0
        
    # (1 - p) 是失敗的機率。
    # 分子：(1-p)**(i-1) * p，代表前面 (i-1) 個人都輸，輪到第 i 個人時他贏了
    # 分母：1 - (1-p)**n，代表扣掉一整輪 N 個人都輸的機率
    return p * ((1 - p) ** (i - 1)) / (1 - (1 - p) ** n)
