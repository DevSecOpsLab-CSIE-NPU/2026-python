# R05. 數字基礎：四捨五入、進制、格式化（3.1–3.4）
# 主題：round / Decimal / math.fsum / format / bin-oct-hex

from decimal import Decimal, localcontext
import math

# ------------------------------------------------------------
# 3.1 round()：四捨五入
# ------------------------------------------------------------
# Python 的 round 採「銀行家捨入（round half to even）」：
# .5 會捨入到最接近的偶數，目的是減少大量統計時的偏差。
print(round(1.27, 1))      # 1.3
print(round(1.25361, 3))   # 1.254
print(round(0.5))          # 0（0 是偶數）
print(round(2.5))          # 2（2 是偶數）

# 第二個參數可用負值，表示對十位、百位、千位做四捨五入
# 這裡是「對百位」四捨五入。
a = 1627731
print(round(a, -2))  # 1627700

# ------------------------------------------------------------
# 3.2 浮點誤差與 Decimal 精確運算
# ------------------------------------------------------------
# 一般 float 用二進位表示，很多十進位小數無法精確表示。
print(4.2 + 2.1)  # 6.300000000000001

# Decimal 用十進位表示，適合金額等精度敏感場景。
da, db = Decimal("4.2"), Decimal("2.1")
print(da + db)  # 6.3

# localcontext 可在區塊內暫時設定精度，不影響全域。
with localcontext() as ctx:
    ctx.prec = 3
    print(Decimal("1.3") / Decimal("1.7"))  # 0.765

# math.fsum 在大量浮點加總時比 sum 更穩定。
print(math.fsum([1.23e18, 1, -1.23e18]))  # 1.0

# ------------------------------------------------------------
# 3.3 format()：數字格式化
# ------------------------------------------------------------
x = 1234.56789

# 固定小數位數
print(format(x, "0.2f"))   # '1234.57'

# 欄位寬度 + 右對齊
print(format(x, ">10.1f"))  # '    1234.6'

# 千分位
print(format(x, ","))      # '1,234.56789'
print(format(x, "0,.2f"))  # '1,234.57'

# 科學記號
print(format(x, "e"))      # '1.234568e+03'

# ------------------------------------------------------------
# 3.4 二進位 / 八進位 / 十六進位
# ------------------------------------------------------------
n = 1234

# 直接轉字串（含前綴）
print(bin(n), oct(n), hex(n))  # 0b10011010010 0o2322 0x4d2

# format 不帶前綴
print(format(n, "b"), format(n, "x"))  # 10011010010 4d2

# 由字串轉回十進位
print(int("4d2", 16), int("2322", 8))  # 1234 1234
