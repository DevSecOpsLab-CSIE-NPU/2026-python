# R20. ChainMap 合併映射（1.20）
# 此示例演示如何使用 ChainMap 將多個字典合併成一個邏輯視圖
# ChainMap 提供了一種高效的方式來搜索多個字典，而無需實際合併它們

# 導入 ChainMap 從 collections 模組
from collections import ChainMap

# ===== 建立多個字典 =====
# 建立第一個字典，包含 x=1 和 z=3
a = {'x': 1, 'z': 3}

# 建立第二個字典，包含 y=2 和 z=4
# 注意：兩個字典都有 'z' 鍵，但值不同（3 vs 4）
b = {'y': 2, 'z': 4}

# ===== 建立 ChainMap =====
# ChainMap(字典1, 字典2, ...)：將多個字典串聯成一個邏輯視圖
# ChainMap 不會建立新的字典，而是建立一個代理對象
# 它可以查詢多個字典，就像它們合併成一個一樣
c = ChainMap(a, b)
# ChainMap 會在括號中定義的順序中搜索鍵

# ===== 查詢鍵的行為 =====
# 訪問存在於第一個字典 a 中的鍵 'x'
# ChainMap 會依序搜索每個字典，直到找到該鍵
c['x']  # 結果：1（來自字典 a）

# 訪問在兩個字典中都存在的鍵 'z'
# ChainMap 返回找到的第一個字典中的值（按照初始化順序）
# 因為 a 在 b 之前，所以返回 a 中的 z 值
print(c['z'])  # 結果：3（來自字典 a，而不是字典 b 的 4）

# ===== ChainMap 的查詢順序 =====
# 1. 首先搜索 a（第一個字典）
# 2. 如果在 a 中找到該鍵，立即返回
# 3. 如果在 a 中找不到，繼續搜索 b（第二個字典）
# 4. 依此類推，直到找到鍵或耗盡所有字典

# ===== ChainMap 相比於 dict.update() 的優點 =====
# 1. 無需建立新字典，節省內存
# 2. 查詢快速：O(1) 時間複雜度
# 3. 保持原字典不變：不修改輸入的字典
# 4. 動態更新：如果原字典改變，ChainMap 會反映這些變化
# 5. 適合多層配置（如環境變量 + 用戶設置 + 默認設置）
