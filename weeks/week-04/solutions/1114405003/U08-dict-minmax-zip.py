# U8. 字典最值為何常用 zip(values, keys)（1.8）
# 此示例演示在字典中查找最小值或最大值時，如何同時獲得鍵和值
# 關鍵技巧：使用 zip(values, keys) 重新組織數據，讓 min/max 既比較值又返回鍵

# ===== 準備數據 =====
# 建立包含股票代碼和價格的字典
prices = {'A': 2.0, 'B': 1.0}

# ===== 方法 1：直接對字典使用 min（錯誤的方法）=====
# min(prices)：對字典直接使用 min 時，默認比較的是鍵而不是值
# 此操作返回字典鍵的最小值（按字母順序）
min(prices)            # 結果：'A'（因為 'A' < 'B' 在字母順序上）
# 問題：返回的是鍵，不是我們要的最小價格

# ===== 方法 2：只取值的最小值（部分解決）=====
# min(prices.values())：提取字典中所有值，找最小值
# prices.values() 返回 dict_values([2.0, 1.0])
# min() 會找出最小的值
min(prices.values())   # 結果：1.0（正確的最小價格）
# 問題：雖然找到了最小價格，但不知道這個最低價格對應哪個股票代碼
# 如果需要知道「哪個股票的價格最低」，就無法回答

# ===== 方法 3：使用 zip 同時獲得值和鍵（完整解決）=====
# zip(prices.values(), prices.keys())：將值和鍵配對
# - prices.values() 提供所有價格：[2.0, 1.0]
# - prices.keys() 提供所有代碼：['A', 'B']
# - zip 將它們配對：[(2.0, 'A'), (1.0, 'B')]

min(zip(prices.values(), prices.keys()))
# 結果：(1.0, 'B')
# 解釋：一個二元組，包含最小價格 1.0 和對應的股票代碼 'B'

# ===== 為什麼這樣做有效 =====
# 1. zip 重新組織數據為 (值, 鍵) 的二元組
# 2. min() 對二元組使用元組比較（元字典序）
# 3. 首先比較第一個元素（價格），找出最小價格
# 4. 如果第一個元素相同，才會比較第二個元素（鍵）
# 5. 自動返回整個二元組，包含最小值和對應的鍵

# ===== 詳細的元組比較過程 =====
# 給定：prices = {'A': 2.0, 'B': 1.0}
# 步驟 1：建立配對 zip(values, keys) → [(2.0, 'A'), (1.0, 'B')]
# 步驟 2：min() 比較二元組
#   - 比較 (2.0, 'A') 和 (1.0, 'B')
#   - 先比較第一個元素：2.0 > 1.0
#   - (1.0, 'B') 更小，選擇它
# 步驟 3：返回 (1.0, 'B')

# ===== 最大值的相同用法 =====
# 找最高價格和對應的股票：
max(zip(prices.values(), prices.keys()))
# 結果：(2.0, 'A')

# ===== 拆包結果 =====
# 如果想分別獲得最小價格和股票代碼：
min_price, min_stock = min(zip(prices.values(), prices.keys()))
# min_price = 1.0
# min_stock = 'B'

# ===== 與其他方法的比較 =====
# 方法 A：使用 min 和 key 參數（也是常見方法）
min_stock = min(prices, key=prices.get)  # 結果：'B'
# 優點：直觀，明確表達「按價格找最小的股票」
# 缺點：只返回鍵，需要再次查詢價格

# 方法 B：使用 zip（此例展示的方法）
min_price, min_stock = min(zip(prices.values(), prices.keys()))
# 優點：一次獲得值和鍵，無需額外查詢
# 缺點：需要拆包二元組

