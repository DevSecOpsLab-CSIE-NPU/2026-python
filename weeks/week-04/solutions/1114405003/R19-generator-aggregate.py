# R19. 轉換+聚合：生成器表達式（1.19）
# 此示例演示如何結合生成器表達式和聚合函數（sum、min、join 等）
# 來高效地進行數據轉換和聚合，而不需要建立中間列表

# ===== 範例 1：計算平方數之和 =====
# 建立包含整數的列表
nums = [1, 2, 3]

# 使用生成器表達式進行轉換和聚合
# sum(生成器表達式)：對生成器產生的所有值求和
# x * x：轉換步驟，計算每個數的平方
# 此方法不會建立中間列表，內存使用高效
sum(x * x for x in nums)
# 結果：1*1 + 2*2 + 3*3 = 14

# ===== 範例 2：將序列元素轉換為字符串並連接 =====
# 建立包含不同類型數據的元組（字符串、整數、浮點數）
s = ('ACME', 50, 123.45)

# 使用生成器表達式進行轉換：將每個元素轉換為字符串
# ','.join(生成器表達式)：使用逗號連接所有轉換後的值
# str(x)：將每個元素轉換為字符串（因為 join 只接受字符串）
# 此方法同樣不會建立中間列表
print(','.join(str(x) for x in s))

# 結果：'ACME,50,123.45'

# ===== 範例 3：找最小值（方法 1 - 直接比較值） =====
# 建立投資組合列表，每個字典包含股票名稱和股數
portfolio = [{'name': 'AOL', 'shares': 20}, {'name': 'YHOO', 'shares': 75}]

# 使用生成器表達式提取所有股票的股數，然後求最小值
# min(生成器表達式)：返回生成器產生的最小值
# s['shares']：提取字典中的 shares 欄位
min(s['shares'] for s in portfolio)
# 結果：20（AOL 擁有最少股數）

# ===== 範例 4：找最小值（方法 2 - 根據條件比較） =====
# 使用 min 函數的 key 參數根據自定義條件找最小值
# min(可迭代對象, key=函數)：根據 key 函數的結果而不是元素本身來比較
# lambda s: s['shares']：一個匿名函數，用於提取比較鍵
print(min(portfolio, key=lambda s: s['shares']))
# 結果：{'name': 'AOL', 'shares': 20}（返回整個字典，而不僅僅是股數值）

