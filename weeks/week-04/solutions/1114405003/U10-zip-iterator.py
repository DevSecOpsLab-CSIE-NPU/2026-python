# U10. zip 為何只能用一次（1.8）
# 此示例演示 zip() 函數返回的是一個迭代器，而不是列表
# 迭代器是一次性的，一旦被消耗就無法再使用
# 這與列表等容器類型不同，列表可以多次遍歷

# ===== 準備數據 =====
# 建立包含股票和價格的字典
prices = {'A': 2.0, 'B': 1.0}

# ===== 建立 zip 迭代器 =====
# zip(prices.values(), prices.keys()) 返回一個迭代器，而不是列表
# 迭代器是一個能產生一系列值的對象
# z 現在指向一個 zip 迭代器，內容為 [(2.0, 'A'), (1.0, 'B')]（但尚未實現）
z = zip(prices.values(), prices.keys())
# 此時 z 內部管理著一個指針，指向第一個元素

# ===== 第一次使用：min(z) =====
# min(z) 遍歷迭代器 z，取出所有元素，找出最小值
# 遍歷過程：
#   1. 取出 (2.0, 'A')
#   2. 取出 (1.0, 'B')
#   3. 迭代器到達末尾，停止
# 結果：(1.0, 'B')
min(z)  # OK（消耗掉迭代器）
# 問題：此時迭代器已經「耗盡」（exhausted），指針已到達末尾

# ===== 第二次嘗試：max(z) =====
# max(z) 嘗試遍歷迭代器 z，但迭代器已經沒有元素可供遍歷
# 因為迭代器没有「重置」的概念，無法回到開始位置
# max(z)  # 會失敗：因為 z 已經被消耗完
# 結果：max() 返回 None 或拋出 ValueError（取決於 Python 版本）
# 這不是一個錯誤，只是迭代器已經沒有更多元素了

# ===== 迭代器 vs 列表的區別 =====
# 比較：列表可以多次遍歷
# lst = [(2.0, 'A'), (1.0, 'B')]
# min(lst)  # OK
# max(lst)  # OK（列表未耗盡）

# 為什麼 zip 返回迭代器而不是列表：
# 1. 內存效率：迭代器是懶惰評估，不存儲所有值
# 2. 性能：不需要一次性建立整個列表
# 3. 無限序列支持：迭代器可以代表無限長的序列（如計數器）

# ===== 解決方案 1：轉換為列表 =====
# 如果需要多次使用 zip 的結果，轉換為列表
z_list = list(zip(prices.values(), prices.keys()))
# 現在 z_list = [(2.0, 'A'), (1.0, 'B')]（真實列表）
# min(z_list)  # OK
# max(z_list)  # OK（列表可重複使用）

# ===== 解決方案 2：多次調用 zip =====
# 如果只需要兩個操作，可以分別建立兩個 zip 迭代器
min(zip(prices.values(), prices.keys()))  # OK
max(zip(prices.values(), prices.keys()))  # OK（新的迭代器）

# ===== 理解迭代器的預期 =====
# 迭代器設計的本意是「單向流」：
# ```
# for item in z:  # 迭代器被遍歷一次
#     print(item)
# ```
# 使用 for 迴圈時，迭代器的一次性特性是預期的

# 然而，當混合使用 min()、max()、list() 等消耗迭代器的函數時，
# 需要留意迭代器是否已被消耗

# ===== 常見的迭代器函數 =====
# 以下函數都會消耗迭代器（遍歷所有元素）：
# - min(iterator)
# - max(iterator)
# - sum(iterator)
# - list(iterator)  # 轉換為列表
# - any(iterator)   # 檢查是否有真值
# - all(iterator)   # 檢查是否全為真值
# - next(iterator)  # 取出下一個元素（部分消耗）

# ===== 最佳實踐 =====
# 1. 如果需要多次遍歷，立即轉換為列表：
#    data = list(zip(...))
#
# 2. 如果只遍歷一次，直接使用迭代器（節省內存）
#
# 3. 在 for 迴圈中，迭代器的一次性特性是正常的
#
# 4. 混合使用 min、max、list 等時，要意識到迭代器被消耗
