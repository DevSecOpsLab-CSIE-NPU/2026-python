# U2. 星號解包為何能處理「不定長」且結果固定是 list（1.2）
# 此示例演示如何使用星號(*)進行解包，處理不定長的序列
# 星號變數會收集多餘的元素，且總是返回一個列表

# ===== 基本星號解包示例 =====
# 建立一個包含姓名和郵件的記錄元組
# 假設記錄中可能還有電話號碼，但在此例中沒有
record = ('Dave', 'dave@example.com')

# 使用星號(*)進行解包
# name：接收第一個元素（'Dave'）
# email：接收第二個元素（'dave@example.com'）
# *phones：星號變數，接收所有剩餘的元素（不定長）
name, email, *phones = record

# ===== 星號變數的特性 =====
# phones 現在的值是一個列表：[]（空列表）
# 重要：即使沒有剩餘元素，星號變數也會返回一個列表而不是 None
# phones == []  # True：這是一個空列表，不是 None
print(phones)  # 結果：[]

# ===== 為什麼星號變數總是返回列表 =====
# 1. 一致性：無論是否有剩餘元素，類型總是列表
# 2. 可迭代性：列表總是可以被迭代，即使為空
# 3. 易於擴展：可以輕鬆添加元素，無需檢查 None

# ===== 另一個有實際電話號碼的例子 =====
# 如果記錄包含多個電話號碼
record2 = ('Dave', 'dave@example.com', '123-4567', '456-7890')
name2, email2, *phones2 = record2
# 現在 phones2 = ['123-4567', '456-7890']（包含 2 個電話號碼的列表）

# ===== 星號解包的常見用法 =====
# 1. 收集不定長的數據：*phones 可以包含 0 個或多個元素
# 2. 提取前幾個和最後幾個元素
#    first, *middle, last = sequence
# 3. 忽略中間的元素
#    first, *_, last = sequence  （使用 _ 表示不關心的值）
