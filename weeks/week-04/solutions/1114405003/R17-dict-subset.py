# R17. 字典子集（1.17）
# 此示例演示如何從字典中提取子集，使用字典推導式根據不同條件過濾鍵值對

# ===== 方法 1：根據值的條件過濾 =====
# 建立包含股票代碼和價格的字典
prices = {'ACME': 45.23, 'AAPL': 612.78, 'IBM': 205.55}

# 使用字典推導式提取價格大於 200 的股票
# {鍵表達式: 值表達式 for 鍵, 值 in 字典.items() if 條件}
# prices.items() 返回字典的所有 (鍵, 值) 對
# if v > 200 條件只保留價格大於 200 的股票
p1 = {k: v for k, v in prices.items() if v > 200}
print(p1)
# 結果：{'AAPL': 612.78, 'IBM': 205.55}

# ===== 方法 2：根據鍵的集合過濾 =====
# 建立包含技術股代碼的集合
# 使用集合的原因：集合支持快速成員檢查（O(1) 時間複雜度），比列表更高效
tech_names = {'AAPL', 'IBM'}

# 使用字典推導式只保留指定集合中的股票
# if k in tech_names 條件檢查字典的鍵是否在 tech_names 集合中
# 集合的 in 操作很快速，適合用於大規模數據過濾
p2 = {k: v for k, v in prices.items() if k in tech_names}
# 結果：{'AAPL': 612.78, 'IBM': 205.55}
