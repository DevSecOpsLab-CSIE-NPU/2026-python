# U4. heap 為何能高效拿 Top-N（1.4）
# 此示例演示如何使用 heapq 模組實現堆（最小堆），
# 堆是一種特殊的數據結構，能在 O(log n) 時間內找到最小值

# 導入 heapq 模組，提供堆相關的高效操作
import heapq

# ===== 準備原始數據 =====
# 建立一個無序的列表，包含數個整數
nums = [5, 1, 9, 2]
print(nums)  # 結果：[5, 1, 9, 2]

# ===== 建立堆的副本 =====
# 複製原列表，因為 heapify 會原位修改列表的結構
# h = nums[:] 建立一個淺拷貝，原列表 nums 保持不變
h = nums[:]
print(h)  # 結果：[5, 1, 9, 2]（與原列表相同，順序未改）

# ===== 將列表轉換為堆結構 =====
# heapify(h)：將列表 h 轉換為堆結構（最小堆）
# - 不需要排序，而是重新組織元素以滿足堆的性質
# - 原位操作，時間複雜度為 O(n)
# - 轉換後看起來可能仍是 [1, 2, 9, 5]，但內部結構已變更
heapq.heapify(h)

# ===== 堆的核心性質 =====
# h[0] 永遠是堆中的最小值（這是最小堆的定義）
# 堆是一種二叉樹結構（但以列表形式存儲）：
# - 父節點 <= 子節點（最小堆的特性）
# - 索引關係：
#   - 節點 i 的左子節點：2*i + 1
#   - 節點 i 的右子節點：2*i + 2
#   - 節點 i 的父節點：(i - 1) // 2

# ===== 從堆中提取最小值 =====
# heappop(h)：移除並返回堆中的最小元素
# - 時間複雜度：O(log n)
# - 返回最小值
# - 自動調整堆結構，保持堆的性質
m = heappop(h)  # 每次 pop 都拿到目前最小值
# m = 1（第一次 pop 的結果是最小值）

# ===== 堆的高效性來源 =====
# 1. 不需要完全排序（排序是 O(n log n)）
# 2. 只維護最小堆的性質（最小值總在頂部）
# 3. 每次 pop 只需 O(log n) 時間
# 4. 提取 Top-N：N 次 pop，總時間 O(n + N log n)

# ===== 獲取 Top-N 最小值的方法 =====
# 方法 1：使用 heappop 循環 N 次
# for _ in range(N):
#     smallest = heappop(h)

# 方法 2：使用 heapq.nsmallest(N, nums)
# nsmallest(3, [5, 1, 9, 2])  →  [1, 2, 5]

# ===== 與排序的時間複雜度比較 =====
# 獲取最小的 3 個元素：
# - 排序方式：sorted(nums)[:3]  →  O(n log n)
# - 堆方式：heapq.nsmallest(3, nums)  →  O(n + 3 log n)
# 當 N << n 時，堆方式更高效
