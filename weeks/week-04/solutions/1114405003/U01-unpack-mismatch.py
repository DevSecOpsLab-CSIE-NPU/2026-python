# U1. 解包失敗的原因：變數數量 ≠ 元素數量（1.1）
# 此示例演示 Python 解包（unpacking）的基本規則
# 解包時，左邊的變數數量必須完全等於右邊可迭代對象的元素數量

# 建立包含兩個元素的元組
p = (4, 5)

# ===== 解包失敗的情況 =====
# 嘗試將 2 個元素解包給 3 個變數
# 這會導致 ValueError：not enough values to unpack (expected 3, got 2)
# 原因：變數個數（3 個：x, y, z）≠ 元素個數（2 個：4, 5）
# x, y, z = p  # ValueError：元素只有 2 個但變數要 3 個

# 列印元組內容查看
print(p)  # 結果：(4, 5)

# ===== 解包成功的情況 =====
# 將 2 個元素解包給 2 個變數
# 變數個數（2 個：x, y）= 元素個數（2 個：4, 5）
# 左邊的變數依序接收右邊對應位置的值
x, y = p  # x=4, y=5
# 現在 x=4, y=5

# ===== 解包的基本規則 =====
# 1. 左邊變數數量必須 等於 右邊元素數量
# 2. 多一個或少一個變數都會導致 ValueError
# 3. 解包按順序進行：第一個變數接收第一個元素，以此類推
# 4. 右邊可以是任何可迭代對象：元組、列表、字符串等



