# U3. deque(maxlen=N) 為何能保留最後 N 筆（1.3）
# 此示例演示如何使用 deque（雙端隊列）的 maxlen 參數
# maxlen 能自動限制隊列的大小，當超过時自動移除最早的元素

# 導入 deque 從 collections 模組
# deque 是一個優化的列表，支持在兩端高效地追加和移除元素
from collections import deque

# ===== 建立最大長度為 3 的 deque =====
# maxlen=3：限制 deque 最多只能包含 3 個元素
# 當新元素被追加且隊列已滿時，最左邊（最早的）元素會自動被移除
q = deque(maxlen=3)

# ===== 循環添加元素並觀察自動移除的行為 =====
# 逐個將 1, 2, 3, 4, 5 添加到 deque 中
for i in [1, 2, 3, 4, 5]:
    q.append(i)
    # 添加過程：
    # 第 1 步：append(1)  →  q = [1]
    # 第 2 步：append(2)  →  q = [1, 2]
    # 第 3 步：append(3)  →  q = [1, 2, 3]（已滿）
    # 第 4 步：append(4)  →  q = [2, 3, 4]（移除最左邊的 1）
    # 第 5 步：append(5)  →  q = [3, 4, 5]（移除最左邊的 2）

# 結果只剩 [3, 4, 5]
# 最初的 1 和 2 因為隊列已滿而自動被移除
print(q)  # 結果：deque([3, 4, 5], maxlen=3)

# ===== deque(maxlen=N) 的工作原理 =====
# 1. 當隊列未滿時，正常追加新元素
# 2. 當隊列已滿（元素數 == maxlen），新元素會推出最左邊的元素
# 3. 自動移除操作很快速，時間複雜度為 O(1)
# 4. 這是與普通列表的主要區別：list.append() 不會自動移除元素

