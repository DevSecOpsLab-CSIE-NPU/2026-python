# U9. groupby 為何一定要先 sort（1.15）

# groupby 的核心特性：只會把「連續相同 key」的項目分組。
# 若資料未排序，相同 key 若不相鄰，會被視為不同的分組。

from itertools import groupby
from operator import itemgetter

rows = [
    {'date': '07/02/2012', 'x': 1},
    {'date': '07/01/2012', 'x': 2},
    {'date': '07/02/2012', 'x': 3},
]

# 場景 1：沒排序的情況
# 資料順序為：07/02 -> 07/01 -> 07/02
# groupby 會這樣處理：
# 1. 遇到 '07/02'，開始第一組
# 2. 遇到 '07/01'（不同於 '07/02'），結束第一組，開始第二組
# 3. 遇到 '07/02'（與第二組 '07/01' 不同），結束第二組，開始第三組
#
# 結果：07/02 會被分成兩段分組！這通常不是我們想要的。
# 沒排序：07/02 會被分成兩段（因為 groupby 只看「連續」）
for k, g in groupby(rows, key=itemgetter('date')):
    print(list(g))

# 場景 2：先排序
# 排序後資料變成：07/01 -> 07/02 -> 07/02
# groupby 會這樣處理：
# 1. '07/01' 自成一組
# 2. 第一個 '07/02' 開始新分組
# 3. 第二個 '07/02' 繼續同組（因為連續且相同）
#
# 結果：同 date 的資料確實在一起，分組才是正確的。
# 排序後：同 date 才會連在一起，分組才正確
rows.sort(key=itemgetter('date'))
for k, g in groupby(rows, key=itemgetter('date')):
    print(list(g))

# 記憶體考量：
# groupby 不會預先掃描所有資料也不會建立完整字典。
# 它只在需要時才產生下一個分組，非常省記憶體。
# 但這種「盲目順序依賴」的設計，就是為何必須先排序的原因。
