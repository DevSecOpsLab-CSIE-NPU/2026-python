"""
R20. ChainMap 合併映射（1.20）

功能：將多個字典合併成一個統一的視圖
本質：不創建副本，而是對原字典的代理
場景：配置文件優先級、環境變數覆蓋、作用域鏈等
優點：內存高效、快速代理多個字典、支持動態修改
"""

from collections import ChainMap
"""
ChainMap 是 collections 模塊中的工具類

說明：
  - 将多個字典"鏈接"在一起形成一個統一視圖
  - 不是創建新字典，而是引用原字典
  - 查詢時按定義順序逐個搜索
  - 修改會影響源字典
"""

# ════════════════════════════════════════════════════════
# 創建 ChainMap 及基本訪問
# ════════════════════════════════════════════════════════

a = {'x': 1, 'z': 3}
"""
第一個字典 a
鍵值對：
  - x: 1
  - z: 3
"""

b = {'y': 2, 'z': 4}
"""
第二個字典 b
鍵值對：
  - y: 2
  - z: 4

注意：b 中的 z 值為 4（與 a 中的 z=3 不同）
"""

c = ChainMap(a, b)
"""
創建 ChainMap 實例

語法：ChainMap(dict1, dict2, dict3, ...)

說明：
  - 將多個字典按順序關聯
  - c 是一個"視圖"，代理 a 和 b
  - c 並未複製任何數據

ChainMap 的結構：
  c.maps = [a, b]
  → maps 是一個列表，存儲所有參與的字典
  → 按傳入順序排列

特點：
  1. 查詢優先級
     → 按字典順序搜索
     → 先查 a，再查 b
  
  2. 輕量級代理
     → 不占用額外內存存儲數據
     → 只維護對原字典的引用
  
  3. 動態代理
     → 按實時狀態查詢
     → 如果修改 a 或 b，ChainMap 的結果會隨即改變
"""

value_x = c['x']
"""
訪問鍵 'x'

查詢過程：
  1. 檢查 a 中是否有 'x'
     → a = {'x': 1, 'z': 3}
     → 'x' 存在 ✓
     → 返回 a['x'] = 1
  
  2. 不需要查詢 b（已在 a 中找到）

結果：value_x = 1

說明：
  - 返回找到的第一個鍵值
  - 查詢在 a 中成功，不再往下找
"""

value_z = c['z']
"""
訪問鍵 'z'

查詢過程：
  1. 檢查 a 中是否有 'z'
     → a = {'x': 1, 'z': 3}
     → 'z' 存在 ✓
     → 返回 a['z'] = 3
  
  2. 不需要查詢 b（已在 a 中找到）

結果：value_z = 3（來自字典 a）

重要特性：
  ✓ ChainMap 遵循 "第一個匹配原則"
  ✓ b 中的 z=4 被忽略
  ✓ 先出現的字典優先級更高

對比說明：

字典 a 中的 z: 3
字典 b 中的 z: 4
ChainMap(a, b) 的 z: 3（來自 a）
  → a 在前，所以 a['z'] 優先返回

ChainMap(b, a) 的 z: 4（來自 b）
  → 如果順序反轉，b 優先級更高
"""


# ════════════════════════════════════════════════════════
# ChainMap 的查詢規則
# ════════════════════════════════════════════════════════

"""
詳細的查詢機制：

1. 訪問存在的鍵
   c['x'] → 1          # 在 a 中找到
   c['y'] → 2          # 在 b 中找到
   c['z'] → 3          # 在 a 中找到（優先級高）

2. 訪問不存在的鍵
   c['not_exist']      # KeyError（兩個字典都沒有）

3. 遍歷所有鍵
   list(c.keys())      # ['x', 'z', 'y']
   → 返回所有字典中出現的鍵
   → 注意：重複的鍵（如 'z'）只返回一次

4. 遍歷所有值
   list(c.values())    # [1, 3, 2]
   → 返回按鍵順序對應的值
   → 如果鍵重複，返回第一個字典中的值

5. 遍歷所有項目
   list(c.items())     # [('x', 1), ('z', 3), ('y', 2)]
"""


# ════════════════════════════════════════════════════════
# ChainMap 的修改操作
# ════════════════════════════════════════════════════════

"""
ChainMap 的修改特性：

1. 添加新鍵
   c['new_key'] = 100
   → 添加到第一個字典 a 中
   → a 變成 {'x': 1, 'z': 3, 'new_key': 100}
   → b 不變

2. 修改現有鍵
   c['x'] = 999
   → 按查詢順序找到的第一個字典中修改
   → 修改 a 中的 x
   → a 變成 {'x': 999, 'z': 3}

3. 刪除鍵
   del c['x']
   → 刪除第一個字典中的鍵
   → a 變成 {'z': 3}
   → b 不變

重要規則：
  ✓ 所有寫操作（添加、修改、刪除）都只影響第一個字典
  ✓ 其他字典保持不變
  ✓ 這確保了修改的一致性和可預測性
"""


# ════════════════════════════════════════════════════════
# ChainMap vs 其他字典合併方式
# ════════════════════════════════════════════════════════

"""
使用場景與對比：

1. ChainMap（推薦用於需要動態代理）
   c = ChainMap(a, b)
   特點：
     ✓ 輕量級，不複製數據
     ✓ 保持原字典引用
     ✓ 修改會影響源字典
     ✓ 適合臨時代理多個字典
   缺點：
     ✗ 修改會影響源字典
     ✗ 不適合需要獨立副本的場景
   
   應用場景：
     - 環境變數 + 配置文件覆蓋
     - 全局變數 + 局部變數作用域
     - 多層配置優先級

2. 字典 update()（創建新副本）
   c = {**a, **b}  # Python 3.5+
   或
   c = a.copy()
   c.update(b)
   特點：
     ✓ 創建獨立副本
     ✓ 修改不影響源字典
     ✗ 占用額外內存
     ✗ 合併後失去動態性
   
   應用場景：
     - 需要固定的合併結果
     - 要修改合併結果不影響源字典

3. dict() 構造器
   c = dict(a, **b)
   特點：
     ✓ 簡潔
     ✗ 需要展開字典
     ✗ 只適合小規模字典

推薦：
  - 需要動態代理多個字典 → 用 ChainMap ✓
  - 需要獨立副本 → 用 update() 或 {**a, **b}
  - 臨時查詢多個字典 → ChainMap 最高效 ✓
"""


# ════════════════════════════════════════════════════════
# ChainMap 的常用方法
# ════════════════════════════════════════════════════════

"""
ChainMap 特有的方法：

1. maps - 訪問底層字典列表
   c.maps
   → [{'x': 1, 'z': 3}, {'y': 2, 'z': 4}]
   → 返回組成 ChainMap 的所有字典

2. parents - 獲取除第一個字典外的 ChainMap
   c.parents
   → ChainMap({'y': 2, 'z': 4})
   → 返回一個新的 ChainMap，包含其餘字典

3. keys(), values(), items() - 標準字典方法
   c.keys()   → dict_keys(['x', 'z', 'y'])
   c.values() → dict_values([1, 3, 2])
   c.items()  → dict_items([('x', 1), ('z', 3), ('y', 2)])

4. get(key, default) - 安全訪問
   c.get('x')           → 1
   c.get('not_exist')   → None
   c.get('not_exist', 0) → 0

5. pop(key) - 刪除並返回值
   c.pop('x')  → 1（並從 a 中移除）

6. clear() - 清空所有字典
   c.clear()   → a 和 b 都被清空
"""


# ════════════════════════════════════════════════════════
# 實踐應用示例：配置優先級系統
# ════════════════════════════════════════════════════════

"""
典型應用：多層配置覆蓋

# 系統默認配置
system_defaults = {
    'host': 'localhost',
    'port': 5432,
    'debug': False,
    'timeout': 30
}

# 用戶自定義配置（會覆蓋部分默認值）
user_config = {
    'host': '192.168.1.1',
    'debug': True
}

# 環境變數（最高優先級）
env_vars = {
    'port': 3306  # 覆蓋系統和用戶配置
}

# 創建優先級鏈
config = ChainMap(env_vars, user_config, system_defaults)

查詢順序（優先級從高到低）：
  1. 環境變數（env_vars）
  2. 用戶配置（user_config）
  3. 系統默認（system_defaults）

查詢結果：
  config['host']     → '192.168.1.1'  # 來自 user_config
  config['port']     → 3306           # 來自 env_vars（優先級最高）
  config['debug']    → True           # 來自 user_config
  config['timeout']  → 30             # 來自 system_defaults

優勢：
  - 清晰的優先級順序
  - 輕量級，無內存複製
  - 配置修改立即生效
  - 易於添加新的優先級層
"""


# ════════════════════════════════════════════════════════
# 最佳實踐與注意事項
# ════════════════════════════════════════════════════════

"""
最佳實踐：

1. 明確定義優先級順序
   config = ChainMap(env_vars, user_config, defaults)
   # 註釋說明：env_vars > user_config > defaults

2. 注意修改會影響源字典
   c = ChainMap(a, b)
   c['new'] = 100  # a 被修改了
   
   如果需要避免修改原字典：
   c = {**a, **b}  # 創建副本

3. 避免參與 ChainMap 的字典被外部修改
   a['x'] = 999
   # c 的查詢結果會隨即改變

4. 使用 parents 訪問其他層
   c = ChainMap(a, b, d)
   c.parents       # ChainMap(b, d)
   c.parents.maps  # [b, d]

常見錯誤：

✗ 錯誤：向 ChainMap 添加鍵影響了不該修改的字典
  c = ChainMap(read_only_dict, mutable_dict)
  c['new'] = 100  # 實際上修改了 read_only_dict！

✓ 正確：如果需要只修改特定字典
  c = ChainMap({}, mutable_dict, read_only_dict)
  # 添加新鍵到第一個獨立字典中

性能提示：
  - ChainMap 查詢性能：O(n)，n 為字典個數
  - 字典數量不多時幾乎無性能差異
  - 優先查詢的鍵應放在前面的字典中
"""
