"""
R16. 過濾：推導式 / generator / filter / compress（1.16）

功能：介紹四種 Python 過濾數據的方法
場景：從集合中篩選出符合條件的元素
選擇指南：
  - 列表推導式：需要立即得到完整列表，代碼簡潔
  - 生成器表達式：數據量大，只需逐個處理，節省內存
  - filter()：過濾邏輯複雜，用自定義函數判斷
  - compress()：根據布爾值序列進行選擇性過濾
"""

# ════════════════════════════════════════════════════════
# 方法1：列表推導式（List Comprehension）
# ════════════════════════════════════════════════════════

mylist = [1, 4, -5, 10]
# 原始列表：包含正數、負數

filtered_list = [n for n in mylist if n > 0]
"""
列表推導式語法：[表達式 for 元素 in 序列 if 條件]

說明：
  - 一行代碼完成過濾操作
  - 返回一個新列表，包含所有符合條件的元素
  - filter_list = [1, 4, 10]
  
優點：
  - 代碼簡潔易讀
  - 效率高（編譯優化）
  - 支持嵌套條件和複雜表達式

缺點：
  - 立即生成完整列表，占用內存
  - 適合數據量小的情況
"""


# ════════════════════════════════════════════════════════
# 方法2：生成器表達式（Generator Expression）
# ════════════════════════════════════════════════════════

pos = (n for n in mylist if n > 0)
"""
生成器表達式語法：(表達式 for 元素 in 序列 if 條件)
【區別：用圓括號 () 代替方括號 []】

說明：
  - 返回一個生成器對象，而不是完整列表
  - 按需計算（lazy evaluation），只在遍歷時才生成元素
  - pos = <generator object at 0x...>

優點：
  - 節省內存：適合大數據量
  - 支持無限序列
  - 可以鏈式組合多個生成器

缺點：
  - 無法重複遍歷（遍歷後迭代器已耗盡）
  - 需要轉換成列表才能多次使用

使用場景：
  - 數據管道式處理
  - 大文件逐行處理
  - 不知道完整數據量的迭代
"""

# 示例：逐個取出元素
for value in pos:
    pass  # 每次迭代時才計算一個值


# ════════════════════════════════════════════════════════
# 方法3：filter() 函數搭配判斷函數
# ════════════════════════════════════════════════════════

values = ['1', '2', '-3', '-', 'N/A']
# 字符串列表：包含有效數字、負數字符串、非數字內容

def is_int(val):
    """判斷字符串是否能轉換為整數
    
    參數：val (str) - 待判斷的字符串
    返回：True 如果能轉換為整數，False 否則
    
    邏輯：
      1. 嘗試調用 int(val) 進行轉換
      2. 如果成功，返回 True
      3. 如果拋出 ValueError（不能轉換），返回 False
    """
    try:
        int(val)  # 嘗試轉換為整數
        return True
    except ValueError:
        # 轉換失敗，說明不是有效整數
        return False


filtered_with_filter = list(filter(is_int, values))
"""
filter() 函數語法：filter(函數, 序列)

說明：
  - filter() 返回生成器，需要用 list() 轉換為列表
  - 對序列中的每個元素調用判斷函數
  - 只保留函數返回 True 的元素
  - 結果：['1', '2', '-3']

執行過程：
  1. '1' → is_int('1') → True ✓ 保留
  2. '2' → is_int('2') → True ✓ 保留
  3. '-3' → is_int('-3') → True ✓ 保留
  4. '-' → is_int('-') → False ✗ 丟棄
  5. 'N/A' → is_int('N/A') → False ✗ 丟棄

優點：
  - 適合複雜的過濾邏輯（自定義函數）
  - 支持複用同一個判斷函數
  - 返回生成器，節省內存

缺點：
  - 代碼相對冗長（需要定義判斷函數）
  - 不如推導式直觀
"""


# ════════════════════════════════════════════════════════
# 方法4：compress() 函數（根據布爾選擇器過濾）
# ════════════════════════════════════════════════════════

from itertools import compress
"""
compress() 是 itertools 模塊中的函數
功能：根據一個布爾值序列，從數據序列中選擇性地提取元素
語法：compress(data, selectors)
"""

addresses = ['a1', 'a2', 'a3']
# 要過濾的數據：地址列表

counts = [0, 3, 10]
# 原始值：每個地址對應的計數

more5 = [n > 5 for n in counts]
"""
創建布爾選擇器序列
語句：[n > 5 for n in counts]
步驟：
  1. 0 > 5 → False
  2. 3 > 5 → False
  3. 10 > 5 → True
結果：more5 = [False, False, True]

說明：
  - 每個布爾值對應 addresses 中的一個元素
  - True 表示"保留對應的地址"
  - False 表示"丟棄對應的地址"
"""


result = list(compress(addresses, more5))
"""
compress() 使用說明：list(compress(addresses, more5))

參數：
  addresses: 要過濾的數據序列
  more5: 布爾值序列（選擇器）

执行過程：
  索引 0: addresses[0]='a1', more5[0]=False → 丟棄
  索引 1: addresses[1]='a2', more5[1]=False → 丟棄
  索引 2: addresses[2]='a3', more5[2]=True → 保留 ✓

結果：result = ['a3']

使用場景：
  - 已經有現成的布爾值序列（如：查詢結果）
  - 需要根據一個布爾掩膜（mask）提取數據
  - 兩個序列長度必須相同

vs 列表推導式的區別：
  - 推導式：[a for a, m in zip(addresses, more5) if m]
  - compress()：list(compress(addresses, more5))
  compress() 更簡潔，效率也更高
"""


