"""
使用場景選擇指南：

1. 列表推導式：[n for n in mylist if n > 0]
   ✓ 最常用的方法
   ✓ 代碼簡潔，效率高
   ✓ 過濾邏輯簡單時使用

2. 生成器表達式：(n for n in mylist if n > 0)
   ✓ 數據量大時使用
   ✓ 只需逐個處理元素
   ✓ 節省內存

3. filter() 函數：filter(is_int, values)
   ✓ 過濾邏輯複雜
   ✓ 判斷函數可複用
   ✓ 已有判斷函數時使用

4. compress() 函數：compress(addresses, selector)
   ✓ 已有布爾掩膜
   ✓ 兩個序列需要一一對應
   ✓ 最高效的布爾選擇方式
"""
