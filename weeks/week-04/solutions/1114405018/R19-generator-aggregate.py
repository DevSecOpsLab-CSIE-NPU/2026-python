"""
R19. 轉換+聚合：生成器表達式（1.19）

功能：使用生成器表達式配合聚合函數進行數據轉換與聚合
場景：計算統計值、格式化輸出、數據篩選等
優點：內存高效、代碼簡潔、性能優秀
"""

# ════════════════════════════════════════════════════════
# 示例1：計算平方和
# ════════════════════════════════════════════════════════

nums = [1, 2, 3]
"""
原始數據：數字列表
內容：1, 2, 3
"""

result = sum(x * x for x in nums)
"""
生成器表達式 + sum() - 計算平方和

語法分析：sum(x * x for x in nums)

說明：
  1. (x * x for x in nums) 是生成器表達式
     → 生成序列：1*1, 2*2, 3*3 = 1, 4, 9
     → 注意：沒有外層方括號 []，是圓括號 ()
  
  2. sum(...) 聚合函數
     → 累加所有生成的值
     → 1 + 4 + 9 = 14
  
  3. 結果 result = 14

對比不同實現方式：

方式1：列表推導式（占用內存）
  result = sum([x * x for x in nums])
  → 先創建完整列表 [1, 4, 9]
  → 再求和

方式2：生成器表達式（推薦，節省內存）
  result = sum(x * x for x in nums)
  → 逐個生成值：1 → 4 → 9
  → 邊生成邊相加
  → 內存占用最小 ✓

性能對比：
  - 小數據量：性能差異不明顯
  - 大數據量：生成器節省大量內存（可能差 10 倍）
  - 結果相同，但生成器更高效

執行流程：
  1. 初始化 sum 累加器為 0
  2. 生成 1*1 = 1，累加 → 0 + 1 = 1
  3. 生成 2*2 = 4，累加 → 1 + 4 = 5
  4. 生成 3*3 = 9，累加 → 5 + 9 = 14
  5. 完成，返回 14
"""


# ════════════════════════════════════════════════════════
# 示例2：將元組轉換為逗號分隔的字串
# ════════════════════════════════════════════════════════

s = ('ACME', 50, 123.45)
"""
原始數據：混合類型的元組
內容：
  - 'ACME' (字符串)
  - 50 (整數)
  - 123.45 (浮點數)
"""

result_str = ','.join(str(x) for x in s)
"""
生成器表達式 + str.join() - 格式化輸出

語法分析：','.join(str(x) for x in s)

說明：
  1. (str(x) for x in s) 是生成器表達式
     → 將每個元素轉換為字符串
     → 生成：'ACME' → '50' → '123.45'
  
  2. ','.join(...) 字符串連接方法
     → 使用逗號作為分隔符連接所有字符串
     → 結果：'ACME,50,123.45'

執行步驟：
  1. str('ACME') → 'ACME'
  2. str(50) → '50'
  3. str(123.45) → '123.45'
  
  4. 使用 ',' 連接
     → 'ACME' + ',' + '50' + ',' + '123.45'
     → 'ACME,50,123.45'

join() 方法實現細節：
  - 比 + 運算符連接高效
  - 一次性分配內存
  - 推薦用於大量字符串連接

對比其他方式：

方式1：字符串連接（不推薦）
  result = ','.join([str(x) for x in s])
  → 先創建臨時列表
  → 再連接
  → 占用額外內存

方式2：生成器表達式（推薦）
  result = ','.join(str(x) for x in s)
  → 邊轉換邊連接
  → 內存占用更少 ✓

方式3：傳統 for 迴圈（冗長）
  parts = []
  for x in s:
      parts.append(str(x))
  result = ','.join(parts)
  → 代碼冗長，不推薦
"""


# ════════════════════════════════════════════════════════
# 示例3：查找最小值 - 方法1（直接比較）
# ════════════════════════════════════════════════════════

portfolio = [
    {'name': 'AOL', 'shares': 20},
    {'name': 'YHOO', 'shares': 75}
]
"""
投資組合數據：股票持股量列表
內容：
  - AOL: 20 股
  - YHOO: 75 股
"""

min_shares = min(s['shares'] for s in portfolio)
"""
方法1：使用生成器表達式提取要比較的值

語法分析：min(s['shares'] for s in portfolio)

說明：
  1. (s['shares'] for s in portfolio) 是生成器表達式
     → 從每個字典中提取 'shares' 字段
     → 生成序列：20 → 75
  
  2. min(...) 聚合函數
     → 找出最小值
     → min(20, 75) = 20
  
  3. 結果 min_shares = 20

執行過程：
  1. 遍歷第一個字典：{'name': 'AOL', 'shares': 20}
     → 提取 s['shares'] = 20
  
  2. 遍歷第二個字典：{'name': 'YHOO', 'shares': 75}
     → 提取 s['shares'] = 75
  
  3. 比較所有值：20 < 75
     → 返回最小值 20

適用場景：
  ✓ 只需要特定字段的最小值
  ✓ 代碼簡潔
  ✗ 無法獲取對應的完整記錄（字典）
"""


# ════════════════════════════════════════════════════════
# 示例4：查找最小值 - 方法2（key 函數）
# ════════════════════════════════════════════════════════

record_with_min = min(portfolio, key=lambda s: s['shares'])
"""
方法2：使用 key 參數指定比較邏輯

語法分析：min(portfolio, key=lambda s: s['shares'])

參數說明：
  - portfolio: 要比較的序列（原始字典列表）
  - key=lambda s: s['shares']: 比較鍵函數
    → lambda 匿名函數
    → s['shares'] 提取用於比較的值

說明：
  1. Python 根據 key 函數計算每個元素的比較值
     → AOL 記錄的比較值：s['shares'] = 20
     → YHOO 記錄的比較值：s['shares'] = 75
  
  2. 按比較值尋找最小者
     → 20 < 75
     → AOL 記錄是最小的
  
  3. 返回最小項的原始值（完整字典）
     → {'name': 'AOL', 'shares': 20}

結果對比：

方法1 結果：min_shares = 20
  - 只得到最小的股票數量值

方法2 結果：record_with_min = {'name': 'AOL', 'shares': 20}
  - 得到持股最少的完整記錄

執行過程：
  1. Python 評估 key 函數
     key(AOL記錄) = 20
     key(YHOO記錄) = 75
  
  2. 比較結果值：20 < 75
     → AOL 記錄的得分最低
  
  3. 返回得分最低的原始項
     → {'name': 'AOL', 'shares': 20}

適用場景：
  ✓ 需要返回完整記錄
  ✓ 比較邏輯複雜
  ✗ 只需要特定字段的簡單比較值（用方法1更經濟）

key 參數的其他用法：

# 忽略大小寫的字符串最小值
min(['Apple', 'banana', 'CHERRY'], key=str.lower)
→ 'Apple'

# 按絕對值找最小
min([-5, 3, -1], key=abs)
→ -1

# 按字符串長度找最小
min(['cat', 'dog', 'elephant'], key=len)
→ 'cat'

# 使用 itemgetter (性能優於 lambda)
from operator import itemgetter
min(portfolio, key=itemgetter('shares'))
→ 結果相同，但性能更好
"""


