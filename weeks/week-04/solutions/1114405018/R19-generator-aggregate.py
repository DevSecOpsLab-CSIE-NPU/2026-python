"""
常用的聚合函數列表：

1. sum(generator, start=0)
   sum(x**2 for x in range(10))
   # 計算 0² + 1² + 2² + ... + 9²

2. min(generator) 或 min(sequence, key=func)
   min(abs(x) for x in [-5, 3, -1])
   # 找絕對值最小的數

3. max(generator) 或 max(sequence, key=func)
   max(s['age'] for s in students)
   # 找年紀最大的學生年紀

4. all(generator)
   all(x > 0 for x in nums)
   # 檢查所有元素是否都為正數

5. any(generator) 
   any(name.startswith('A') for name in names)
   # 檢查是否有任何名字以 'A' 開頭

6. sorted(generator, key=func)
   sorted(portfolio, key=lambda s: s['shares'])
   # 按股票數量排序

生成器表達式的優勢：
  ✓ 內存高效（按需生成）
  ✓ 代碼簡潔
  ✓ 與聚合函數完美配合
  ✓ 可組合使用
"""


