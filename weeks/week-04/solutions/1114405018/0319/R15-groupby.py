"""
R15. 分組 groupby（1.15）

功能：使用 itertools.groupby() 進行數據分組
場景：根據指定的鍵（如日期）將相同值的數據分組在一起
應用：費用彙總、日誌按日期分析、數據分類統計等
"""

from itertools import groupby
# - groupby() 是一個迭代函數，用於將連續的相同元素分組
# - 注意：groupby() 要求輸入數據必須先按分組鍵排序
# - 返回一個迭代器，每次迭代產生 (鍵, 組迭代器) 的元組

from operator import itemgetter
# - itemgetter(key) 返回一個函數，用於從字典或元組中提取指定鍵的值
# - 例如：itemgetter('date') 等同於 lambda x: x['date']
# - 比 lambda 更高效，推薦用於簡單的鍵提取


# ════════════════════════════════════════════════════════
# 第1步：建立原始數據
# ════════════════════════════════════════════════════════

