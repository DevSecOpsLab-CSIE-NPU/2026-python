"""
R17. 字典子集（1.17）

功能：從原字典中篩選出符合條件的鍵值對，生成新字典
場景：數據過濾、參數選擇、配置提取等
方法：使用字典推導式進行過濾
"""

# ════════════════════════════════════════════════════════
# 示例1：根據值的條件過濾字典
# ════════════════════════════════════════════════════════

prices = {'ACME': 45.23, 'AAPL': 612.78, 'IBM': 205.55}
"""
原始字典：股票代碼 → 價格

內容分析：
  - ACME: 45.23 元
  - AAPL: 612.78 元（> 200）✓
  - IBM: 205.55 元（> 200）✓
"""

p1 = {k: v for k, v in prices.items() if v > 200}
"""
字典推導式語法：{key: value for key, value in dict.items() if 條件}

步驟分解：
  1. prices.items() 返回鍵值對的視圖
     → [('ACME', 45.23), ('AAPL', 612.78), ('IBM', 205.55)]
  
  2. for k, v in prices.items()
     → 遍歷每個鍵值對，將鍵賦給 k，值賦給 v
  
  3. if v > 200
     → 過濾條件：只保留價格 > 200 的項目
  
  4. {k: v for ...}
     → 構建新字典，鍵為 k，值為 v

結果：p1 = {'AAPL': 612.78, 'IBM': 205.55}

執行過程：
  ✗ ACME: 45.23 > 200? False → 丟棄
  ✓ AAPL: 612.78 > 200? True → 保留
  ✓ IBM: 205.55 > 200? True → 保留

說明：
  - 只有價格超過 200 的股票會被包含在新字典中
  - 新字典與原字典無關，修改新字典不會影響原字典
"""


# ════════════════════════════════════════════════════════
# 示例2：根據鍵的集合進行過濾
# ════════════════════════════════════════════════════════

tech_names = {'AAPL', 'IBM'}
"""
技術股票集合：只保留這兩個代碼的股票

集合類型說明：
  - 使用大括號 {} 和無冒號，表示集合（set）
  - 集合支持快速的成員檢查：k in tech_names O(1)
  - 比列表的 in 檢查 O(n) 更高效
"""

p2 = {k: v for k, v in prices.items() if k in tech_names}
"""
字典推導式 + 集合過濾：{key: value for key, value in dict.items() if key in set}

步驟分解：
  1. prices.items() 返回所有鍵值對
  
  2. for k, v in prices.items()
     → 遍歷每一項
  
  3. if k in tech_names
     → 過濾條件：只保留鍵在 tech_names 集合中的項目
     → ACME in {'AAPL', 'IBM'}? False
     → AAPL in {'AAPL', 'IBM'}? True ✓
     → IBM in {'AAPL', 'IBM'}? True ✓
  
  4. {k: v for ...}
     → 構建新字典

結果：p2 = {'AAPL': 612.78, 'IBM': 205.55}

執行過程：
  ✗ ACME in tech_names? False → 丟棄
  ✓ AAPL in tech_names? True → 保留
  ✓ IBM in tech_names? True → 保留

說明：
  - 兩個示例的結果相同，但條件不同
  - 示例1 按值過濾（價格 > 200）
  - 示例2 按鍵過濾（是否屬於特定集合）
"""


