"""
方法對比：

1. 字典推導式（推薦）
   p1 = {k: v for k, v in prices.items() if v > 200}
   ✓ 代碼簡潔，效率高
   ✓ 支持複雜的過濾邏輯
   ✓ Python 2.7+ 支持

2. 使用 filter() 和 lambda
   p1 = dict(filter(lambda item: item[1] > 200, prices.items()))
   ✓ 函數式編程風格
   ✗ 代碼相對冗長

3. 逐個添加（傳統方法）
   p1 = {}
   for k, v in prices.items():
       if v > 200:
           p1[k] = v
   ✓ 易於理解
   ✗ 代碼冗長，效率較低

4. 使用 dict.fromkeys()（針對特定場景）
   p2 = {k: prices[k] for k in tech_names if k in prices}
   ✓ 適合按現有鍵集合提取
   ✓ 可避免鍵不存在的錯誤

推薦：優先使用字典推導式，代碼簡潔高效
"""


