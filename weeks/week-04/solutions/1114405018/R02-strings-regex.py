"""
R02. 正則表達式：搜尋、替換、旗標（2.4–2.8）

功能概述：
  - 2.4: 使用 re.compile、findall、match、finditer 進行模式匹配
  - 2.5: 使用 re.sub 進行搜尋和替換、命名群組、re.subn 計次
  - 2.6: 使用 re.IGNORECASE 旗標進行大小寫不敏感匹配
  - 2.7: 使用非貪婪匹配 .*? 實現最短匹配
  - 2.8: 使用 re.DOTALL 旗標進行多行匹配

核心概念：
  - 捕獲群組：(...)
  - 分組訪問：m.group(0), m.groups(), m.group(1)
  - 反向引用：\1, \2 在替換中引用群組
  - 貪婪 vs 非貪婪：.* vs .*?
"""

import re

# ════════════════════════════════════════════════════════
# 2.4 匹配和搜尋
# ════════════════════════════════════════════════════════

text = "Today is 11/27/2012. PyCon starts 3/13/2013."
"""
測試文本：包含兩個日期
日期格式：MM/DD/YYYY
  - 11/27/2012 第一個日期
  - 3/13/2013 第二個日期
"""

datepat = re.compile(r"(\d+)/(\d+)/(\d+)")
"""
編譯正則表達式模式

正則表達式分析：r"(\d+)/(\d+)/(\d+)"
  - (\d+) 捕獲群組 1：一個或多個數字（月份）
  - / 字面雙斜線（日期分隔符）
  - (\d+) 捕獲群組 2：一個或多個數字（日期）
  - / 字面雙斜線
  - (\d+) 捕獲群組 3：一個或多個數字（年份）

符號詳解：
  - \d 匹配任何十進制數字 [0-9]
  - + 表示一個或多個（量詞）
  - (...) 捕獲群組，用於提取子字符串

re.compile() 的作用：
  - 將字符串模式編譯為可重複使用的正則表達式對象
  - 如果要多次使用同一模式，編譯可以提高性能
  - 返回一個 re.Pattern 對象

性能建議：
  - 如果只用一次模式 → 直接用 re.findall(pattern, text)
  - 如果多次用同一模式 → 先 compile，再多次調用 → 更快 ✓
"""

result1 = datepat.findall(text)
print(result1)
"""
findall() - 查找所有匹配

方法：pattern.findall(string)

說明：
  - 在 text 中查找所有符合模式的子字符串
  - 返回一個列表
  
返回值規則：
  - 如果模式有捕獲群組 → 返回群組內容的元組列表
  - 如果模式無捕獲群組 → 返回匹配的整個字符串列表

執行過程：
  1. 查找第一個日期：11/27/2012
     → 群組1: '11'（月份）
     → 群組2: '27'（日期）
     → 群組3: '2012'（年份）
     → 收集為元組：('11', '27', '2012')
  
  2. 查找第二個日期：3/13/2013
     → 群組1: '3'
     → 群組2: '13'
     → 群組3: '2013'
     → 收集為元組：('3', '13', '2013')

結果：[('11', '27', '2012'), ('3', '13', '2013')]

特點：
  - 找到所有匹配（不只是第一個）
  - 返回列表，適合進一步處理
"""

m = datepat.match("11/27/2012")
"""
match() - 從字符串開始匹配

方法：pattern.match(string)

說明：
  - 檢查字符串是否以模式開頭匹配
  - 只在字符串起始位置檢查
  - 如果匹配返回 Match 對象，否則返回 None

執行：
  1. 檢查 "11/27/2012" 是否以日期模式開頭
  2. 第一個字符就開始匹配 "11"（群組1）
  3. 然後是 "/" 和 "27"（群組2）等
  4. 完整匹配 "11/27/2012"
  5. 返回 Match 對象（表示成功）

vs search() 的區別：
  match()：只在字符串開始檢查
  search()：在整個字符串中搜尋
  
示例：
  pattern = re.compile(r"python")
  
  match("hello python"):   # None（python 不在開始）
  match("python hello"):   # Match（python 在開始）
  
  search("hello python"):  # Match（找到 python）
  search("python hello"):  # Match（找到 python）
"""

assert m is not None
"""
斷言：確保匹配成功

說明：
  - 驗證 m 不為 None（即匹配成功）
  - 如果 m 是 None，拋出 AssertionError
"""

result_info = (m.group(0), m.groups())
print(result_info)
"""
提取匹配結果：group(0) 和 groups()

方法詳解：

1. m.group(0)
   - 返回整個匹配的字符串
   - 等同於 m.group()（默認參數是 0）
   - 結果：'11/27/2012'

2. m.groups()
   - 返回所有捕獲群組的元組
   - 群組編號從 1 開始（0 是整個匹配）
   - 結果：('11', '27', '2012')

群組訪問方式：
  m.group(0) = '11/27/2012'     # 整個匹配
  m.group(1) = '11'              # 第一個群組（月份）
  m.group(2) = '27'              # 第二個群組（日期）
  m.group(3) = '2012'            # 第三個群組（年份）

執行流程：
  1. 匹配成功得到 Match 對象 m
  2. m.group(0) 返回完整匹配 '11/27/2012'
  3. m.groups() 返回所有子群組 ('11', '27', '2012')

實際輸出：('11/27/2012', ('11', '27', '2012'))
"""

for m in datepat.finditer(text):
    """
    finditer() - 遍歷所有匹配
    
    方法：pattern.finditer(string)
    
    說明：
      - 返回一個迭代器
      - 每次迭代產生一個 Match 對象
      - 節省內存（不一次性創建所有 Match 對象）
    
    vs findall() 的區別：
      
      findall()：
        - 返回所有結果的列表
        - 適合需要完整結果的場景
        - 有模式時返回群組元組
      
      finditer()：
        - 返回 Match 對象的迭代器
        - 適合隻需逐個處理結果的場景
        - 訪問詳細信息（如匹配位置）
        - 內存更高效 ✓
    
    執行過程：
      1. 第一次迭代：
         - m 是匹配 '11/27/2012' 的 Match 對象
         - m.groups() = ('11', '27', '2012')
         - 解包到：month='11', day='27', year='2012'
         - 打印：2012-11-27
      
      2. 第二次迭代：
         - m 是匹配 '3/13/2013' 的 Match 對象
         - m.groups() = ('3', '13', '2013')
         - 打印：2013-3-13
    """
    month, day, year = m.groups()
    print(f"{year}-{month}-{day}")


# ════════════════════════════════════════════════════════
# 2.5 搜尋和替換
# ════════════════════════════════════════════════════════

result2 = re.sub(r"(\d+)/(\d+)/(\d+)", r"\3-\1-\2", text)
print(result2)
"""
re.sub() - 搜尋和替換

函數：re.sub(pattern, repl, string)

參數說明：
  - pattern: 正則表達式模式
  - repl: 替換字符串（可以包含反向引用）
  - string: 要替換的文本

執行過程：
  1. 在 text 中查找所有符合 (\d+)/(\d+)/(\d+) 的日期
  2. 對每個匹配進行替換
  
反向引用說明：
  - \1 引用第一個捕獲群組
  - \2 引用第二個捕獲群組
  - \3 引用第三個捕獲群組
  - 替換模式 r"\3-\1-\2" 表示：群組3 + "-" + 群組1 + "-" + 群組2

替換詳解：

原文本：Today is 11/27/2012. PyCon starts 3/13/2013.

第一個匹配：11/27/2012
  - \1 = '11'（月份）
  - \2 = '27'（日期）
  - \3 = '2012'（年份）
  - 替換為：2012-11-27

第二個匹配：3/13/2013
  - \1 = '3'
  - \2 = '13'
  - \3 = '2013'
  - 替換為：2013-3-13

結果：Today is 2012-11-27. PyCon starts 2013-3-13.

說明：
  - re.sub() 替換所有匹配（不只是第一個）
  - 返回替換後的新字符串
  - 原文本不變
"""

# 命名群組
result3 = re.sub(
    r"(?P<month>\d+)/(?P<day>\d+)/(?P<year>\d+)",
    r"\g<year>-\g<month>-\g<day>",
    text,
)
print(result3)
"""
命名群組（Named Groups）- 更可讀的替換方式

模式分析：r"(?P<month>\d+)/(?P<day>\d+)/(?P<year>\d+)"
  - (?P<name>...) 命名群組語法
  - (?P<month>\d+) 創建名為 'month' 的群組
  - (?P<day>\d+) 創建名為 'day' 的群組
  - (?P<year>\d+) 創建名為 'year' 的群組

優點：
  - 比編號群組 \1, \2 更可讀
  - 代碼自文檔化
  - 易於維護

替換模式：r"\g<year>-\g<month>-\g<day>"
  - \g<name> 引用命名群組的語法（需要 \g）
  - vs \1 引用編號群組（可以不用 \g）

執行結果：
  - 功能與上面的 re.sub() 完全相同
  - 只是使用命名群組讓代碼更清楚

對比：

編號群組版本：
  re.sub(r"(\d+)/(\d+)/(\d+)", r"\3-\1-\2", text)
  - 緊湊但需要記住群組順序

命名群組版本：
  re.sub(r"(?P<month>\d+)/(?P<day>\d+)/(?P<year>\d+)",
         r"\g<year>-\g<month>-\g<day>", text)
  - 冗長但含義清晰 ✓ 推薦用於複雜模式
"""

# re.subn 回傳替換次數
newtext, n = re.subn(r"(\d+)/(\d+)/(\d+)", r"\3-\1-\2", text)
print(f"替換了 {n} 次")
"""
re.subn() - 替換並返回替換次數

函數：re.subn(pattern, repl, string)

說明：
  - 功能與 re.sub() 相同
  - 返回一個元組 (新字符串, 替換次數)
  - Python 2 中使用 tuple unpacking，Python 3 也支持

執行過程：
  1. 在 text 中查找所有日期模式
  2. 進行替換：
     - 11/27/2012 → 2012-11-27（第1次）
     - 3/13/2013 → 2013-3-13（第2次）
  3. 返回 ('Today is 2012-11-27. PyCon starts 2013-3-13.', 2)

結果解包：
  newtext = 'Today is 2012-11-27. PyCon starts 2013-3-13.'
  n = 2（進行了 2 次替換）

應用場景：
  - 需要知道替換了多少次
  - 驗證替換是否成功
  - 日誌記錄

輸出：
  替換了 2 次
"""


# ════════════════════════════════════════════════════════
# 2.6 忽略大小寫
# ════════════════════════════════════════════════════════

s = "UPPER PYTHON, lower python, Mixed Python"
"""
測試字符串：包含不同大小寫形式的 "python"
  - PYTHON（全大寫）
  - python（全小寫）
  - Python（首字母大寫）
"""

result4 = re.findall("python", s, flags=re.IGNORECASE)
print(result4)
"""
re.findall() with re.IGNORECASE 旗標

函數：re.findall(pattern, string, flags=旗標)

參數說明：
  - pattern: "python"（搜尋this字符串）
  - string: s（測試文本）
  - flags: re.IGNORECASE（旗標）

旗標詳解：
  - re.IGNORECASE 或 re.I
  - 忽略大小寫進行匹配
  - 模式中的大小寫無關緊要

執行過程：
  1. 搜尋模式 "python"（無視大小寫）
  2. 在 s 中查找所有匹配
  
匹配過程：
  - "UPPER PYTHON" → 找到 "PYTHON" ✓
  - "lower python" → 找到 "python" ✓
  - "Mixed Python" → 找到 "Python" ✓

重要特性：
  ✓ 查找時忽略大小寫
  ✗ 返回的仍是原始大小寫（不會轉換）

結果：['PYTHON', 'python', 'Python']

vs 不使用旗標：
  
  re.findall("python", s):
    # 只返回完全小寫的 ['python']
  
  re.findall("python", s, flags=re.IGNORECASE):
    # 返回所有大小寫形式 ['PYTHON', 'python', 'Python']

常用旗標：
  - re.IGNORECASE / re.I：大小寫不敏感
  - re.MULTILINE / re.M：啟用多行模式
  - re.DOTALL / re.S：. 匹配換行符
  - re.VERBOSE / re.X：允許註釋和空白
"""


# ════════════════════════════════════════════════════════
# 2.7 非貪婪（最短匹配）
# ════════════════════════════════════════════════════════

text2 = 'Computer says "no." Phone says "yes."'
"""
測試文本：包含兩對引號
  - 第一對：引號包圍 no.
  - 第二對：引號包圍 yes.
"""

greedy_result = re.compile(r'"(.*)"').findall(text2)
print(greedy_result)
"""
貪婪匹配：.* - 匹配盡可能多的字符

模式分析：r'"(.*)"'
  - " 開頭的引號
  - (.*) 捕獲群組
    → . 匹配除換行外的任何字符
    → * 表示 0 個或多個
    → 貪婪模式：盡可能匹配更多字符
  - " 結尾的引號

執行過程（貪婪）：
  1. 找到第一個 " 在位置 13
  2. 開始匹配 .*
  3. 貪婪模式會一直匹配到最後一個 "
  4. 最後一個 " 在位置 36
  5. 所以匹配："no." Phone says "yes."
  
  → 貪婪的 .* 包括了所有中間內容，從第一個 " 到最後一個 "

結果：['no." Phone says "yes.']
  → 一個巨大的匹配，而不是兩個分開的匹配

問題：
  - 不是我們想要的結果
  - 我們想分開提取 "no." 和 "yes."
  - 需要使用非貪婪匹配
"""

nongreedy_result = re.compile(r'"(.*?)"').findall(text2)
print(nongreedy_result)
"""
非貪婪匹配：.*? - 匹配盡可能少的字符

模式分析：r'"(.*?)"'
  - " 開頭的引號
  - (.*?) 捕獲群組
    → . 匹配除換行外的任何字符
    → *? 非貪婪量詞（*後面加?）
    → 這意味著：匹配盡可能少的字符
  - " 結尾的引號

執行過程（非貪婪）：
  1. 找到第一個 " 在位置 13
  2. 開始匹配 .*?
  3. 非貪婪模式試圖盡快結束匹配
  4. 找到下一個 " 在位置 19（"no." 後）
  5. 結束匹配，得到 "no."
  
  6. 繼續查找下一個 "
  7. 找到在位置 30
  8. 開始匹配 .*?
  9. 找到下一個 " 在位置 36
  10. 結束匹配，得到 "yes."

結果：['no.', 'yes.']
  → 兩個分開的匹配，符合預期

對比總結：

測試文本：'Computer says "no." Phone says "yes."'

貪婪匹配 .*：
  - 從第一個引號匹配到最後一個引號
  - 結果："no." Phone says "yes."（不正確）

非貪婪匹配 .*?：
  - 從第一個引號匹配到最近的下一個引號
  - 結果："no." 和 "yes."（正確）✓

非貪婪量詞列表：
  - *?  0 個或多個（最少）
  - +?  1 個或多個（最少）
  - ??  0 個或 1 個（最少）
  - {n,m}? n 到 m 個（最少）

何時使用非貪婪：
  - 提取被分隔符包圍的內容：引號、標籤等 ✓
  - 避免越過分隔符邊界
  - 大多數文本提取場景都應該用非貪婪 ✓
"""


# ════════════════════════════════════════════════════════
# 2.8 多行匹配（DOTALL）
# ════════════════════════════════════════════════════════

code = "/* this is a\nmultiline comment */"
"""
測試文本：多行註釋
內容：
  - 開始：/*
  - 文本：this is a
  - 換行符：\n（實際的換行）
  - 續文本：multiline comment
  - 結束：*/
"""

result5 = re.compile(r"/\*(.*?)\*/", re.DOTALL).findall(code)
print(result5)
"""
re.DOTALL 旗標 - 使 . 匹配換行符

模式分析：r"/\*(.*?)\*/"
  - /\* 字面的開始 /*
  - (.*?) 非貪婪匹配任何字符
    → 問題：默認 . 不匹配換行符 \n
    → 所以 .*? 會在換行符處停止
  - \*/ 字面的結束 */

沒有 re.DOTALL 時的問題：
  - 模式 /\*(.*?)\*/ 不帶旗標
  - . 不匹配 \n
  - 匹配會在換行符處停止
  - 無法匹配整個多行註釋
  - 結果：[] 或不完整匹配

加上 re.DOTALL 旗標：
  - 使 . 也能匹配換行符 \n
  - 現在 .*? 可以跨越多行匹配
  - 能夠完整捕獲多行內容

執行過程：
  1. 找到開始 /*
  2. 進入 (.*?) 匹配
  3. 匹配 'this is a'
  4. 遇到 \n（換行符）
  5. 由於 re.DOTALL，. 也能匹配 \n ✓
  6. 匹配 'multiline comment'
  7. 找到結束 */
  8. 完成匹配

結果：[' this is a\nmultiline comment ']
  → 包含中間的換行符 ✓

對比：

不使用 re.DOTALL：
  re.compile(r"/\*(.*?)\*/").findall(code)
  → [] 或 ['this is a']（只到換行符）

使用 re.DOTALL：
  re.compile(r"/\*(.*?)\*/", re.DOTALL).findall(code)
  → [' this is a\nmultiline comment '] ✓

替代方式：

方式1：使用 [\s\S] 代替 .
  re.compile(r"/\*([\s\S]*?)\*/").findall(code)
  → [\s\S] 匹配任何空白或非空白字符（包括 \n）

方式2：使用 DOTALL 旗標（推薦）
  re.compile(r"/\*(.*?)\*/", re.DOTALL).findall(code)
  → 更簡潔、含義清晰 ✓

常見场景：
  - 提取 HTML/XML 元素（可能跨多行）
  - 提取代碼註釋
  - 提取 JSON 對象（可能跨多行）
  → 都應該用 re.DOTALL ✓

旗標組合：
  - 可以組合多個旗標
  - re.IGNORECASE | re.DOTALL
  - re.I | re.M | re.S（使用別名更短）
"""
