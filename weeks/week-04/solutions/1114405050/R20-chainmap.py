# R20. ChainMap 合併映射（1.20）
"""
本範例示範 collections.ChainMap 如何將多個映射（如 dict）串聯在一起形成單一的「映射視圖」。

ChainMap 的特性：
- 查詢時會依照提供的映射順序搜尋，第一個映射中有的鍵會優先回傳
- 不會複製底層資料，僅建立一個「視圖」，修改底層 dict 會即時反映
- 主要用在設定覆寫（如從多個設定來源取得值）或在不同作用域之間查詢鍵
"""

from collections import ChainMap

# 兩個底層 dict，且它們有共同的鍵 'z'
a = {'x': 1, 'z': 3}
b = {'y': 2, 'z': 4}

# 將 a、b 串在一起，先查 a，再查 b
c = ChainMap(a, b)

# 取值時：先查 a，找到後就回傳；找不到才會到 b 查
c['x']  # 來自 a
c['z']  # 會取到 a 中的 z（值為 3），因為 a 在 b 前面
