# U1. 解包失敗的原因：變數數量 ≠ 元素數量（1.1）
"""
本範例示範 Python 序列解包（unpacking）時常見的錯誤情形：
變數個數與被解包的元素個數不一致，會導致 ValueError。

解包是一種方便的語法，可以同時將序列中的多個元素賦值給多個變數。
但必須確保變數數量與元素數量相同，否則會失敗。

以下提供如何正確解包以及如何避免錯誤的示例。
"""

p = (4, 5)

# 錯誤示範：變數多於元素，會發生 ValueError
# x, y, z = p  # ValueError：元素只有 2 個但變數要 3 個

# 正確示範：變數數量與元素數量相同
x, y = p

# 如果元素數量不定，可以使用 * 來捕獲剩餘元素
# 例如：
# x, *rest = (4, 5, 6)  # x=4, rest=[5, 6]
# *head, z = (4, 5, 6)  # z=6, head=[4, 5]
# x, *middle, z = (4, 5, 6)  # middle=[5]

