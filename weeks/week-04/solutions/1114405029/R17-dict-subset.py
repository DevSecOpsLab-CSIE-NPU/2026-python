# R17. 字典子集（1.17）

# 原始資料：股票名稱與價格的字典
prices = {'ACME': 45.23, 'AAPL': 612.78, 'IBM': 205.55}

# ── 根據「數值」過濾 ──────────────────────────────────
# 使用字典推導式建立一個新的字典 p1
# 條件：只保留價格 (v) 大於 200 的項目
# prices.items() 會同時產生 鍵(k) 與 值(v)
p1 = {k: v for k, v in prices.items() if v > 200}
# 結果：{'AAPL': 612.78, 'IBM': 205.55}

# ── 根據「鍵名」過濾 ──────────────────────────────────
# 定義一個包含目標股票名稱的集合 (set)
tech_names = {'AAPL', 'IBM'}

# 使用字典推導式建立一個新的字典 p2
# 條件：只保留股票名稱 (k) 出現在 tech_names 集合中的項目
p2 = {k: v for k, v in prices.items() if k in tech_names}
# 結果：{'AAPL': 612.78, 'IBM': 205.55}