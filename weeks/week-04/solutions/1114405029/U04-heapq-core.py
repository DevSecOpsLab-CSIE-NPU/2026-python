# U4. heap 為何能高效拿 Top-N（1.4）

import heapq

# ── 準備原始資料 ─────────────────────────────────────
nums = [5, 1, 9, 2]

# 複製一份資料，避免直接更動原始列表
h = nums[:]

# ── 建立堆疊結構 (Heapify) ────────────────────────────
# heapq.heapify(h)：將列表原地 (In-place) 轉換為最小堆疊結構。
# 此操作的時間複雜度為 O(N)，比完整排序 O(N log N) 更快。
# 轉換後，列表的順序雖然看起來不一定是全排序，但它保證了「堆疊屬性」。
heapq.heapify(h)

# ── 堆疊的核心性質 ────────────────────────────────────
# 在最小堆疊中，索引為 0 的元素（h[0]）永遠是整個堆疊中的最小值。
# 如果你需要頻繁獲取最小值，存取 h[0] 的時間複雜度僅為 O(1)。
# print(h[0])  # 此時為 1

# ── 提取最小值 (Heappop) ──────────────────────────────
# heapq.heappop(h)：彈出並回傳堆疊中的最小元素。
# 彈出後，heapq 會自動重新調整剩餘的元素，確保新的 h[0] 依然是最小值。
# 每次 pop 的時間複雜度為 O(log N)，對於處理海量資料取 Top-N 極具優勢。
m = heapq.heappop(h)  # 每次 pop 都拿到目前最小（此處 m 為 1）