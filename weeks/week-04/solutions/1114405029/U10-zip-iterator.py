# U10. zip 為何只能用一次（1.8）

prices = {'A': 2.0, 'B': 1.0}

# ── 建立 zip 迭代器 ──────────────────────────────────
# zip() 在 Python 3 中不會建立列表，而是建立一個「迭代器 (Iterator)」。
# 迭代器的特性是：它會記住目前處理到哪裡，並且「按需計算」資料。
z = zip(prices.values(), prices.keys())

# ── 第一次消耗 ──────────────────────────────────────
# 當呼叫 min(z) 時，Python 會從頭到尾走訪一次 z 中的所有元素。
# 此時，迭代器的指針已經移動到了末尾（已經被「掏空」了）。
min(z)  # 運作正常：回傳 (1.0, 'B')

# ── 第二次嘗試（會失敗） ──────────────────────────────
# 由於 z 是一個迭代器且已經被消耗完畢，此時 z 內部已經沒有任何資料。
# 如果接著執行 max(z)，它會像是在對一個「空序列」進行操作。
# 在 min/max 中對空序列操作會拋出 ValueError: max() arg is an empty sequence。

# max(z)  # 會失敗：因為 z 已經在上面 min(z) 執行時被消耗完了