# U8. 字典最值為何常用 zip(values, keys)（1.8）

# 原始資料：產品與價格的字典
prices = {'A': 2.0, 'B': 1.0, 'C': 1.0}

# ── 1. 直接對字典進行 min() ──────────────────────────
# 預設行為：Python 只會對「鍵 (Key)」進行比較
# 結果：回傳字母排序最小的鍵 'A'。這通常不是我們要的結果（我們要比的是價格）。
min(prices)            

# ── 2. 對 values() 進行 min() ────────────────────────
# 行為：只比較字典中的「數值」
# 結果：回傳最小的價格 1.0。
# 缺點：雖然知道了最低價，但遺失了「這是哪一項產品」的資訊。
min(prices.values())   

# ── 3. 使用 zip(values, keys) 的核心技巧 ──────────────
# 關鍵思維：透過 zip 將 (值, 鍵) 封裝成一個個元組 (Tuple)
# 這樣 min() 在比較時會：
#   (a) 先比較元組的第一個元素（價格）。
#   (b) 如果價格相同（如 B 和 C 都是 1.0），則會接著比較第二個元素（鍵名）。
# 結果：回傳 (1.0, 'B')，讓你一次獲得最小數值及其對應的鍵名。
min(zip(prices.values(), prices.keys()))

# 補充：zip() 創立的是一個迭代器，內容只能被消耗一次。