# R19. 轉換+聚合：生成器表達式（1.19）

# ── 1. 數值運算與聚合 ──────────────────────────────────
nums = [1, 2, 3]

# 在聚合函數中直接寫入推導式 (x * x for x in nums)
# 這是一個「生成器表達式」，它會逐個產生平方值並直接交給 sum() 計算
# 相比於 sum([x * x for x in nums])，這種寫法不需要額外佔用記憶體來存放中間列表
sum(x * x for x in nums)  # 結果：1 + 4 + 9 = 14

# ── 2. 字串格式化與合併 ────────────────────────────────
s = ('ACME', 50, 123.45)

# join() 只能接收字串序列。這裡透過生成器表達式將元組中的每個元素 (x)
# 即時轉換成字串 str(x)，再進行合併
','.join(str(x) for x in s)  # 結果：'ACME,50,123.45'

# ── 3. 處理物件/字典列表的極值 ────────────────────────
portfolio = [
    {'name': 'AOL', 'shares': 20}, 
    {'name': 'YHOO', 'shares': 75},
    {'name': 'GOOG', 'shares': 35}
]

# 方法 A：僅獲取特定欄位的最小值
# 這會遍歷 portfolio，提取所有 'shares' 的值，並回傳其中最小的數字
min(s['shares'] for s in portfolio)  # 結果：20

# 方法 B：獲取「包含最小值」的整個原始字典
# 使用 key 參數指定比較基準 (lambda)，這會回傳整筆資料項目
# 這在需要知道「哪一家公司的股份最少」時非常實用
min(portfolio, key=lambda s: s['shares'])  # 結果：{'name': 'AOL', 'shares': 20}