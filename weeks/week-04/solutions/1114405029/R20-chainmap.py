# R20. ChainMap 合併映射（1.20）

from collections import ChainMap

# ── 建立多個字典 ─────────────────────────────────────
a = {'x': 1, 'z': 3}  # 優先權較高的字典（例如：使用者設定）
b = {'y': 2, 'z': 4}  # 優先權較低的字典（例如：系統預設值）

# ── 使用 ChainMap 進行邏輯合併 ────────────────────────
# ChainMap 不會拷貝資料，而是建立一個清單來存放這些字典的引用。
# 當進行查找時，它會按照由左至右 (a -> b) 的順序搜尋。
c = ChainMap(a, b)

# 查詢存在於第一個字典 a 中的鍵
c['x']  # 結果：1

# 查詢同時存在於 a 與 b 中的鍵 'z'
# 根據優先權，ChainMap 會回傳「第一個找到」的值
c['z']  # 結果：3 (取到 a 的 z，b 的 z 被「遮蔽」了)

# 查詢只存在於第二個字典 b 中的鍵
# a 找不到時，會自動往後搜尋 b
# c['y']  # 結果：2