# U3. deque(maxlen=N) 為何能保留最後 N 筆（1.3）

from collections import deque

# ── 建立固定長度的雙向隊列 ─────────────────────────────
# maxlen=3：設定隊列的最大長度為 3。
# 當隊列滿了之後，新加入的元素會自動「擠掉」最舊的元素。
q = deque(maxlen=3)

# ── 模擬資料連續寫入 ─────────────────────────────────
# 依序存入 1, 2, 3, 4, 5
for i in [1, 2, 3, 4, 5]:
    q.append(i)
    # 過程分解：
    # append(1) -> [1]
    # append(2) -> [1, 2]
    # append(3) -> [1, 2, 3]
    # append(4) -> [2, 3, 4] (1 被擠出左側)
    # append(5) -> [3, 4, 5] (2 被擠出左側)

# 最後結果：q 內容為 [3, 4, 5]
# 這種特性非常適合用來保留「最後 N 個項目」的紀錄（例如 Log 紀錄或最近搜尋）。