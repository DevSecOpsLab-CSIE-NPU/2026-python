# R11. 命名切片 slice（1.11）

# 假設這是一條固定長度的資料記錄，內容包含空白填充的數值
record = '....................100 .......513.25 ..........'

# ── 1. 定義命名切片 ──────────────────────────────────
# 使用 slice(start, stop, step) 建立一個切片物件
# 這可以讓你的程式碼具備語意化，別人一看就知道這段範圍代表什麼
SHARES = slice(20, 23)  # 代表數量欄位的索引範圍 [20, 23)
PRICE = slice(31, 37)   # 代表價格欄位的索引範圍 [31, 37)

# ── 2. 使用切片物件 ──────────────────────────────────
# 與其寫 record[20:23]，不如使用命名後的 SHARES
# 這樣做的好處是：如果未來資料格式變動（例如欄位往後移 2 格），
# 你只需要修改 slice 定義處，不需要更動所有計算邏輯。

# 擷取字串並轉換為對應型別後進行計算
cost = int(record[SHARES]) * float(record[PRICE])

# 結果：100 * 513.25 = 51325.0