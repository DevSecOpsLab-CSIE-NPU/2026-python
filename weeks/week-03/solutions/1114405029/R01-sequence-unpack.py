# R1. 序列解包（1.1）

# ── 基礎解包 ──────────────────────────────────────────
# 定義一個包含兩個元素的元組
p = (4, 5)
# 將元組中的值依序分配給 x 和 y
x, y = p 
# 此時 x = 4, y = 5

# ── 列表與巢狀結構解包 ────────────────────────────────
# 定義一個包含多種型別（字串、整數、浮點數、元組）的列表
data = ['ACME', 50, 91.1, (2012, 12, 21)]

# 層次一：將最後一個元組當作一個整體賦值給 date
name, shares, price, date = data
# 此時 date = (2012, 12, 21)

# 層次二：巢狀解包 (Nested Unpacking)
# 直接在解包過程中拆解內層的元組，變數結構必須與資料結構完全對應
name, shares, price, (year, mon, day) = data
# 此時 year = 2012, mon = 12, day = 21

# ── 丟棄不需要的值（佔位符） ──────────────────────────
# 如果你只需要資料中的某幾個欄位，慣例上會使用底線 (_) 作為變數名稱
# 這告訴閱讀程式碼的人：這個位置的值我們並不打算使用
_, shares, price, _ = data
# 此處僅保留了份數 (shares) 與價格 (price)，忽略了名稱與日期