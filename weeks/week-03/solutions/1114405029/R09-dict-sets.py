# R9. 兩字典相同點：keys/items 集合運算（1.9）
#
# 這份程式示範：
# - dict 的 keys()/items() 視圖可以做「集合運算」
# - 可快速找出共同 key、差集 key、共同鍵值對
# - 再搭配字典推導式做資料過濾

# 兩個範例字典
a = {'x': 1, 'y': 2, 'z': 3}
b = {'w': 10, 'x': 11, 'y': 2}


# 交集（&）：找兩邊都存在的 key
# 結果會是 {'x', 'y'}
a.keys() & b.keys()

# 差集（-）：在 a 有、但 b 沒有的 key
# 結果會是 {'z'}
a.keys() - b.keys()

# items() 的交集：找兩邊完全一樣的 (key, value)
# 注意：key 一樣但 value 不同，不算相同 item
# 這裡共同 item 只有 ('y', 2)
a.items() & b.items()


# 字典推導式：從 a 建立一個新的過濾字典 c
# a.keys() - {'z', 'w'} 的意思：
# - 從 a 的 key 中排除 z、w
# - 但 w 原本不在 a，所以實際只會排除 z
# 最後 c 會是 {'x': 1, 'y': 2}
c = {k: a[k] for k in a.keys() - {'z', 'w'}}


# 讀懂這份程式的步驟：
# 1. 先看運算對象是 key 還是 item（影響比對粒度）。
# 2. 記住集合符號語意：
#    & = 交集（共同）
#    - = 差集（前者有、後者無）
# 3. items() 比的是整組 (key, value)，不是只看 key。
# 4. 推導式通常是「先算出要保留哪些 key，再回去取 a[k]」。
