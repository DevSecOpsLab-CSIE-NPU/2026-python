# R9. 兩字典相同點：keys/items 集合運算（1.9）

# 定義兩個測試字典
a = {'x': 1, 'y': 2, 'z': 3}
b = {'w': 10, 'x': 11, 'y': 2}

# ── 鍵 (Keys) 的集合運算 ──────────────────────────────
# a.keys() & b.keys()：找出兩個字典共同擁有的「鍵」 (交集)
# 結果：{'x', 'y'}
a.keys() & b.keys()

# a.keys() - b.keys()：找出存在於 a 但不存在於 b 的「鍵」 (差集)
# 結果：{'z'}
a.keys() - b.keys()

# ── 項目 (Items) 的集合運算 ────────────────────────────
# a.items() & b.items()：找出兩個字典中完全相同的「鍵值對」 (交集)
# 必須「鍵」與「值」都完全一致才會被納入
# 在此例中，'x' 的值不同 (1 vs 11)，只有 'y': 2 相同
# 結果：{('y', 2)}
a.items() & b.items()

# ── 字典推導式應用 ────────────────────────────────────
# 透過集合運算來過濾字典內容
# 這裡從 a 的鍵中移除 {'z', 'w'}，再根據剩餘的鍵建立新字典 c
# 邏輯：{'x', 'y', 'z'} - {'z', 'w'} = {'x', 'y'}
c = {k: a[k] for k in a.keys() - {'z', 'w'}}
# 結果：c = {'x': 1, 'y': 2}