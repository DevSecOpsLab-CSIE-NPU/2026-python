# R11. 命名切片 slice（Naming a Slice）—— Python Cookbook 1.11

# ── 問題 ─────────────────────────────────────────────────
# 固定格式的文字紀錄常用硬編碼索引切片取值，例如 record[20:23]
# 這種「魔術數字」難以閱讀，改了格式就要到處修正

record = '....................100 .......513.25 ..........'
#         0         1         2         3         4
#         0123456789012345678901234567890123456789012345678

# ── 用 slice() 物件給切片命名 ─────────────────────────────
# slice(start, stop) 和 [start:stop] 等效，但可以先命名再重複使用
SHARES = slice(20, 23)    # 第 20–22 個字元 = 股數欄位
PRICE  = slice(31, 37)    # 第 31–36 個字元 = 價格欄位

# 之後只需用語義化名稱操作，不用看「數字」猜意義
cost = int(record[SHARES]) * float(record[PRICE])
# int('100') * float('513.25') = 51325.0

# ── slice 物件的常用屬性 ─────────────────────────────────
# SHARES.start → 20
# SHARES.stop  → 23
# SHARES.step  → None（沒有指定步長時為 None）
