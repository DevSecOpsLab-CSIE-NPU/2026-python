# Understand（理解）- itertools 工具函數

from itertools import islice, dropwhile, takewhile, chain, permutations, combinations

# ============================================================================
# 區塊 1：islice() - 針對可迭代物件做「懶惰切片」
# ----------------------------------------------------------------------------
# 說明：
# 1. islice(iterable, start, stop) 類似 list 的切片 [start:stop]。
# 2. 但它不會一次建立完整清單，而是逐步取值，適合無限序列或大型資料。
# 3. 下面搭配 count() 產生器示範：從 0 開始無限遞增，最後只取第 5~9 個值。
# ============================================================================
print("--- islice() 切片 ---")


def count(n):
    # 建立一個無限產生器：每次 yield 目前數字後 +1。
    # 注意：這個函式本身不會停止，停止條件由外部（例如 islice）控制。
    i = n
    while True:
        yield i
        i += 1


# c 代表從 0 開始的無限序列：0, 1, 2, 3, ...
c = count(0)
# 取出索引位置 [5, 10) 的元素，也就是 5, 6, 7, 8, 9。
result = list(islice(c, 5, 10))
print(f"islice(c, 5, 10): {result}")

# ============================================================================
# 區塊 2：dropwhile() - 先丟棄前段符合條件的元素
# ----------------------------------------------------------------------------
# 說明：
# 1. dropwhile(predicate, iterable) 會從頭開始檢查。
# 2. 只要條件為 True，就持續丟棄元素。
# 3. 一旦第一次遇到 False，從該元素起「後面全部」都原樣保留（不再判斷丟棄）。
# ============================================================================
print("\n--- dropwhile() 條件跳過 ---")
nums = [1, 3, 5, 2, 4, 6]
# 遇到 5 時，x < 5 為 False，因此從 5 開始全部保留，結果為 [5, 2, 4, 6]。
result = list(dropwhile(lambda x: x < 5, nums))
print(f"dropwhile(x<5, {nums}): {result}")

# ============================================================================
# 區塊 3：takewhile() - 只取前段符合條件的元素
# ----------------------------------------------------------------------------
# 說明：
# 1. takewhile(predicate, iterable) 與 dropwhile 相反。
# 2. 會從頭開始取值，直到第一次條件為 False 就立刻停止。
# 3. 後面元素即使符合條件也不再被考慮。
# ============================================================================
print("\n--- takewhile() 條件取用 ---")
# nums = [1, 3, 5, 2, 4, 6]，碰到 5 時條件失敗，結果只會拿到 [1, 3]。
result = list(takewhile(lambda x: x < 5, nums))
print(f"takewhile(x<5, {nums}): {result}")

# ============================================================================
# 區塊 4：chain() - 串接多個可迭代物件
# ----------------------------------------------------------------------------
# 說明：
# 1. chain(a, b, c) 會依序把多個序列接成一條迭代流。
# 2. 常用於避免手動 for 迴圈合併資料。
# ============================================================================
print("\n--- chain() 串聯 ---")
a = [1, 2]
b = [3, 4]
c = [5]
print(f"chain(a, b, c): {list(chain(a, b, c))}")

# ============================================================================
# 區塊 5：permutations() - 排列（重視順序，不可重複取同一元素）
# ----------------------------------------------------------------------------
# 說明：
# 1. permutations(items) 預設長度 r = len(items)，即「全排列」。
# 2. permutations(items, r) 可指定排列長度。
# 3. 排列中順序不同視為不同結果，例如 ('a','b') 與 ('b','a') 不同。
# ============================================================================
print("\n--- permutations() 排列 ---")
items = ["a", "b", "c"]
print(f"permutations(items):")
for p in permutations(items):
    print(f"  {p}")

print(f"permutations(items, 2):")
for p in permutations(items, 2):
    print(f"  {p}")

# ============================================================================
# 區塊 6：combinations() - 組合（不重視順序，不可重複）
# ----------------------------------------------------------------------------
# 說明：
# 1. combinations(items, r) 取長度 r 的組合。
# 2. 與排列不同，('a','b') 與 ('b','a') 在組合中視為同一種。
# ============================================================================
print("\n--- combinations() 組合 ---")
print(f"combinations(items, 2):")
for c in combinations(items, 2):
    print(f"  {c}")

# ============================================================================
# 區塊 7：組合應用 - 兩位密碼列舉
# ----------------------------------------------------------------------------
# 說明：
# 1. permutations(chars, 2)：產生長度 2 的排列，不可重複字元（例如 AA 不會出現）。
# 2. combinations_with_replacement(chars, 2)：可重複，且不考慮順序。
#    例如 AB 與 BA 在此只會保留其中一種表示法。
# 3. 若要「可重複且順序有差」的完整密碼窮舉，可改用 product(chars, repeat=2)。
# ============================================================================
print("\n--- 組合應用：密碼窮舉 ---")
chars = ["A", "B", "1"]
print("2位數密碼:")
for p in permutations(chars, 2):
    print(f"  {''.join(p)}")

print("2位數密碼（可重複）:")
from itertools import combinations_with_replacement

for p in combinations_with_replacement(chars, 2):
    print(f"  {''.join(p)}")
