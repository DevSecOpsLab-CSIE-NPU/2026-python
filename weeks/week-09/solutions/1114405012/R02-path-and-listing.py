# R02. 路徑操作與目錄列舉（5.11 / 5.12 / 5.13）
# Bloom: Remember — 會用 pathlib 組路徑、檢查存在、列出檔案

import os
from pathlib import Path

# ============================================================================
# 區塊 1：組路徑（pathlib 與 os.path.join）
# ----------------------------------------------------------------------------
# 目標：
# 1. 學會使用 pathlib 的 / 運算子組路徑，讓程式跨平台（Windows/macOS/Linux）都能正確運作。
# 2. 認識常見路徑屬性：name、parent、suffix、stem。
# 3. 了解舊式寫法 os.path.join 仍可用，但 pathlib 可讀性通常更好。
# ============================================================================
# ── 5.11 組路徑：pathlib 是現代寫法 ────────────────────
# 用 / 串接路徑片段，Path 會依作業系統自動使用正確分隔符號。
base = Path("weeks") / "week-09"
# 印出完整相對路徑字串。
print(base)              # weeks/week-09（Windows 會自動變成反斜線）
# 取最後一層名稱（檔名或資料夾名）。
print(base.name)         # week-09
# 取上一層路徑。
print(base.parent)       # weeks
# 取副檔名；資料夾通常沒有副檔名，因此為空字串。
print(base.suffix)       # ''（無副檔名）

# 示範檔名拆解：stem 是主檔名，suffix 是副檔名。
f = Path("hello.txt")
print(f.stem, f.suffix)  # hello .txt

# 相容舊寫法：os.path.join 會依平台組合路徑。
# 在舊專案或混用程式庫時仍很常見。
print(os.path.join("weeks", "week-09", "README.md"))

# ============================================================================
# 區塊 2：存在判斷（exists / is_file / is_dir）
# ----------------------------------------------------------------------------
# 目標：
# 1. 在讀寫檔案前先檢查路徑是否存在，避免執行時例外。
# 2. 區分「存在的檔案」與「存在的資料夾」，避免把目錄當檔案打開。
# ============================================================================
# ── 5.12 存在判斷 ──────────────────────────────────────
p = Path("hello.txt")
# exists(): 路徑是否存在（不分檔案或資料夾）。
print(p.exists())    # 是否存在
# is_file(): 路徑存在且是一般檔案才會回傳 True。
print(p.is_file())   # 是否是檔案
# is_dir(): 路徑存在且是資料夾才會回傳 True。
print(p.is_dir())    # 是否是資料夾

missing = Path("no_such_file.txt")
# 實務上常先檢查不存在再略過，避免 open/read 時拋出 FileNotFoundError。
if not missing.exists():
    print(f"{missing} 不存在，略過讀取")

# ============================================================================
# 區塊 3：列出資料夾內容（listdir / glob / rglob）
# ----------------------------------------------------------------------------
# 目標：
# 1. 比較三種常見列舉方式：
#    - os.listdir: 列出指定目錄「當層」名稱（字串）。
#    - Path.glob: 依樣式比對指定目錄「當層」項目。
#    - Path.rglob: 遞迴搜尋包含子目錄。
# 2. 了解不同方法回傳型別與使用情境。
# ============================================================================
# ── 5.13 列出資料夾內容 ────────────────────────────────
here = Path(".")

# 只列當層：
# os.listdir() 回傳名稱字串，不含完整 Path 物件行為。
for name in os.listdir(here):
    print("listdir:", name)

# 只抓 .py（當層）：
# glob("*.py") 會回傳 Path 物件，方便後續再取屬性或做檔案操作。
for p in here.glob("*.py"):
    print("glob:", p)

# 遞迴抓所有 .py（含子資料夾）：
# rglob() 會往下層搜尋整棵目錄樹，常用於專案批次掃描。
# 此處 break 只是教學示範，避免輸出過多結果。
for p in Path("..").rglob("*.py"):
    print("rglob:", p)
    break  # 示範用，只印第一個
