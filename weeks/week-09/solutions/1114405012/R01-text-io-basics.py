# R01. 文本 I/O 基本式（5.1 / 5.2 / 5.3 / 5.17）
# Bloom: Remember — 會叫出 open/print 的基本參數

from pathlib import Path

# ============================================================================
# 區塊 1：讀寫文本檔
# ----------------------------------------------------------------------------
# 這一段示範最基礎的文字檔處理流程：
# 1. 用 open() 以文字模式寫入檔案，並且指定 encoding，避免跨平台編碼問題。
# 2. 再以文字模式讀回內容，示範「一次讀完整個檔案」與「逐行讀取」兩種方式。
# 3. 對小檔案可以直接 read()，但大檔案通常更適合逐行迭代，較省記憶體。
# ============================================================================
# ── 5.1 讀寫文本檔 ─────────────────────────────────────
# 寫入：mode='wt'（預設 't'），一定要指定 encoding
path = Path("hello.txt")
# 建立/覆蓋 hello.txt，使用文字模式（wt）寫入 Unicode 字串。
# 這裡指定 utf-8 是為了避免不同作業系統的預設編碼差異。
with open(path, "wt", encoding="utf-8") as f:
    f.write("你好，Python\n")
    f.write("第二行\n")

# 讀回：一次讀完 vs 逐行讀
# read() 會把整個檔案一次讀入記憶體，適合內容很小、需要整體處理的情況。
with open(path, "rt", encoding="utf-8") as f:
    print(f.read())  # 一次讀完（小檔才適合）

# 逐行讀取會一行一行產生字串，對大型檔案更友善，也方便做串流處理。
with open(path, "rt", encoding="utf-8") as f:
    for line in f:  # 大檔必備：逐行迭代
        print(line.rstrip())

# ============================================================================
# 區塊 2：print 導向檔案
# ----------------------------------------------------------------------------
# print() 不一定只能輸出到螢幕，只要用 file= 指定檔案物件，就能把內容寫進檔案。
# 這種寫法適合產生日誌、報表或簡單文字輸出，比手動 f.write() 更直覺。
# ============================================================================
# ── 5.2 print 導向檔案 ─────────────────────────────────
# 以文字模式建立 log.txt，接著把 print 的輸出導向到該檔案。
with open("log.txt", "wt", encoding="utf-8") as f:
    print("登入成功", file=f)
    print("使用者:", "alice", file=f)

# ============================================================================
# 區塊 3：調整分隔符與行終止符
# ----------------------------------------------------------------------------
# 這一段示範 print() 的兩個重要參數：
# 1. sep：控制多個輸出項目之間的分隔字元，預設是空白。
# 2. end：控制輸出結尾，預設是換行字元。若改成空字串或逗號，就能做出不同格式。
# 常見用途包括 CSV、日誌格式化、或自訂一行輸出內容。
# ============================================================================
# ── 5.3 調整分隔符與行終止符 ───────────────────────────
fruits = ["apple", "banana", "cherry"]
# 使用 sep="," 把清單內容輸出成逗號分隔格式；end="\n" 則保留正常換行。
with open("fruits.csv", "wt", encoding="utf-8") as f:
    print(*fruits, sep=",", end="\n", file=f)

# 這裡改成附加模式 at，接續在原檔尾端寫入。
# end="," 表示這次輸出不在結尾換行，而是先保留逗號，讓下一次輸出接在同一列。
with open("fruits.csv", "at", encoding="utf-8") as f:
    print("date", end=",", file=f)
    print("2026-04-23", file=f)

# 直接把 fruits.csv 的內容讀回並印出，方便檢查最終檔案長相。
print(Path("fruits.csv").read_text(encoding="utf-8"))
# apple,banana,cherry
# date,2026-04-23

# ============================================================================
# 區塊 4：文字模式 vs 位元組模式提醒
# ----------------------------------------------------------------------------
# 這一段是在提醒型別要對上：
# 1. 文字模式（wt / rt）處理的是 str。
# 2. 位元組模式（wb / rb）處理的是 bytes。
# 3. 若在文字模式下寫入 bytes，Python 會丟出 TypeError，這是常見錯誤。
# ============================================================================
# ── 5.17 文字模式 vs 位元組模式提醒 ────────────────────
# 'wt' 寫 str、'wb' 寫 bytes；寫錯型別會 TypeError
try:
    with open("bad.txt", "wt", encoding="utf-8") as f:
        f.write(b"bytes in text mode")  # ← 會錯
except TypeError as e:
    # 捕捉並顯示錯誤訊息，讓學習者知道文字模式不能直接寫入 bytes。
    print("錯誤示範:", e)
