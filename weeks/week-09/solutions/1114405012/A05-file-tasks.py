from pathlib import Path
from datetime import date

# ============================================================================
# 區塊 1：日記小工具（使用 'x' 模式避免覆蓋）
# ----------------------------------------------------------------------------
# 任務目標：
# 1. 依今天日期建立一個日記檔（例如 diary-2026-04-23.txt）。
# 2. 同一天只允許建立一次，避免重複執行時把舊內容覆蓋掉。
# 3. 透過例外處理 FileExistsError 來做友善提示。
#
# 關鍵觀念：
# - open(..., 'x') = exclusive create（僅在檔案不存在時建立）。
# - 若檔案已存在，會直接拋出 FileExistsError。
# ============================================================================
# ── 任務一：日記小工具（5.5 的 'x' 模式） ──────────────
# 規則：每天只能建一次；同一天重複執行要提示「已存在」。
# 取得今天日期字串（ISO 格式：YYYY-MM-DD），方便拼進檔名。
today = date.today().isoformat()          # 例如 2026-04-23
# 依日期產生今日日記檔名。
diary = Path(f"diary-{today}.txt")

try:
    # 'x' 模式：若檔案已存在就報錯，不會覆蓋既有內容。
    with open(diary, "x", encoding="utf-8") as f:   # 'x' = exclusive create
        # 寫入簡單的日記模板內容。
        f.write(f"# {today} 日記\n")
        f.write("今天學了檔案 I/O。\n")
    print(f"已建立 {diary}")
except FileExistsError:
    # 捕捉「已存在」情況，提示並保留原檔。
    print(f"{diary} 今天已寫過，保留原內容不覆蓋")

# ============================================================================
# 區塊 2：統計資料夾中所有 .py 檔案
# ----------------------------------------------------------------------------
# 任務目標：
# 1. 遞迴搜尋指定資料夾下的所有 Python 檔案。
# 2. 逐檔逐行累計：
#    - total：總行數
#    - nonblank：非空白行數
#    - defs：以 def 開頭的行數（粗略估計函式宣告數）
#
# 設計重點：
# - 使用 rglob("*.py") 做遞迴搜尋。
# - 逐行讀取可減少記憶體壓力，對大檔更友善。
# - errors="replace" 可在編碼異常時以替代字元處理，避免整個流程中斷。
# ============================================================================
# ── 任務二：統計某資料夾裡 .py 檔的行數 ────────────────
# 走訪目錄 → 逐檔逐行讀 → 累計三個數字
def count_py(folder: Path):
    # total: 全部行數；nonblank: 去掉空白後仍有內容的行；defs: 以 def 開頭的行。
    total, nonblank, defs = 0, 0, 0
    # 遞迴搜尋 folder 底下所有副檔名為 .py 的檔案。
    for p in folder.rglob("*.py"):
        # 文字模式讀取，遇到無法解碼字元時以替代符號處理，避免拋出例外中斷。
        with open(p, "rt", encoding="utf-8", errors="replace") as f:
            for line in f:
                total += 1
                # strip() 後可統一判斷空白行與是否為 def 開頭。
                s = line.strip()
                if s:
                    nonblank += 1
                # 粗略統計函式宣告行；此法不會解析語法樹，偏教學用途。
                if s.startswith("def "):
                    defs += 1
    return total, nonblank, defs

# 指定要統計的目標資料夾（相對路徑）。
target = Path("..") / ".." / "week-04" / "in-class"
# 先檢查目標目錄是否存在，避免搜尋時發生路徑錯誤。
if target.exists():
    total, nonblank, defs = count_py(target)
    print(f"{target}")
    print(f"  總行數       : {total}")
    print(f"  非空白行     : {nonblank}")
    print(f"  def 起頭行數 : {defs}")
else:
    # 若示範目錄不存在，輸出提示而不讓程式崩潰。
    print(f"示範目錄不存在：{target}")

