# U1. 解包失敗的原因：變數數量 ≠ 元素數量（1.1）

# 建立一個 tuple（元組）p
# 這個元組裡面只有 2 個元素，分別是 4 和 5
p = (4, 5)

# 正常情況下，若要進行解包（unpacking），
# 左邊的變數數量必須和右邊的元素數量完全一致
# 例如這個 p 有 2 個元素，就只能用 2 個變數來接
# 如果變數太多或太少，都會發生錯誤

# 下面這行程式碼是錯誤示範
# 因為 p 裡面只有 2 個元素，
# 但左邊卻想用 3 個變數 x、y、z 來接收
# 所以會產生 ValueError 錯誤
# x, y, z = p  # ValueError：元素只有 2 個但變數要 3 個

# 印出原始元組 p
print("原始元組 p：", p)

# 印出元組中的元素個數
print("元組 p 中的元素數量：", len(p))

print()  # 空一行，讓輸出結果更清楚

# 說明正確的解包概念
print("正確觀念：解包時，左邊變數數量必須等於右邊元素數量。")

# 說明這題為什麼會失敗
print("這題若寫成 x, y, z = p，會失敗。")
print("原因是：左邊有 3 個變數，但右邊的 p 只有 2 個元素。")

print()  # 空一行，讓輸出結果更清楚

# 額外示範正確作法
# 因為 p 有 2 個元素，所以用 2 個變數接收才正確
x, y = p

# 印出正確解包後的結果
print("正確解包示範：")
print("x =", x)
print("y =", y)