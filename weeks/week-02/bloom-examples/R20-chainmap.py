# R20. ChainMap 合併映射（1.20）

# ChainMap 可把多個 dict 串成一個「邏輯上合併」的映射檢視。
# 特色是：不會建立真正的新字典副本，而是查找時逐層往後找。
from collections import ChainMap

# 第一層映射（優先層）。
a = {'x': 1, 'z': 3}
# 第二層映射（次優先層）。
b = {'y': 2, 'z': 4}

# 建立 ChainMap，查找順序為 a -> b。
# 若同名鍵同時存在，會優先使用前面映射（a）的值。
c = ChainMap(a, b)

# 查找 x：a 中存在，直接回傳 1。
c['x']
# 查找 z：a 與 b 都有 z，但因 a 在前，所以取到 a 的 3。
c['z']  # 取到 a 的 z

# 補充觀念：
# - 若查找 y，會在 a 找不到後，繼續到 b，得到 2。
# - ChainMap 適合處理「多層設定來源」情境，
#   例如：命令列參數 > 環境變數 > 預設設定。
