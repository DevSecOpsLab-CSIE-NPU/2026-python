# ============================================================================
# R17. 字典子集提取（1.17）
# ============================================================================
# 本題展示如何使用字典推導式從現有字典中提取滿足條件的子集。
# 應用場景：
# 1. 按值過濾：提取所有價格超過 N 的股票
# 2. 按鍵過濾：只保留指定名單中的股票
# ============================================================================

print("【原始資料】")
prices = {'ACME': 45.23, 'AAPL': 612.78, 'IBM': 205.55}
print(f"股票價格字典: {prices}\n")

# ──────────────────────────────────────────────────────────────────────────
# 【方法 1】按值過濾：提取所有價格 > 200 的股票
# ──────────────────────────────────────────────────────────────────────────
print("【方法 1】按值過濾 - 提取高價股票")
print("條件：價格 > 200\n")

# 【語法】{k: v for k, v in dict.items() if condition}
# - k, v: 字典的鍵值對
# - .items(): 返回 (鍵, 值) 的迭代對
# - if condition: 過濾條件
#
# 執行流程：
# 1. 遍歷 prices 中的每個 (鍵, 值) 對
# 2. 檢查 v > 200 的條件
# 3. 如果條件為真，將 (k, v) 加入新字典

p1 = {k: v for k, v in prices.items() if v > 200}
print(f"過濾結果 p1: {p1}")
print(f"說明：只保留 AAPL (612.78) 和 IBM (205.55)\n")

# ──────────────────────────────────────────────────────────────────────────
# 【方法 2】按鍵過濾：只保留指定的股票名稱
# ──────────────────────────────────────────────────────────────────────────
print("【方法 2】按鍵過濾 - 提取特定公司")
print()

tech_names = {'AAPL', 'IBM'}  # 使用集合（set）作為篩選清單
print(f"篩選清單 tech_names: {tech_names}")
print(f"條件：鍵（股票代碼）在 tech_names 中\n")

# 執行流程：
# 1. 遍歷 prices 中的每個 (鍵, 值) 對
# 2. 檢查 k in tech_names 的條件
# 3. 如果條件為真，將 (k, v) 加入新字典

p2 = {k: v for k, v in prices.items() if k in tech_names}
print(f"過濾結果 p2: {p2}")
print(f"說明：只保留 AAPL 和 IBM\n")

# ──────────────────────────────────────────────────────────────────────────
# 【進階技巧】組合多個條件
# ──────────────────────────────────────────────────────────────────────────
print("【進階】組合多個條件")
print("-" * 50)

# 同時過濾：價格 > 100 AND 股票代碼在 tech_names 中
p3 = {k: v for k, v in prices.items() if v > 100 and k in tech_names}
print(f"條件：(價格 > 100) AND (代碼在 tech_names)")
print(f"結果 p3: {p3}")
print()

# ──────────────────────────────────────────────────────────────────────────
# 【效能對比】字典推導式 vs 迴圈
# ──────────────────────────────────────────────────────────────────────────
print("\n【效能對比】")
print("-" * 50)

print("\n方法 A：字典推導式（推薦）")
print("  p1 = {k: v for k, v in prices.items() if v > 200}")
print("  優點：簡潔、可讀性高、速度快")

print("\n方法 B：傳統迴圈")
print("  p1_loop = {}")
print("  for k, v in prices.items():")
print("      if v > 200:")
print("          p1_loop[k] = v")
print("  優點：易於理解複雜邏輯")
print("  缺點：代碼更冗長")

print("\n在 Python 中，推薦使用字典推導式來提取子集！")
