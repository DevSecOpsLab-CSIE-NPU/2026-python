# U10. zip 為何只能用一次（1.8）

# zip 回傳的是「迭代器」而非一個實際的列表。
# 迭代器的特點是「惰性計算」且「一次性」：
# - 只有在實際迭代時才產生值
# - 一旦走訪完就無法重新開始

prices = {'A': 2.0, 'B': 1.0}
# 建立一個 zip 迭代器，配對 prices 的值與鍵。
# 目前還沒有任何實際配對發生。
z = zip(prices.values(), prices.keys())

# 調用 min(z) 會迭代走訪整個 z，比較所有配對值找最小值。
# 此操作會「消耗」這個迭代器，即將內部指標移到末尾。
min(z)  # OK（消耗掉迭代器）

# 此時再調用 max(z) 會失敗，因為：
# - z 的迭代指標已在末尾
# - 迭代器無法重新開始或回到起始位置
# - max 得不到任何值，結果會報錯
# max(z)  # 會失敗：因為 z 已經被消耗完

