# R20. ChainMap 合併映射（1.20）
#
# ChainMap 可以把多個 dict（映射）串在一起，讓它們表現得像是一個大 dict。
# 查找鍵時會按照傳入 ChainMap 的順序，依序在每個映射中查找，
# 只要找到第一個匹配的鍵就會回傳該值。
#
# 這種機制常用於「覆寫」設定值（例如：預設值 + 使用者自定義值），
# 或是在不同命名空間之間做查詢（如函式的本地變數、全域變數、內建變數）。

from collections import ChainMap

# 兩個不同的映射（字典）
a = {'x': 1, 'z': 3}
b = {'y': 2, 'z': 4}

# 透過 ChainMap 將 a、b 串接成一個 "虛擬的" 映射。
# 查找鍵時會先查 a，找不到才會查 b。
c = ChainMap(a, b)

# 讀取鍵 'x'：只存在於 a 中，因此結果是 1
c['x']

# 讀取鍵 'z'：a 與 b 都有，但會先從 a 取得，結果是 3
c['z']  # 取到 a 的 z
