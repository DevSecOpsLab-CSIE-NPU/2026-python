# R9. 兩字典相同點：keys/items 集合運算（1.9）
# 本程式示範如何使用集合運算來比較兩個字典的鍵和鍵值對
# 這包括找出共同的鍵、不同的鍵，以及共同的鍵值對
# 這些運算對於數據分析和比較字典內容非常有用

# 定義第一個字典 a，包含鍵值對 'x':1, 'y':2, 'z':3
# 這是一個簡單的字典，用來模擬數據
a = {'x': 1, 'y': 2, 'z': 3}

# 定義第二個字典 b，包含鍵值對 'w':10, 'x':11, 'y':2
# 注意 'x' 和 'y' 在兩個字典中都存在，但值可能不同
b = {'w': 10, 'x': 11, 'y': 2}

# 使用集合運算 & 計算兩個字典鍵的交集
# a.keys() 返回 a 的鍵集合，b.keys() 返回 b 的鍵集合
# 交集運算會返回兩個集合中共同的元素，即 'x' 和 'y'
a.keys() & b.keys()

# 使用集合運算 - 計算 a 的鍵減去 b 的鍵
# 這會返回只在 a 中存在但不在 b 中的鍵，即 'z'
a.keys() - b.keys()

# 使用集合運算 & 計算兩個字典鍵值對的交集
# a.items() 返回 a 的鍵值對元組集合，如 {('x',1), ('y',2), ('z',3)}
# b.items() 返回 b 的鍵值對元組集合，如 {('w',10), ('x',11), ('y',2)}
# 交集運算會返回鍵和值都相同的鍵值對，即 ('y',2)
a.items() & b.items()

# 使用字典推導式創建新字典 c
# 從 a 的鍵中減去集合 {'z', 'w'}，得到 {'x', 'y'}
# 然後為每個鍵創建鍵值對，值來自 a[k]
# 這會創建一個新的字典，排除鍵 'z' 和 'w'
c = {k: a[k] for k in a.keys() - {'z', 'w'}}
