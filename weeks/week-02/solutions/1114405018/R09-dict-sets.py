"""R9. 兩字典相同點：keys / items 集合運算（1.9）

這個範例示範 Python 字典檢視圖（keys/items）可以直接做集合運算：
1. 找交集：兩個字典共同擁有的 key 或 key-value
2. 找差集：某個字典獨有的 key
3. 用集合運算快速過濾字典
"""

# 兩個字典資料，故意讓它們有部分重疊、部分不同
a = {'x': 1, 'y': 2, 'z': 3}
b = {'w': 10, 'x': 11, 'y': 2}

# keys() 會回傳字典的鍵檢視圖，可以直接和另一個鍵集合做交集
# 交集結果是兩個字典共同擁有的 key
a.keys() & b.keys()

# 差集：a 有但 b 沒有的 key
a.keys() - b.keys()

# items() 會回傳 (key, value) 的檢視圖
# 因為它是可做集合運算的，所以可以找出完全相同的鍵值對
a.items() & b.items()

# 字典推導式：只保留 a 裡面那些不在 {'z', 'w'} 中的鍵
# a.keys() - {'z', 'w'} 會先算出要保留的 key 集合，再用 for 產生新字典
c = {k: a[k] for k in a.keys() - {'z', 'w'}}
