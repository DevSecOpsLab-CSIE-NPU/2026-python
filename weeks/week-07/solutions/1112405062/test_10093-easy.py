"""
===============================================================================
UVA 10093 - 炮兵部署問題 單元測試（簡單版本）
===============================================================================

題目說明：
    在 N×M 的網格地圖上部署炮兵部隊。
    - 山地 (H)：不能部署炮兵
    - 平原 (P)：每格最多可部署一支炮兵部隊
    - 攻擊範圍：橫向左右各兩格，縱向上下各兩格（不受地形影響）
    - 限制：任何兩支炮兵不能互相攻擊

測試目的：
    驗證 max_artillery 函式能否正確計算最多能部署的炮兵數量。

測試策略：
    1. 基本邊界測試：最小輸入、邊界值
    2. 功能測試：簡單網格、混合地形
    3. 壓力測試：大尺寸網格

===============================================================================
"""

# 匯入待測試的函式
# max_artillery(N, M, grid) 會回傳最多能部署的炮兵數量
from solution_10093_easy import max_artillery

# 匯入 unittest 框架
import unittest


class TestArtillery(unittest.TestCase):
    """
    測試類別：炮兵部署功能測試

    包含多個測試案例，驗證不同情況下的計算結果是否正確。
    """

    # ========================================================================
    # 基本邊界測試
    # ========================================================================

    def test_single_plain(self):
        """
        測試案例 1：單一格平原

        輸入：
            - N = 1, M = 1
            - grid = ["P"]（只有一個平原格）

        預期結果：1

        說明：
            這是最小的合法輸入。只有一個格子且是平原，
            沒有任何限制，可以放一台炮兵。
        """
        self.assertEqual(max_artillery(1, 1, ["P"]), 1)

    def test_single_mountain(self):
        """
        測試案例 2：單一格山地

        輸入：
            - N = 1, M = 1
            - grid = ["H"]（只有一個山地格）

        預期結果：0

        說明：
            山地不能放置炮兵，所以答案是 0。
        """
        self.assertEqual(max_artillery(1, 1, ["H"]), 0)

    # ========================================================================
    # 簡單網格測試
    # ========================================================================

    def test_two_rows_plain(self):
        """
        測試案例 3：2×1 全部平原

        輸入：
            - N = 2, M = 1
            - grid = ["P", "P"]（兩列，各一格，都是平原）

        預期結果：1

        說明：
            雖然有兩個格子，但炮兵的縱向攻擊範圍是上下各 2 格。
            因此相邻的兩格不能同時放炮兵，只能放 1 台。
        """
        self.assertEqual(max_artillery(2, 1, ["P", "P"]), 1)

    def test_all_mountains(self):
        """
        測試案例 4：2×2 全部山地

        輸入：
            - N = 2, M = 2
            - grid = ["HH", "HH"]（全部都是山地）

        預期結果：0

        說明：
            所有格子都是山地，不能放置任何炮兵。
        """
        self.assertEqual(max_artillery(2, 2, ["HH", "HH"]), 0)

    # ========================================================================
    # 中等尺寸測試
    # ========================================================================

    def test_3x3_plain(self):
        """
        測試案例 5：3×3 全部平原

        輸入：
            - N = 3, M = 3
            - grid = ["PPP", "PPP", "PPP"]

        預期結果：>= 0（有合法解即可）

        說明：
            測試中等尺寸的完整平原網格。
            我們不需預設正確答案，只需確認函式能正常運算。
        """
        self.assertGreaterEqual(max_artillery(3, 3, ["PPP", "PPP", "PPP"]), 0)

    def test_mixed(self):
        """
        測試案例 6：混合地形（部分山地、部分平原）

        輸入：
            - N = 3, M = 3
            - grid = ["PHP", "PPP", "PPP"]
              （第一列：平原、山地、平原）

        預期結果：>= 0（有合法解即可）

        說明：
            測試有山地干擾時的情況。
            山地位置不能放炮兵，會影響整體部署策略。
        """
        self.assertGreaterEqual(max_artillery(3, 3, ["PHP", "PPP", "PPP"]), 0)

    # ========================================================================
    # 大尺寸測試
    # ========================================================================

    def test_wide(self):
        """
        測試案例 7：寬網格（M = 10，最大寬度）

        輸入：
            - N = 2, M = 10
            - grid = ["PPPPPPPPPP", "PPPPPPPPPP"]

        預期結果：>= 0（能正常運算即可）

        說明：
            M = 10 是題目規定的最大值。
            此時狀態數為 2^10 = 1024，是複雜度較高的情況。
        """
        self.assertGreaterEqual(max_artillery(2, 10, ["PPPPPPPPPP", "PPPPPPPPPP"]), 0)

    def test_narrow(self):
        """
        測試案例 8：窄網格（M = 1，最小寬度）

        輸入：
            - N = 5, M = 1
            - grid = ["P", "P", "P", "P", "P"]

        預期結果：>= 0（能正常運算即可）

        說明：
            M = 1 時，每行只能放最多 1 台炮兵（因為同行內距離需 >= 3）。
            由於縱向攻擊範圍是上下 2 格，所以最多只能放 1 台。
        """
        self.assertGreaterEqual(max_artillery(5, 1, ["P", "P", "P", "P", "P"]), 0)

    # ========================================================================
    # 複雜地形測試
    # ========================================================================

    def test_alternating(self):
        """
        測試案例 9：交錯地形（P 和 H 交錯排列）

        輸入：
            - N = 4, M = 4
            - grid = ["PHPH", "HPHP", "PHPH", "HPHP"]
              （P 和 H 交替排列）

        預期結果：>= 0（能正常運算即可）

        說明：
            這是較複雜的地形，適合測試演算法的穩定性。
            交錯的地形會限制炮兵的放置位置。
        """
        self.assertGreaterEqual(
            max_artillery(4, 4, ["PHPH", "HPHP", "PHPH", "HPHP"]), 0
        )


# ========================================================================
# 主程式入口
# ========================================================================
if __name__ == "__main__":
    """
    執行測試
    
    verbosity=2 表示詳細輸出，會顯示每個測試案例的名稱和結果。
    """
    unittest.main(verbosity=2)
