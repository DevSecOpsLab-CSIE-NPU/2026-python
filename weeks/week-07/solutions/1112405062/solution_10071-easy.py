"""
================================================================================
UVA 10071 - 六元組求和問題（簡單版）
================================================================================

題目說明：
    給定一個整數集合 S，其元素均介於 -30000 到 30000 之間（含首尾）。
    請計算满足条件的六元組數量：a + b + c + d + e = f，
    其中 a、b、c、d、e、f 均屬於 S（可重複使用）。

================================================================================
簡單解題思路
================================================================================

直接暴力法（適合理解，但 N 太大時會超時）：
    - 用六層迴圈列舉 a, b, c, d, e, f
    - 檢查是否满足 a + b + c + d + e == f

配對法（簡單好記）：
    - 計算所有 (a+b) 的可能和
    - 計算所有 (c+d+e) 的可能和
    - 對於每個 f，檢查 (a+b) + (c+d+e) = f 是否成立

================================================================================
"""

from typing import List


def count_six_tuples(S: List[int]) -> int:
    """
    計算满足 a + b + c + d + e = f 的六元組數量

    簡單版本：使用配對法，容易理解
    """
    # 移除重複元素
    S_list = list(set(S))
    N = len(S_list)

    # =========================================================================
    # 步驟 1：計算所有 (a+b) 的可能和
    # =========================================================================
    sum_ab = {}
    for i in range(N):
        for j in range(N):
            s = S_list[i] + S_list[j]
            sum_ab[s] = sum_ab.get(s, 0) + 1

    # =========================================================================
    # 步驟 2：計算所有 (c+d+e) 的可能和
    # =========================================================================
    sum_cde = {}
    for i in range(N):
        for j in range(N):
            for k in range(N):
                s = S_list[i] + S_list[j] + S_list[k]
                sum_cde[s] = sum_cde.get(s, 0) + 1

    # =========================================================================
    # 步驟 3：配對統計
    # =========================================================================
    total = 0
    for f in S_list:
        for ab_sum in sum_ab:
            # 需要的 cde 和 = f - ab_sum
            cde_needed = f - ab_sum
            if cde_needed in sum_cde:
                total += sum_ab[ab_sum] * sum_cde[cde_needed]

    return total


def main():
    """主函式：讀取輸入、執行計算、輸出結果"""
    import sys

    # 讀取輸入
    data = sys.stdin.read().strip().split()
    if not data:
        return

    N = int(data[0])
    S = [int(x) for x in data[1 : 1 + N]]

    # 計算並輸出結果
    result = count_six_tuples(S)
    print(result)


if __name__ == "__main__":
    main()
